function age(seconds: number): string {
  return seconds < 60
    ? `${String(seconds)} s ago`
    : seconds < 3600
      ? `${String(Math.floor(seconds / 60))} min ago`
      : `${String(Math.floor(seconds / 3600))} h ago`;
}

