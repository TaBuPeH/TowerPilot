// @ts-check
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { format, resolveConfig } from 'prettier';
import {
  familyIdentity,
  generatedFile,
  generateModule,
  writeGenerated,
} from './generate-contract.mjs';
import { loadJsonWithIdentity } from './contract-fixture.mjs';
import { HISTORY_FIXTURE_PATH } from './history-fixture.mjs';

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Same generator and backend family-hash algorithm as the Runs contract. */
export const HISTORY_DESCRIPTOR = {
  name: 'dashboard_contract_pages_v1_history',
  boundTo: /** @type {const} */ ('families'),
  families: [
    {
      key: 'cases.history_list',
      name: 'HistoryListAnswer',
      rawPath: 'answer',
      pick: ['status', 'body'],
    },
    {
      key: 'cases.history_detail',
      name: 'HistoryDetailAnswer',
      rawPath: 'answer',
      pick: ['status', 'body'],
    },
  ],
};

export async function generateHistory(check = false) {
  const { fixture } = loadJsonWithIdentity(HISTORY_FIXTURE_PATH);
  const identity = familyIdentity(HISTORY_FIXTURE_PATH, HISTORY_DESCRIPTOR);
  const file = path.basename(generatedFile(identity, HISTORY_DESCRIPTOR));
  const folder = path.join(APP, 'src/contract/generated/history');
  const generated = await generateModule(fixture, identity, HISTORY_DESCRIPTOR);
  writeGenerated(
    folder,
    [[path.join(folder, file), generated]],
    check,
    'node scripts/generate-history-contract.mjs',
  );
  const index = path.join(APP, 'src/contract/history.ts');
  const text = await format(
    `// Generated by scripts/generate-history-contract.mjs. Per-family hashes, not a whole-pages pin.\nexport { historyListAnswerSchema, historyDetailAnswerSchema } from './generated/history/${file}';`,
    { ...(await resolveConfig(path.join(APP, '.prettierrc.json'))), filepath: index },
  );
  if (check) {
    if (readFileSync(index, 'utf8') !== text) throw new Error('History contract index drift');
  } else writeFileSync(index, text);
  console.log(
    `${check ? 'Checked' : 'Generated'} history contract ${identity.sha256}\nFamilies: ${JSON.stringify(identity.families)}`,
  );
}

if (import.meta.url === pathToFileURL(path.resolve(process.argv[1] ?? '')).href)
  await generateHistory(process.argv.includes('--check'));
