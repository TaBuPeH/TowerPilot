import { existsSync, readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import type { Plugin } from 'vite';

/**
 * Writes THIRD_PARTY_NOTICES.txt next to the build: the name, version, licence
 * and full licence text of every npm package whose code is in the bundle.
 * The list comes from the bundle itself: every module with rendered code,
 * including helpers a build tool injects (Vite's modulepreload polyfill,
 * Rolldown's runtime), so it can neither miss bundled code nor list a dev-only
 * package. The build fails when bundled code has no known owner or a bundled
 * package has no licence file to copy.
 */
export const NOTICES_FILE = 'THIRD_PARTY_NOTICES.txt';

const LICENCE_FILE = /^(licen[cs]e|copying)(\.(md|txt))?$/i;

/** The package directory of a bundled module id, or null for app code and virtual modules. */
export function packageDirOf(moduleId: string): string | null {
  const clean = moduleId.replace(/^\0/, '').split('?')[0] ?? '';
  const normalized = clean.replaceAll('\\', '/');
  const marker = '/node_modules/';
  const at = normalized.lastIndexOf(marker);
  if (at < 0) {
    return null;
  }
  const rest = normalized.slice(at + marker.length).split('/');
  const first = rest[0];
  if (first === undefined || first === '') {
    return null;
  }
  const name = first.startsWith('@') ? `${first}/${rest[1] ?? ''}` : first;
  if (name.endsWith('/')) {
    return null;
  }
  return normalized.slice(0, at + marker.length) + name;
}

export interface BundledPackage {
  readonly name: string;
  readonly version: string;
  readonly license: string;
  readonly licenceText: string;
}

export function readPackage(dir: string): BundledPackage {
  const manifest = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8')) as {
    name?: unknown;
    version?: unknown;
    license?: unknown;
  };
  const name = typeof manifest.name === 'string' ? manifest.name : path.basename(dir);
  const version = typeof manifest.version === 'string' ? manifest.version : 'unknown';
  const license = typeof manifest.license === 'string' ? manifest.license : 'UNKNOWN';
  const licenceFile = readdirSync(dir).find((file) => LICENCE_FILE.test(file));
  if (licenceFile === undefined) {
    throw new Error(`${name}@${version} is bundled but ships no licence file in ${dir}`);
  }
  return {
    name,
    version,
    license,
    licenceText: readFileSync(path.join(dir, licenceFile), 'utf8').trim(),
  };
}

export function formatNotices(packages: readonly BundledPackage[]): string {
  const sorted = [...packages].sort((a, b) => a.name.localeCompare(b.name));
  const header = [
    'Third-party software bundled in the Tower Pilot dashboard app (frontend/webui/app).',
    'Generated by frontend/app/scripts/licence-notices.ts at build time.',
    '',
    ...sorted.map((pkg) => `- ${pkg.name} ${pkg.version} (${pkg.license})`),
  ];
  const bodies = sorted.map((pkg) =>
    [
      `=`.repeat(72),
      `${pkg.name} ${pkg.version} - ${pkg.license}`,
      `=`.repeat(72),
      pkg.licenceText,
    ].join('\n'),
  );
  return [...header, '', ...bodies, ''].join('\n');
}

export type BundledModule =
  | { readonly kind: 'app' }
  | { readonly kind: 'package'; readonly dir: string }
  | { readonly kind: 'unknown' };

/**
 * Who owns a module the bundle rendered: the app itself (a file under `root`
 * outside node_modules), an npm package (a file in node_modules, or a virtual
 * helper such as `\0vite/modulepreload-polyfill.js` or `\0rolldown/runtime.js`
 * that a build tool injects - its first path segment names the package), or
 * nobody known.
 */
export function classifyModule(id: string, root: string): BundledModule {
  const packageDir = packageDirOf(id);
  if (packageDir !== null) {
    return { kind: 'package', dir: packageDir };
  }
  if (id.startsWith('\0')) {
    const parts = id.slice(1).replace(/^\/+/, '').split('/');
    const first = parts[0] ?? '';
    const name = first.startsWith('@') ? `${first}/${parts[1] ?? ''}` : first;
    const dir = path.join(root, 'node_modules', name);
    if (
      /^(@[\w-][\w.-]*\/)?[\w-][\w.-]*$/.test(name) &&
      existsSync(path.join(dir, 'package.json'))
    ) {
      return { kind: 'package', dir: dir.replaceAll('\\', '/') };
    }
    return { kind: 'unknown' };
  }
  const file = path.resolve(id.split('?')[0] ?? '');
  const relative = path.relative(root, file);
  if (relative !== '' && !relative.startsWith('..') && !path.isAbsolute(relative)) {
    return { kind: 'app' };
  }
  return { kind: 'unknown' };
}

export function licenceNotices(): Plugin {
  let root = process.cwd();
  return {
    name: 'tower-pilot-licence-notices',
    apply: 'build',
    configResolved(config) {
      root = config.root;
    },
    generateBundle(_options, bundle) {
      const dirs = new Set<string>();
      const unknown: string[] = [];
      for (const output of Object.values(bundle)) {
        if (output.type !== 'chunk') {
          continue;
        }
        for (const [id, module] of Object.entries(output.modules)) {
          if (module.renderedLength === 0) {
            continue;
          }
          const owner = classifyModule(id, root);
          if (owner.kind === 'package') {
            dirs.add(owner.dir);
          } else if (owner.kind === 'unknown') {
            unknown.push(JSON.stringify(id));
          }
        }
      }
      if (unknown.length > 0) {
        throw new Error(
          `The bundle contains code with no known owner, so its licence cannot be listed: ${unknown.join(', ')}`,
        );
      }
      const packages = [...dirs].map(readPackage);
      this.emitFile({ type: 'asset', fileName: NOTICES_FILE, source: formatNotices(packages) });
    },
  };
}
