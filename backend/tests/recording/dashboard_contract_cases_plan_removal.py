"""Contract cases of what removing the day plan changes (roadmap r12d; the gap left by plan_section_delete, F6-11 brief 6.5).

ONE new family of dashboard_contract_pages_v1.json, `plan_removal_effects`, generated by the real routes (POST /api/profile-patch, GET /api/runs, GET /api/profile-src) over the
populated world of the other pages with the config's `combo` preset (the day-plan run) and the shipped readiness check. plan_section_delete records the delete and the profile
read; here the page also sees what the delete does to the run list, and what the validator refuses on the way:

  * GET /api/runs lists the `combo` run only while the profile has a plan section: removing the section removes the run (from `runs` and from `readiness`), adding the section back
    lists it again; the blueprint runs are the same before, after and after the plan is added back;
  * deleting one half of the plan (`plan.week` or `plan.days`) leaves a plan with no blocks, which the validator refuses (400, uncoded, `problems`) - the page offers the removal of
    the whole section instead; the refusal writes nothing and the run list does not change;
  * with the section gone, deleting `plan.week` is refused the same way (the route builds an empty plan to delete from).

Not recorded: GET /api/schedule/status. It reports the running scheduler's last observation, and in the synthetic world it stayed `available` with the same observed winner
after the plan was removed (probed, one world); it changes when the scheduler observes again, which no route here triggers.
"""
import copy

from dashboard_contract_cases_profile import PATCH_URL
from dashboard_contract_pages_world import PLAN, populate
from test_dashboard_contract import real_readiness, requirements

PRE = 'plan_removal_effects'
COMBO = {'label': 'Combo (day plan)', 'runner': 'scheduling/combo.py', 'tier': 1}
NO_BLOCKS = 'plan: a plan with no blocks schedules nothing - remove the plan section to use the legacy constants, or add blocks'
BLUEPRINTS = ['bp_farm', 'bp_farm_deep', 'bp_shards', 'bp_tourney']


def runs(w, case):
    return w.get(PRE, case, '/api/runs').get_json()


def source(w, case=None):
    reply = w.get(PRE, case, '/api/profile-src/mine') if case else w.client.get('/api/profile-src/mine')
    return reply.get_json()


def plan_removal_effects_cases(gen):
    with gen.world('pre_effects') as w:
        real_readiness(w)
        populate(w, config=lambda cfg: cfg.setdefault('presets', {}).update(combo=copy.deepcopy(COMBO)))
        requirements(w, {})
        before = runs(w, 'read_runs_before_the_removal_the_day_plan_run_is_listed')
        assert sorted(before['runs']) == sorted(BLUEPRINTS + ['combo']) and before['runs']['combo'] == COMBO, sorted(before['runs'])
        assert before['readiness']['combo'] == {'advisory': [], 'details': [], 'missing': [], 'ready': True}, before['readiness']['combo']
        profile = source(w, 'read_profile_before_the_removal')
        assert profile['profile']['plan'] == PLAN and profile['problems'] == []
        revision = profile['revision']
        for part in ('week', 'days'):
            refused = w.post(PRE, f'plan_{part}_deleted_is_refused_a_plan_with_no_blocks', PATCH_URL,
                             dict(name='mine', path=['plan', part], op='delete', expected_revision=revision))
            body = refused.get_json()
            assert refused.status_code == 400 and body['ok'] is False and body['error'] == NO_BLOCKS and body['problems'] == [NO_BLOCKS] and 'code' not in body, body
        assert source(w)['revision'] == revision, 'a refused delete changed the profile'
        assert runs(w, 'read_runs_after_the_refusals_nothing_changed') == before
        removed = w.post(PRE, 'plan_section_removed', PATCH_URL, dict(name='mine', path=['plan'], op='delete', expected_revision=revision))
        assert removed.status_code == 200 and 'plan' not in removed.get_json()['profile'] and removed.get_json()['revision'] != revision, removed.get_json()
        after = runs(w, 'read_runs_after_the_removal_the_day_plan_run_is_gone')
        assert sorted(after['runs']) == BLUEPRINTS and sorted(after['readiness']) == BLUEPRINTS, (sorted(after['runs']), sorted(after['readiness']))
        assert after['runs'] == {name: before['runs'][name] for name in BLUEPRINTS} and after['readiness'] == {name: before['readiness'][name] for name in BLUEPRINTS}
        gone = source(w, 'read_profile_after_the_removal')
        assert 'plan' not in gone['profile'] and gone['problems'] == [] and gone['revision'] == removed.get_json()['revision']
        again = w.post(PRE, 'plan_week_deleted_when_the_plan_is_gone_is_refused_the_same_way', PATCH_URL,
                       dict(name='mine', path=['plan', 'week'], op='delete', expected_revision=gone['revision']))
        assert again.status_code == 400 and again.get_json()['problems'] == [NO_BLOCKS], again.get_json()
        assert source(w)['revision'] == gone['revision']
        added = w.post(PRE, 'plan_section_added_back', PATCH_URL, dict(name='mine', path=['plan'], value=copy.deepcopy(PLAN), expected_revision=gone['revision']))
        assert added.status_code == 200 and added.get_json()['profile']['plan'] == PLAN, added.get_json()
        assert runs(w, 'read_runs_after_the_plan_was_added_back_the_day_plan_run_is_listed') == before
