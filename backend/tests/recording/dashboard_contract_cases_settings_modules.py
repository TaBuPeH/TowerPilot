"""Contract cases of the typed settings modules for the machine and emulator defaults, and of the manual restore values (roadmap r12b / F6-15).

They are appended to two families whose cases are published: `settings` (the seven modules instance-defaults, active-instance, run-defaults,
tournament-cards, loop-defaults, missions-defaults, fleet-defaults: saved, stale revision, the read after the save; ten invalid values; the
configuration read after switching the selected emulator) and `loadout_patch` (cards_restore and modules_restore: saved, refused, the read after
the save). Generated by the real routes over the synthetic worlds of the other settings and equipment families; nothing here is a hand-written answer.

What the routes do (read from the source, then recorded):
  * POST /api/settings is compare-and-set on the revision of config.yaml + the active profile and on the {instance, account, profile} context; a stale
    revision or context is 409 whatever the values are. Every value is validated before any is written, so one invalid field changes none.
  * the machine defaults loop-defaults, missions-defaults and fleet-defaults write the ROOT blocks `loop`, `missions`, `fleet`; the modules loop,
    missions and fleet keep writing the selected emulator's override. Saving a default never creates or replaces an override.
  * instance-defaults writes instances.<selected>.label | preset | autostart (an empty preset means "use the machine fallback"); run-defaults writes
    the root `preset`. Both offer only runnable presets (a placeholder with `defined: false` is not a choice).
  * tournament-cards writes `tourney_card_tweaks` (string lists, ordered, nothing coerced). With an account bound to the selected emulator the lists
    are the ACCOUNT's (accounts.<id>.tourney_card_tweaks); the root block stays the legacy default.
  * active-instance selects another emulator. It is a selection-only write: the stored configuration differs from before in `active_instance` and
    nothing else, so no account record changes, whatever it stores (accounts.persist, which fills in a sparse record's defaults, is not run); the
    answer is the settings snapshot of the new context. settings_switch_records records the same switch over SPARSE accounts.
  * the restore values are two keys of a loadout body, validated like `cards` and `modules`: a card preset the account owns, a module it has. The
    validator reads only the loadouts a run of the ACTIVE profile names, so the route refuses (409 `restore_loadout_unused`, nothing written) a
    body that sets, changes or clears a restore key of any other loadout, or when there is no active profile: loadout_restore_eligibility.
"""
import copy

import yaml

from dashboard_contract_cases_context import page_context
from dashboard_contract_cases_editors import LOADOUTS, config_of, equipped, loadout
from dashboard_contract_cases_profile import write_profile
from dashboard_contract_cases_settings import module_of, save, snapshot, submit
from dashboard_contract_pages_world import populate

SM, LR = 'settings_modules', 'loadout_restore'      # new families: appended after every published one, so no published family changes (the case names are the brief's)
LE, SR = 'loadout_restore_eligibility', 'settings_switch_records'     # r12b2 (review R1, R2): appended after settings_modules and loadout_restore, which keep their bytes

# the account of alpha (selected emulator `main`) and beta (emulator `other`): different profile, loadouts and tournament tweaks, and legacy defaults
ACCOUNTS = {
    'alpha': {'label': 'Alpha', 'active_profile': 'mine', 'profiles': ['mine'], 'loadouts': {'alpha_farm': {}},
              'tourney_card_tweaks': {'drop': ['alpha_drop'], 'add': []}},
    'beta': {'label': 'Beta', 'active_profile': 'theirs', 'profiles': ['theirs'], 'loadouts': {'beta_farm': {}},
             'tourney_card_tweaks': {'drop': [], 'add': ['beta_add']}}}


def bound(cfg):
    cfg['accounts'] = copy.deepcopy(ACCOUNTS)
    cfg['instances']['main'].update(account='alpha', label='Alpha tower')
    cfg['instances']['other'].update(account='beta', label='Beta tower')
    cfg['loadouts'] = {'legacy_farm': {}}
    cfg['tourney_card_tweaks'] = {'drop': ['legacy_drop'], 'add': []}
    cfg['presets'] = {'normal_run': {'label': 'High Tier'}, 'coin_farm': {'label': 'Coin Farm'}, 'later': {'defined': False}}
    cfg['preset'] = 'normal_run'


def furnished(w):
    """The populated account with two bound emulators, plus beta's profile file."""
    profile = populate(w, config=bound)
    (w.root / 'profiles' / 'theirs.yaml').write_text(yaml.safe_dump(profile, sort_keys=False), encoding='utf-8')


def stored(w):
    return yaml.safe_load((w.root / 'config.yaml').read_text(encoding='utf-8'))


def must(condition, detail=None):
    assert condition, detail
    return True


def slug(module):
    return module.replace('-', '_').replace(':', '_')


def without_backup(reply):
    return {key: value for key, value in reply.items() if key != 'backup'}


def round_of(w, module, values, other, check):
    """Save `values`, read, then repeat the save with the revision this one replaced (stale) and show nothing changed."""
    old = snapshot(w)
    reply = save(w, 'saved_' + slug(module), old, module, values, SM)
    held = module_of(reply, module)
    for key, value in values.items():
        assert next(f for f in held['fields'] if f['key'] == key)['value'] == value, (module, key)
    check(stored(w))
    read = snapshot(w, 'read_after_saved_' + slug(module), SM)
    assert read == without_backup(reply), module
    before = (w.root / 'config.yaml').read_bytes()
    stale = submit(w, 'stale_revision_' + slug(module), old, module, other, expect=409, family=SM).get_json()
    assert stale['ok'] is False and (w.root / 'config.yaml').read_bytes() == before, module
    assert snapshot(w) == read


def settings_module_cases(gen):
    with gen.world('set_mod_defaults') as w:
        furnished(w)
        base = snapshot(w)
        runnable = [o['value'] for o in module_of(base, 'run-defaults')['fields'][0]['options']]
        assert len(runnable) >= 2 and module_of(base, 'instance-defaults')['fields'][1]['options'][0] == {'value': '', 'label': 'Use machine fallback'}, runnable
        fallback = next(name for name in runnable if name != module_of(base, 'run-defaults')['fields'][0]['value'])
        round_of(w, 'instance-defaults', {'label': 'Tower one', 'preset': runnable[0], 'autostart': True}, {'label': 'Stale'},
                 lambda cfg: must(all(cfg['instances']['main'][k] == v for k, v in (('label', 'Tower one'), ('preset', runnable[0]), ('autostart', True)))
                                  and 'autostart' not in cfg['instances']['other'] and cfg['instances']['other']['label'] == 'Beta tower', cfg['instances']))
        round_of(w, 'run-defaults', {'preset': fallback}, {'preset': runnable[0]}, lambda cfg: must(cfg['preset'] == fallback, cfg['preset']))
        round_of(w, 'tournament-cards', {'drop': ['cash', 'extra_orb'], 'add': ['golden_orb']}, {'drop': []},
                 lambda cfg: must(cfg['accounts']['alpha']['tourney_card_tweaks'] == {'drop': ['cash', 'extra_orb'], 'add': ['golden_orb']}
                                  and cfg['accounts']['beta']['tourney_card_tweaks'] == ACCOUNTS['beta']['tourney_card_tweaks']
                                  and cfg['tourney_card_tweaks'] == {'drop': ['legacy_drop'], 'add': []}, cfg))
        round_of(w, 'loop-defaults', {'fps': 3.5, 'dry_run': True}, {'fps': 4}, lambda cfg: must(cfg['loop'] == {'fps': 3.5, 'dry_run': True}, cfg['loop']))
        round_of(w, 'missions-defaults', {'visit_delay_sec': [90, 450]}, {'visit_delay_sec': [10, 20]},
                 lambda cfg: must(cfg['missions'] == {'visit_delay_sec': [90, 450]}, cfg['missions']))
        round_of(w, 'fleet-defaults', {'hold_window': 120, 'post_window': 175}, {'hold_window': 1},
                 lambda cfg: must((cfg['fleet']['hold_window'], cfg['fleet']['post_window']) == (120, 175), cfg['fleet']))
        assert 'loop' not in stored(w)['instances']['main'] and 'missions' not in stored(w)['instances']['main']     # no override was created
    with gen.world('set_mod_switch') as w:
        furnished(w)
        before = stored(w)
        old = snapshot(w)
        assert old['context'] == {'instance': 'main', 'account': 'alpha', 'profile': 'mine'}
        reply = save(w, 'saved_active_instance', old, 'active-instance', {'active_instance': 'other'}, SM)
        after = stored(w)
        assert after['active_instance'] == 'other' and after['accounts'] == before['accounts'], after['accounts']
        assert all(after[key] == before[key] for key in ('loadouts', 'tourney_card_tweaks', 'active_profile', 'instances')), 'legacy defaults changed'
        assert reply['context'] == {'instance': 'other', 'account': 'beta', 'profile': 'theirs'}
        read = snapshot(w, 'read_after_saved_active_instance', SM)
        assert read == without_backup(reply) and module_of(read, 'active-instance')['fields'][0]['value'] == 'other'
        config = w.get(SM, 'read_config_after_saved_active_instance', '/api/config').get_json()
        assert (config['active_instance'], config['active_profile'], config['loadouts']) == ('other', 'theirs', {'beta_farm': {}}), config
        assert config['accounts'] == before['accounts']
        stale = submit(w, 'stale_revision_active_instance', old, 'active-instance', {'active_instance': 'main'}, expect=409, family=SM).get_json()
        assert stale['ok'] is False and stored(w) == after


INVALID = [
    ('invalid_string_instance_defaults', 'instance-defaults', {'label': 7}),
    ('invalid_enum_instance_defaults', 'instance-defaults', {'preset': 'ghost'}),
    ('invalid_boolean_instance_defaults', 'instance-defaults', {'autostart': 'true'}),
    ('invalid_enum_active_instance', 'active-instance', {'active_instance': 'ghost'}),
    ('invalid_enum_run_defaults', 'run-defaults', {'preset': 'ghost'}),
    ('invalid_string_list_tournament_cards', 'tournament-cards', {'drop': ['cash'], 'add': [1]}),
    ('invalid_number_loop_defaults', 'loop-defaults', {'fps': 'fast'}),
    ('invalid_boolean_loop_defaults', 'loop-defaults', {'dry_run': 1}),
    ('invalid_range_missions_defaults', 'missions-defaults', {'visit_delay_sec': [600, 60]}),
    ('invalid_integer_fleet_defaults', 'fleet-defaults', {'hold_window': 1.5}),
]


def settings_module_refusals(gen):
    with gen.world('set_mod_invalid') as w:
        furnished(w)
        snap = snapshot(w)
        before = (w.root / 'config.yaml').read_bytes()
        for case, module, values in INVALID:
            reply = submit(w, case, snap, module, values, expect=400, family=SM).get_json()
            assert reply['ok'] is False and reply['error'], case
            assert (w.root / 'config.yaml').read_bytes() == before, case              # nothing was written, not even the valid half of a request
        assert snapshot(w) == snap


def restore_cases(gen):
    with gen.world('lo_restore') as w:
        equipped(w)
        context = page_context(w)
        revision = config_of(w)['config_revision']
        cards = {'cards': 'main_farm', 'cards_restore': 'no_card'}
        reply = loadout(w, 'saved_cards_restore', 'plain', cards, revision, expect=200, expected_context=context, family=LR).get_json()
        assert reply['ok'] and reply['loadouts']['plain'] == cards and reply['config_revision'] != revision
        read = w.get(LR, 'read_after_saved_cards_restore', '/api/config').get_json()
        assert read['loadouts']['plain'] == cards and read['config_revision'] == reply['config_revision']
        refused = loadout(w, 'refused_cards_restore', 'plain', dict(cards, cards_restore='ghost_deck'), read['config_revision'], expect=400, expected_context=context, family=LR).get_json()
        assert refused['ok'] is False and 'cards_restore' in refused['error'] and config_of(w)['config_revision'] == read['config_revision']
        modules = dict(cards, modules=[['amplifying_strike', 'primary']], modules_restore=[['black_hole_digestor', 'assist']])
        reply = loadout(w, 'saved_modules_restore', 'plain', modules, read['config_revision'], expect=200, expected_context=context, family=LR).get_json()
        assert reply['ok'] and reply['loadouts']['plain'] == modules
        read = w.get(LR, 'read_after_saved_modules_restore', '/api/config').get_json()
        assert read['loadouts']['plain'] == modules and read['config_revision'] == reply['config_revision']
        refused = loadout(w, 'refused_modules_restore', 'plain', dict(modules, modules_restore=[['ghost_module', 'assist']]), read['config_revision'], expect=400, expected_context=context, family=LR).get_json()
        assert refused['ok'] is False and 'ghost_module' in refused['error'] and config_of(w)['loadouts']['plain'] == modules


def settings_modules_cases(gen):
    settings_module_cases(gen)
    settings_module_refusals(gen)
    restore_cases(gen)


# ------------------------------------------------------------------------------------------------ r12b2 / review R1: who may edit a restore value
GHOST_CARDS = {'cards': 'no_card', 'cards_restore': 'ghost_deck'}
OWNED_CARDS = {'cards': 'no_card', 'cards_restore': 'main_farm'}
GHOST_MODULES = {'cards': 'no_card', 'modules_restore': [['ghost_module', 'assist']]}
OWNED_MODULES = {'cards': 'no_card', 'modules_restore': [['black_hole_digestor', 'assist']]}


def refused_unused(w, case, name, body, revision, context, keys, active):
    """One restore edit the route refuses: 409 restore_loadout_unused, naming the loadout, the keys and the active profile; config.yaml is untouched."""
    reply = loadout(w, case, name, body, revision, expect=409, expected_context=context, family=LE).get_json()
    assert reply['ok'] is False and reply['code'] == 'restore_loadout_unused', reply
    assert (reply['loadout'], reply['restore_keys'], reply['active_profile']) == (name, keys, active) and reply['error'], reply
    assert config_of(w)['config_revision'] == revision, (case, 'a refused restore edit changed config.yaml')
    return reply


def restore_eligibility_cases(gen):
    with gen.world('lo_restore_unused') as w:
        equipped(w)                                  # the active profile `mine` names plain (and as_is); the loadout `spare` is named by no run
        context, revision = page_context(w), config_of(w)['config_revision']
        refused_unused(w, 'refused_unknown_cards_restore_on_a_loadout_no_run_uses', 'spare', GHOST_CARDS, revision, context, ['cards_restore'], 'mine')
        refused_unused(w, 'refused_owned_cards_restore_on_a_loadout_no_run_uses', 'spare', OWNED_CARDS, revision, context, ['cards_restore'], 'mine')
        refused_unused(w, 'refused_unknown_modules_restore_on_a_loadout_no_run_uses', 'spare', GHOST_MODULES, revision, context, ['modules_restore'], 'mine')
        refused_unused(w, 'refused_owned_modules_restore_on_a_loadout_no_run_uses', 'spare', OWNED_MODULES, revision, context, ['modules_restore'], 'mine')
        refused_unused(w, 'refused_both_restore_values_on_a_loadout_no_run_uses', 'spare', dict(GHOST_CARDS, **GHOST_MODULES), revision, context,
                       ['cards_restore', 'modules_restore'], 'mine')
        read = w.get(LE, 'read_after_the_refusals_nothing_changed', '/api/config').get_json()
        assert read['config_revision'] == revision and read['loadouts']['spare'] == LOADOUTS['spare'], read['loadouts']
        plain = loadout(w, 'unused_loadout_saved_without_restore_values_is_unchanged_behaviour', 'spare', {'cards': 'main_farm'}, revision, expect=200,
                        expected_context=context, family=LE).get_json()
        assert plain['loadouts']['spare'] == {'cards': 'main_farm'} and plain['config_revision'] != revision
        stale = loadout(w, 'stale_revision_is_judged_before_the_restore_guard', 'spare', GHOST_CARDS, revision, expect=409, expected_context=context, family=LE).get_json()
        assert stale['code'] == 'revision_conflict' and stale['config_revision'] == plain['config_revision']
        used = loadout(w, 'owned_cards_restore_saved_on_the_loadout_the_active_profile_uses', 'plain', dict(OWNED_CARDS, cards='main_farm', cards_restore='no_card'),
                       plain['config_revision'], expect=200, expected_context=context, family=LE).get_json()
        assert used['ok'] and used['loadouts']['plain']['cards_restore'] == 'no_card'
    with gen.world('lo_restore_inactive') as w:
        equipped(w)
        profile = w.client.get('/api/profile-src/mine').get_json()['profile']
        profile['blueprints'] = {name: dict(run, loadout='spare') for name, run in profile['blueprints'].items()}
        write_profile(w, 'elsewhere', profile)       # a profile of this machine that DOES name spare - but it is not the active one
        context, revision = page_context(w), config_of(w)['config_revision']
        refused_unused(w, 'refused_restore_when_only_an_inactive_profile_names_the_loadout', 'spare', OWNED_MODULES, revision, context, ['modules_restore'], 'mine')
    with gen.world('lo_restore_stored') as w:
        equipped(w, loadouts=dict(LOADOUTS, spare={'cards': 'no_card', 'cards_restore': 'ghost_deck'}))      # a restore value saved before the route checked who may
        context, revision = page_context(w), config_of(w)['config_revision']
        kept = loadout(w, 'unused_loadout_saved_with_its_stored_restore_value_unchanged', 'spare', {'cards': 'main_farm', 'cards_restore': 'ghost_deck'}, revision,
                       expect=200, expected_context=context, family=LE).get_json()
        assert kept['loadouts']['spare'] == {'cards': 'main_farm', 'cards_restore': 'ghost_deck'}
        refused_unused(w, 'refused_clearing_the_stored_restore_value_of_a_loadout_no_run_uses', 'spare', {'cards': 'main_farm'}, kept['config_revision'], context,
                       ['cards_restore'], 'mine')
        held = w.get(LE, 'read_after_the_clearing_refusal_the_stored_value_remains', '/api/config').get_json()
        assert held['loadouts']['spare'] == {'cards': 'main_farm', 'cards_restore': 'ghost_deck'}
    with gen.world('lo_restore_no_profile') as w:
        equipped(w)
        w.edit_config(lambda cfg: cfg.update(active_profile=None))
        context, revision = page_context(w), config_of(w)['config_revision']
        assert context['profile'] is None
        reply = refused_unused(w, 'refused_restore_with_no_active_profile_nothing_to_check_it_against', 'plain', OWNED_CARDS, revision, context, ['cards_restore'], None)
        assert 'no active profile' in reply['error']
        w.get(LE, 'read_after_the_no_profile_refusal_nothing_changed', '/api/config')


# ------------------------------------------------------------------------------------------------ r12b2 / review R2: a selection writes only the selection
SPARSE_ACCOUNTS = {
    'alpha': {'label': 'Alpha', 'active_profile': 'mine', 'profiles': ['mine', 'archive']},          # no loadouts, no tweaks, a profile list nobody sorted
    'beta': {'label': 'Beta', 'active_profile': 'theirs'}}                                              # no profile list either


def switch_records_cases(gen):
    with gen.world('set_switch_sparse') as w:
        furnished(w)
        w.edit_config(lambda cfg: cfg.__setitem__('accounts', copy.deepcopy(SPARSE_ACCOUNTS)))
        before = stored(w)
        assert before['accounts'] == SPARSE_ACCOUNTS and 'loadouts' not in before['accounts']['alpha']
        first = save(w, 'saved_active_instance_between_sparse_accounts', snapshot(w), 'active-instance', {'active_instance': 'other'}, SR)
        after = stored(w)
        assert after == dict(before, active_instance='other'), 'the switch wrote more than the selection'
        assert yaml.safe_dump(after['accounts']['alpha']) == yaml.safe_dump(before['accounts']['alpha']), 'the old emulator\'s account record changed'
        assert first['context'] == {'instance': 'other', 'account': 'beta', 'profile': 'theirs'}
        read = snapshot(w, 'read_after_the_sparse_switch', SR)
        assert read == without_backup(first)
        config = w.get(SR, 'read_config_after_the_sparse_switch', '/api/config').get_json()
        assert config['accounts'] == SPARSE_ACCOUNTS and config['active_instance'] == 'other', config['accounts']
        back = save(w, 'saved_active_instance_back_to_the_first_sparse_account', read, 'active-instance', {'active_instance': 'main'}, SR)
        assert stored(w) == before and back['context'] == {'instance': 'main', 'account': 'alpha', 'profile': 'mine'}
        config = w.get(SR, 'read_config_after_switching_back_every_record_as_it_was', '/api/config').get_json()
        assert config['accounts'] == SPARSE_ACCOUNTS, config['accounts']


def settings_switch_records_cases(gen):
    switch_records_cases(gen)


def loadout_restore_eligibility_cases(gen):
    restore_eligibility_cases(gen)
