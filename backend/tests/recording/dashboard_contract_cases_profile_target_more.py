"""Contract cases of editing an INACTIVE profile that the profile_target family left out (roadmap r12e; the open recording requests of the F6-14 reports).

ONE new family of dashboard_contract_pages_v1.json, `profile_target_more`, generated by the real routes over the world of profile_target (alpha on main / fake:1, profile
`mine` in force, `second` beside it, `theirs` owned by beta). profile_target recorded the saves of an inactive target; the UI author listed what it could not bind to a real
answer, and each item is here:

  Schedule      the whole day plan of the inactive profile removed, with the read that follows, the delete of an absent section, the refusal to delete one half, a stale revision,
                a context that changed;
  Abilities     an unused Ultimate Weapon policy and an unused rescue policy deleted, the same deletes refused while a run of the inactive profile uses the policy, and a rescue
                policy's rules put in another order (as a whole policy, which is what the page sends, and by the rules subpath);
  Runs entry    every field of a run the Runs page can save, delete or be refused (the same lists the active profile's run_entry_patch family replays: ENTRY_SAVES, ENTRY_DELETES, a
                set of ENTRY_REFUSALS), sent for `second` with expected_context and expected_revision, then a stale revision and a changed account;
  Read failure  GET /api/profile-files that fails (500, the default page of an unhandled exception) and the inactive target whose source cannot be read: the list still names it
                and calls it patchable, the source read answers 400 with the parser's text or "is not a mapping", and a patch of it (even with its true revision) is that same 400.

Every request that writes carries {name: 'second', path, value | op: 'delete', expected_context: E, expected_revision: R} exactly as profile_target's do (a delete has no `value`). The
generator asserts, for every group, that the active profile `mine` and config.yaml are byte-identical afterwards.
"""
import copy
import hashlib

from dashboard_contract_cases_context import page_context, switch_to_beta
from dashboard_contract_cases_editors import RESCUE, RESCUE_POLICIES, UW
from dashboard_contract_cases_profile_target import PATCH_URL, PLAN, UW_CALM, source, target_world
from dashboard_contract_cases_run_leftovers import ENTRY_DELETE_REFUSALS, ENTRY_DELETES, ENTRY_REFUSALS, ENTRY_SAVES, add_dissonance_run
from dashboard_contract_pages_world import pin_mtimes
from test_dashboard_contract import raising

PM = 'profile_target_more'
# the refusals of the run-entry validator worth binding to the inactive route: one per kind of refusal (the rest are the validator's own and equal the active profile's)
REFUSED_RUN_FIELDS = ('loadout_unknown_equipment', 'loadout_as_is_on_a_tournament_run', 'tier_zero', 'tier_text', 'dissonant_tab_unknown', 'perk_bans_thirty_one_entries',
                      'gem_cap_negative', 'count_on_a_coin_run_names_the_alternative', 'gathering_policy_unknown', 'field_not_legal_for_a_coin_run')


def read(w, case, name='second', family=PM):
    return w.get(family, case, f'/api/profile-src/{name}').get_json()


def revision_of(w, name='second'):
    return source(w, name).get_json()['revision']


def send(w, case, path, *, value=None, delete=False, name='second', context=None, revision=None, expect, family=PM):
    """The patch the page sends for the profile it chose to edit: {name, path, value | op:'delete', expected_context, expected_revision}."""
    body = dict(name=name, path=path, expected_context=page_context(w) if context is None else context, expected_revision=revision_of(w, name) if revision is None else revision)
    if delete:
        body['op'] = 'delete'
    else:
        body['value'] = value
    reply = w.post(family, case, PATCH_URL, body)
    assert reply.status_code == expect, (case, reply.status_code, reply.get_json())
    return reply.get_json()


def earlier(w, path, value):
    """What the page did before the case starts (not recorded: the save is profile_target's, the case is what follows it)."""
    body = dict(name='second', path=path, value=value, expected_context=page_context(w), expected_revision=revision_of(w))
    assert w.plain_post(PATCH_URL, body).status_code == 200, path


def untouched(w, snapshot):
    """Whatever was written, it was written to `second`: the active profile and config.yaml are byte-identical."""
    mine, config = snapshot
    assert (w.root / 'profiles' / 'mine.yaml').read_bytes() == mine and (w.root / 'config.yaml').read_bytes() == config, 'a write to second touched another file'


def snapshot_of(w):
    return (w.root / 'profiles' / 'mine.yaml').read_bytes(), (w.root / 'config.yaml').read_bytes()


def schedule_cases(gen):
    with gen.world('ptm_schedule') as w:
        target_world(w)
        snapshot = snapshot_of(w)
        before = read(w, 'read_before_the_inactive_plan_is_removed')
        assert before['profile']['plan']['week'] and before['problems'] == []
        half = send(w, 'inactive_plan_week_deleted_is_refused_a_plan_with_no_blocks', ['plan', 'week'], delete=True, expect=400)
        assert half['ok'] is False and 'schedules nothing' in half['error'] and half['problems'] == [half['error']] and 'code' not in half, half
        assert revision_of(w) == before['revision'], 'a refused delete changed the profile'
        removed = send(w, 'inactive_plan_deleted', ['plan'], delete=True, expect=200)
        assert removed['ok'] is True and 'plan' not in removed['profile'] and removed['revision'] != before['revision'] and removed['warnings'] == [], removed
        after = read(w, 'read_after_the_inactive_plan_was_removed')
        assert 'plan' not in after['profile'] and after['revision'] == removed['revision'] and after['problems'] == [] and after['profile'] == removed['profile']
        again = send(w, 'inactive_plan_delete_when_the_section_is_already_gone', ['plan'], delete=True, expect=200)
        assert again['revision'] == removed['revision'] and 'plan' not in again['profile'], 'deleting what is absent must not rewrite the file'
        active = read(w, 'read_the_active_profile_after_the_inactive_plan_was_removed', 'mine')
        assert active['profile']['plan'] == before['profile']['plan'], 'the active profile lost its plan'
        untouched(w, snapshot)
    with gen.world('ptm_schedule_refused') as w:
        target_world(w)
        snapshot = snapshot_of(w)
        e, r = page_context(w), revision_of(w)
        assert w.plain_post(PATCH_URL, dict(name='second', path=['plan', 'week', 'sunday'], value='tourney_day', expected_revision=r)).status_code == 200      # another client saved first
        stale = send(w, 'inactive_plan_delete_stale_revision_409', ['plan'], delete=True, revision=r, expect=409)
        assert stale['code'] == 'revision_conflict' and stale['revision'] != r, stale
        kept = read(w, 'read_after_the_stale_delete_the_plan_remains')
        assert 'plan' in kept['profile'] and kept['revision'] == stale['revision']
        switch_to_beta(w)
        moved = send(w, 'inactive_plan_delete_refused_after_account_switch', ['plan'], delete=True, context=e, revision=kept['revision'], expect=409)
        assert moved['code'] == 'context_changed' and moved['current_context']['account'] == 'beta', moved
        assert 'plan' in source(w).get_json()['profile'], 'a refused delete removed the plan'
        assert (w.root / 'profiles' / 'mine.yaml').read_bytes() == snapshot[0]


def abilities_cases(gen):
    with gen.world('ptm_abilities') as w:
        target_world(w)
        snapshot = snapshot_of(w)
        earlier(w, UW + ['calm'], UW_CALM)
        earlier(w, RESCUE + ['extra'], copy.deepcopy(RESCUE_POLICIES['any_falling']))
        before = read(w, 'read_before_the_inactive_policies_are_deleted')
        assert {'calm', 'farm_cl'} <= set(before['profile']['policies']['uw_policies']) and {'extra', 'wall_drain'} <= set(before['profile']['policies']['rescue_policies'])
        used = {run['policies'].get('uw') for run in before['profile']['blueprints'].values()} | {run['policies'].get('rescue') for run in before['profile']['blueprints'].values()}
        assert 'farm_cl' in used and 'wall_drain' in used and 'calm' not in used and 'extra' not in used
        in_use = [('inactive_uw_policy_deleted_while_a_run_uses_it_is_refused', UW + ['farm_cl'], 'farm_cl'),
                  ('inactive_rescue_policy_deleted_while_a_run_uses_it_is_refused', RESCUE + ['wall_drain'], 'wall_drain')]
        for case, path, policy in in_use:
            refused = send(w, case, path, delete=True, expect=400)
            assert refused['ok'] is False and f"unknown policy '{policy}'" in refused['error'] and refused['problems'] == [refused['error']] and 'code' not in refused, refused
        held = read(w, 'read_after_the_in_use_deletes_were_refused_nothing_changed')
        assert held['revision'] == before['revision'] and held['profile'] == before['profile']
        uw = send(w, 'inactive_unused_uw_policy_deleted', UW + ['calm'], delete=True, expect=200)
        assert 'calm' not in uw['profile']['policies']['uw_policies'] and uw['revision'] != before['revision']
        rescue = send(w, 'inactive_unused_rescue_policy_deleted', RESCUE + ['extra'], delete=True, expect=200)
        assert 'extra' not in rescue['profile']['policies']['rescue_policies']
        after = read(w, 'read_after_the_unused_policies_were_deleted')
        assert after['revision'] == rescue['revision'] and set(after['profile']['policies']['uw_policies']) == {'farm_cl', 'tourney_cl'} and after['problems'] == []
        policy = copy.deepcopy(after['profile']['policies']['rescue_policies']['wall_drain'])
        order = lambda rules: [next(iter(rule['do'])) + ':' + next(iter(rule['when'])) for rule in rules]
        was = order(policy['rules'])
        whole = send(w, 'inactive_rescue_policy_saved_with_its_rules_in_another_order', RESCUE + ['wall_drain'], value=dict(policy, rules=[policy['rules'][2], policy['rules'][0], policy['rules'][1]]), expect=200)
        now = order(whole['profile']['policies']['rescue_policies']['wall_drain']['rules'])
        assert now == [was[2], was[0], was[1]] and now != was, (was, now)
        reordered = read(w, 'read_after_the_inactive_rescue_rules_were_reordered_as_a_whole_policy')
        assert order(reordered['profile']['policies']['rescue_policies']['wall_drain']['rules']) == now and reordered['problems'] == []
        rules = copy.deepcopy(reordered['profile']['policies']['rescue_policies']['wall_drain']['rules'])
        sub = send(w, 'inactive_rescue_rules_reordered_by_the_rules_subpath', RESCUE + ['wall_drain', 'rules'], value=list(reversed(rules)), expect=200)
        assert order(sub['profile']['policies']['rescue_policies']['wall_drain']['rules']) == list(reversed(now))
        read(w, 'read_after_the_inactive_rescue_rules_were_reordered_by_the_subpath')
        untouched(w, snapshot)


def run_entry_cases(gen):
    refused = {case: (run, fields, value) for run, case, fields, value in ENTRY_REFUSALS}
    assert set(REFUSED_RUN_FIELDS) <= set(refused), sorted(set(REFUSED_RUN_FIELDS) - set(refused))
    with gen.world('ptm_entry') as w:
        target_world(w, mutate=add_dissonance_run)
        snapshot = snapshot_of(w)
        before = read(w, 'read_before_the_first_inactive_run_entry_save')
        assert set(before['profile']['blueprints']) == {'farm', 'farm_deep', 'shards', 'tourney', 'dissonance'} and before['problems'] == []
        for run, case, fields, value in ENTRY_SAVES:
            reply = send(w, f'inactive_{case}', ['blueprints', run, *fields], value=value, expect=200)
            assert reply['ok'] is True, case
        for run, case, fields in ENTRY_DELETES:
            send(w, f'inactive_{case}', ['blueprints', run, *fields], delete=True, expect=200)
        held = read(w, 'read_after_the_inactive_run_entry_saves_holds_every_change')
        runs = held['profile']['blueprints']
        assert held['problems'] == [] and runs['farm']['label'] == 'Daily coin farm' and runs['farm']['tier'] == 2 and 'uw' not in runs['farm']['policies']
        assert runs['dissonance']['dissonant_tab'] == 'defense' and runs['tourney']['gem_entry_max'] == 0 and runs['shards']['count'] == 0
        untouched(w, snapshot)
    with gen.world('ptm_entry_refused') as w:
        target_world(w, mutate=add_dissonance_run)
        snapshot = snapshot_of(w)
        revision = revision_of(w)
        for case in REFUSED_RUN_FIELDS:
            run, fields, value = refused[case]
            reply = send(w, f'inactive_{case}_is_refused', ['blueprints', run, *fields], value=value, expect=400)
            assert reply['ok'] is False and reply['problems'] and reply['error'] == reply['problems'][0] and 'code' not in reply, (case, reply)
        for run, case, fields in ENTRY_DELETE_REFUSALS:
            reply = send(w, f'inactive_{case}_is_refused', ['blueprints', run, *fields], delete=True, expect=400)
            assert reply['problems'], case
        assert revision_of(w) == revision, 'a refused patch changed the inactive profile'
        read(w, 'read_after_the_inactive_run_entry_refusals_nothing_changed')
        untouched(w, snapshot)
    with gen.world('ptm_entry_fences') as w:
        target_world(w, mutate=add_dissonance_run)
        e, r = page_context(w), revision_of(w)
        assert w.plain_post(PATCH_URL, dict(name='second', path=['blueprints', 'farm', 'label'], value='Saved by another client', expected_revision=r)).status_code == 200
        stale = send(w, 'inactive_run_entry_stale_revision_409', ['blueprints', 'farm', 'tier'], value=3, revision=r, expect=409)
        assert stale['code'] == 'revision_conflict' and stale['revision'] != r, stale
        send(w, 'inactive_run_entry_stale_revision_is_judged_before_the_values', ['blueprints', 'farm', 'tier'], value=0, revision=r, expect=409)
        current = read(w, 'read_after_the_stale_run_entry_refusals_holds_the_other_clients_save')
        assert current['profile']['blueprints']['farm']['label'] == 'Saved by another client' and current['profile']['blueprints']['farm']['tier'] == 1
        switch_to_beta(w)
        moved = send(w, 'inactive_run_entry_refused_after_account_switch', ['blueprints', 'farm', 'tier'], value=3, context=e, revision=current['revision'], expect=409)
        assert moved['code'] == 'context_changed' and moved['current_context']['account'] == 'beta', moved
        assert source(w).get_json()['revision'] == current['revision']


def unreadable_cases(gen):
    with gen.world('ptm_unreadable') as w:
        target_world(w)
        path = w.root / 'profiles' / 'second.yaml'
        config = (w.root / 'config.yaml').read_bytes()
        broken = 'plan: [unclosed\n  - x: : :'
        path.write_text(broken, encoding='utf-8')
        revision = hashlib.sha256(path.read_bytes()).hexdigest()
        parse = w.get(PM, 'inactive_target_source_that_cannot_be_parsed_400', '/api/profile-src/second')
        assert parse.status_code == 400 and parse.get_json()['ok'] is False and 'while parsing' in parse.get_json()['error'], parse.get_json()
        pin_mtimes(w)                                     # the listing publishes file modification times: the contract pins them
        files = w.get(PM, 'profile_files_still_lists_the_target_whose_source_cannot_be_parsed', '/api/profile-files').get_json()
        by_name = {item['name']: item for item in files['profiles']}
        assert by_name['second']['patchable'] is True and by_name['second']['active'] is False and files['active'] == 'mine', files
        patched = send(w, 'inactive_patch_of_a_target_that_cannot_be_parsed_is_the_parser_error_400', ['plan'], value=PLAN, revision=revision, expect=400)
        assert patched['ok'] is False and 'while parsing' in patched['error'] and path.read_text(encoding='utf-8') == broken, patched
        path.write_text('- a\n- b\n', encoding='utf-8')
        revision = hashlib.sha256(path.read_bytes()).hexdigest()
        flat = w.get(PM, 'inactive_target_source_that_is_not_a_mapping_400', '/api/profile-src/second')
        assert flat.status_code == 400 and flat.get_json() == {'error': 'second.yaml is not a mapping', 'ok': False}, flat.get_json()
        flat_patch = send(w, 'inactive_patch_of_a_target_that_is_not_a_mapping_400', ['plan'], value=PLAN, revision=revision, expect=400)
        assert flat_patch == {'error': 'second.yaml is not a mapping', 'ok': False} and path.read_text(encoding='utf-8') == '- a\n- b\n'
        real = w.dash.load_config
        w.mp.setattr(w.dash, 'load_config', raising(OSError('fixture config could not be read')))
        failed = w.get(PM, 'profile_files_read_failed_500', '/api/profile-files')
        assert failed.status_code == 500 and failed.get_json(silent=True) is None, failed.get_data(as_text=True)[:80]
        w.mp.setattr(w.dash, 'load_config', real)
        assert (w.root / 'config.yaml').read_bytes() == config
        pin_mtimes(w)                                     # second.yaml was rewritten since the first listing
        again = w.get(PM, 'profile_files_read_after_the_failure_answers_again', '/api/profile-files').get_json()
        assert {item['name'] for item in again['profiles']} == {'mine', 'second'}


def profile_target_more_cases(gen):
    schedule_cases(gen)
    abilities_cases(gen)
    run_entry_cases(gen)
    unreadable_cases(gen)
