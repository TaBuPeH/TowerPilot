"""Contract cases of the fenced writes to the ACTIVE profile (roadmap r12d; F6-14b, brief f6-14-profiles-brief.md section 7, root decision D4).

ONE new family of dashboard_contract_pages_v1.json, `profile_patch_fenced`, generated by the real route (POST /api/profile-patch) over the world of profile_target: alpha on
main / fake:1, profile `mine` in force, `second` and beta's `theirs` beside it. Every page that edits the active profile now sends `expected_context` E (the runtime context as
GET /api/config publishes it) with `expected_revision` R (the source revision of `mine` it read); the recordings that existed for this were the inactive profile (`profile_target`),
the shopping library and one tier refusal. Here each write path of the Schedule, Collection, Abilities and Runs pages has its fenced body and the read that follows it:

  Schedule   the day plan saved and removed;
  Collection a gathering policy's label, a copy of it, one created from the shipped template, an unused one deleted, the chores list;
  Abilities  an Ultimate Weapon policy and a rescue policy saved, then deleted while unused;
  Runs       a run's label saved, a run's perk bans deleted;
  Any        the same write after the account was switched: 409 context_changed, nothing written.

The brief's table names 14 cases; each success is followed by `read_after_<case>` (GET /api/profile-src/mine) as the brief asks, and the refusal by the read that shows `mine` unchanged.
"""
import copy

import yaml

from dashboard_contract_cases_context import page_context, switch_to_beta
from dashboard_contract_cases_editors import RESCUE_POLICIES
from dashboard_contract_cases_profile_target import GATHER, PLAN, UW_CALM, target_world
from dashboard_contract_cases_profile import PATCH_URL

PF = 'profile_patch_fenced'


def source(w, case=None):
    return w.get(PF, case, '/api/profile-src/mine') if case else w.client.get('/api/profile-src/mine')


def patch(w, case, path, *, value=None, delete=False, context=None, expect=200):
    """The fenced patch of the active profile: {name:'mine', path, value | op:'delete', expected_context:E, expected_revision:R}, then the read that settles it."""
    body = dict(name='mine', path=path, expected_context=page_context(w) if context is None else context, expected_revision=source(w).get_json()['revision'])
    if delete:
        body['op'] = 'delete'
    else:
        body['value'] = value
    reply = w.post(PF, case, PATCH_URL, body)
    assert reply.status_code == expect, (case, reply.status_code, reply.get_json())
    return reply.get_json()


def saved(w, case, path, **kw):
    before = source(w).get_json()['revision']
    got = patch(w, case, path, **kw)
    assert got['ok'] is True and got['revision'] != before, (case, got)
    read = source(w, 'read_after_' + case).get_json()
    assert read['revision'] == got['revision'] and read['profile'] == got['profile'] and read['problems'] == [], (case, read['problems'])
    return read['profile']


def profile_patch_fenced_cases(gen):
    from player.run_templates import catalogue
    template = next(t for t in catalogue()['templates'] if t['id'] == 'farm')['policies']['gather']['all_on']
    with gen.world('pf_active') as w:
        target_world(w)
        second_before = (w.root / 'profiles' / 'second.yaml').read_bytes()
        config_before = (w.root / 'config.yaml').read_bytes()
        assert source(w).get_json()['profile']['plan'] != PLAN
        assert saved(w, 'active_plan_saved', ['plan'], value=PLAN)['plan'] == PLAN
        assert 'plan' not in saved(w, 'active_plan_deleted', ['plan'], delete=True)
        assert saved(w, 'active_gather_label_saved', ['policies', 'gather', 'all_on', 'label'], value='Offline')['policies']['gather']['all_on']['label'] == 'Offline'
        assert saved(w, 'active_gather_copy_saved', ['policies', 'gather', 'spare'], value=GATHER)['policies']['gather']['spare'] == GATHER
        assert 'fresh' in saved(w, 'active_gather_template_created', ['policies', 'gather', 'fresh'], value=template)['policies']['gather']
        assert 'spare' not in saved(w, 'active_unused_gather_deleted', ['policies', 'gather', 'spare'], delete=True)['policies']['gather']
        assert saved(w, 'active_chores_saved', ['policies', 'chores'], value=[{'name': 'quest_scan', 'enabled': False}])['policies']['chores'] == [{'name': 'quest_scan', 'enabled': False}]
        assert saved(w, 'active_uw_policy_saved', ['policies', 'uw_policies', 'calm'], value=UW_CALM)['policies']['uw_policies']['calm'] == UW_CALM
        assert 'calm' not in saved(w, 'active_uw_policy_deleted', ['policies', 'uw_policies', 'calm'], delete=True)['policies']['uw_policies']
        extra = copy.deepcopy(RESCUE_POLICIES['any_falling'])
        assert saved(w, 'active_rescue_policy_saved', ['policies', 'rescue_policies', 'extra'], value=extra)['policies']['rescue_policies']['extra'] == extra
        assert 'extra' not in saved(w, 'active_rescue_policy_deleted', ['policies', 'rescue_policies', 'extra'], delete=True)['policies']['rescue_policies']
        assert saved(w, 'active_run_entry_label_saved', ['blueprints', 'farm', 'label'], value='Offline farm')['blueprints']['farm']['label'] == 'Offline farm'
        # the field the page deletes must exist to be deleted: the setup (not recorded) gives the run perk bans
        setup = w.plain_post(PATCH_URL, dict(name='mine', path=['blueprints', 'farm', 'perk_bans'], value=['coins, but tower max health'],
                                             expected_revision=source(w).get_json()['revision']))
        assert setup.status_code == 200 and setup.get_json()['profile']['blueprints']['farm']['perk_bans']
        assert 'perk_bans' not in saved(w, 'active_run_entry_field_deleted', ['blueprints', 'farm', 'perk_bans'], delete=True)['blueprints']['farm']
        assert (w.root / 'profiles' / 'second.yaml').read_bytes() == second_before and (w.root / 'config.yaml').read_bytes() == config_before, 'a write to mine touched another file'
    with gen.world('pf_switched') as w:
        target_world(w)
        e = page_context(w)
        before = source(w).get_json()
        switch_to_beta(w)
        refused = patch(w, 'active_patch_refused_after_account_switch', ['plan'], value=PLAN, context=e, expect=409)
        assert refused['code'] == 'context_changed' and refused['current_context']['account'] == 'beta' and refused['current_context']['profile'] == 'theirs', refused
        again = source(w, 'read_after_active_patch_refused_after_account_switch').get_json()
        assert again['revision'] == before['revision'] and again['profile'] == before['profile'], 'a refused fenced write changed mine'
