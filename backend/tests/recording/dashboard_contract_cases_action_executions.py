"""Contract cases of GET /api/actions/executions and the `executions` block of GET /api/battles/<id> (roadmap item 6, batch 2: r17a).

ONE new family of dashboard_contract_pages_v1.json, `action_executions`, generated by the real routes over a temporary ledger whose rows are written by the
real `ActionSession` / `Actions` (the same calls the collectors, the shopper and the harvest host make) on the world's fixed clock; nothing is the live ledger.

The history is the Dashboard's one generic read for every timed action: the page lists the executions of the emulator and account it is showing, newest first, and
renders any action from the row (action, instance, trigger, state, outcome, host, coverage, aggregate) without a branch per action.

  list           GET /api/actions/executions[?action=&action_instance=&battle_id=&before=&limit=&instance=]  ->  {schema_version, ledger_id, context, executions, truncated, next_before,
                 unusable}. Newest first in the order (start time, id), so rows of one start time are ordered and a cursor never loses one. `limit` 1..500 (default 50), `before` is a
                 `next_before` cursor or a bare start time (strictly older rows), anything else a coded 400 {ok:false, code:"invalid_request", error}. The account is part of the query: a
                 row of another account on the same device, and a row of another device, are never returned. `unusable` counts the damaged rows the page skipped.
  cold           a checkout with no ledger, and a ledger that never recorded an execution, answer an empty list with ledger_id null and create nothing.
  newer schema   a ledger a newer build wrote is not interpreted: executions [], reason "newer_schema", ledger_schema_version; status stays readable.
  battle detail  GET /api/battles/<id> carries `executions` {items (newest first), reason, truncated}: items null with reason "recorded_before_action_history" for a battle created before
                 the action store existed (which is not a battle where nothing ran), "newer_schema" on a newer ledger; rows of a battle a driver ADOPTED say coverage "since_adoption".

Two states have no producer and are made by writing the ledger the way a future build or a failing disk would: a row whose body is not JSON (the damaged-row count) and
`action_meta.schema_version` above this build's. Every other row is made by the writer. Not recorded: the refresher's settlement (no route triggers it; test_action_executions_route.py).
"""
