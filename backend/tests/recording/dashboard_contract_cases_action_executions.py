AX = 'action_executions'
URL = '/api/actions/executions'
T0 = 1_800_000_000.0
OTHER_DEVICE = 'other-device-key'


class At:
    """The session's clock: the instant a scenario names, for the wall start of a row and the monotonic length of its window."""

    def __init__(self, seconds=0.0):
        self.seconds = T0 + seconds

    def mono(self):
        return self.seconds

    def wall(self):
        return self.seconds

    def set(self, offset):
        self.seconds = T0 + offset


def selected(w):
    with w.dash.app.test_request_context('/'):
        return w.dash._battle_history_context()


def writer(w, clock, *, account=None, device=None, driver='collector'):
    chosen = selected(w)
    context = dict(device_key=device or chosen['device_key'], account=account or chosen['account'], instance=chosen['instance'], serial=chosen['serial'], profile='mine')
    return ActionSession(operations.ledger_path(w.root), context=context, driver=driver, clock=clock)


def get(w, case, query=''):
    return w.get(AX, case, URL + query)


def run(session, clock, at, action, *, length=4.0, **finish):
    """One window: opened at `at` seconds, closed `length` seconds later."""
    clock.set(at)
    execution = session.begin(action, trigger=finish.pop('trigger', 'automatic'), occurrence_key=finish.pop('occurrence_key', f'window:{action}:{at:g}'),
                              command_id=finish.pop('command_id', None))
    clock.set(at + length)
    session.finish(execution, **finish)
    return execution


def seed(w):
    """Nine rows of the selected emulator and account, one of another account and one of another emulator: windows that confirmed and that did not, three starting at the same
    second, a sweep, a refused manual request, five identical no-input checks (one counted row) and a window still open."""
    clock = At()
    own, other = writer(w, clock), writer(w, clock, account='another-account')
    elsewhere, shopper = writer(w, clock, device=OTHER_DEVICE), writer(w, clock, driver='orchestrator')
    rows = {}
    rows['ad_confirmed'] = run(own, clock, 0, 'ad_gems', result='succeeded', reason='offer_disappeared', effect='unconfirmed', attempts=1, confirmed=1, evidence=['offer_disappeared'])
    rows['ad_unconfirmed'] = run(own, clock, 60, 'ad_gems', result='failed', reason='offer_still_visible', effect='unconfirmed', attempts=1)
    clock.set(60)
    rows['orbit_confirmed'] = own.begin('floating_gems', trigger='automatic', occurrence_key='window:orbit-1')
    clock.set(64)
    own.finish(rows['orbit_confirmed'], result='succeeded', reason='balance_increased', effect='confirmed', attempts=3, confirmed=1, evidence=['balance_increased'])
    clock.set(60)
    rows['orbit_unconfirmed'] = own.begin('floating_gems', trigger='automatic', occurrence_key='window:orbit-2')
    clock.set(75)
    own.finish(rows['orbit_unconfirmed'], result='failed', reason='attempt_timeout', effect='unconfirmed', attempts=4)
    rows['other_account'] = run(other, clock, 70, 'ad_gems', result='succeeded', reason='offer_disappeared', effect='unconfirmed', attempts=1, confirmed=1)
    rows['other_device'] = run(elsewhere, clock, 80, 'ad_gems', result='succeeded', reason='offer_disappeared', effect='unconfirmed', attempts=1, confirmed=1)
    rows['sweep'] = run(shopper, clock, 90, 'shopping', length=12.0, result='succeeded', reason='sweep_complete', effect='confirmed', attempts=3, confirmed=2, evidence=['confirmed_purchase'])
    clock.set(120)
    rows['manual_refused'] = own.record('ad_gems', result='refused', reason='battle_not_visible', trigger='manual', command_id='command-1', occurrence_key='request:command-1').get('id')
    for _ in range(5):
        clock.set(150)
        own.check('ad_gems', result='no_op', reason='no_offer_seen')
    rows['checks'] = own.last['ad_gems']['execution_id']
    clock.set(200)
    rows['open'] = own.begin('floating_gems', trigger='manual', command_id='command-2', occurrence_key='window:open')
    return rows, own


def ids(reply):
    return [row['id'] for row in reply.get_json()['executions']]


def follow(w, query, first_case, *cases):
    """Walk the pages the first read starts, recording the continuations under `cases`; returns every id seen, in order."""
    reply = get(w, first_case, query)
    seen, body = ids(reply), reply.get_json()
    for case in cases:
        assert body['truncated'] and body['next_before'], body
        reply = get(w, case, f"{query}&before={body['next_before']}")
        body = reply.get_json()
        seen += ids(reply)
    assert not body['truncated'] and body['next_before'] is None, body
    return seen


def refused(reply, text):
    body = reply.get_json()
    assert reply.status_code == 400 and body['ok'] is False and body['code'] == 'invalid_request' and text in body['error'], body


def action_executions_cases(gen):
    with gen.world('exec_cold') as w:
        w.mp.setattr(actions_module, 'time', w.clock)
        cold = get(w, 'read_cold_checkout_no_ledger_no_history').get_json()
        assert cold['executions'] == [] and cold['ledger_id'] is None and cold['truncated'] is False and cold['next_before'] is None and cold['unusable'] == 0 and 'reason' not in cold
        assert not operations.ledger_path(w.root).exists(), 'a read created the ledger'
        w.store.accept('run', w.context(), {}, 'a-ledger-with-no-history')
        before = operations.ledger_path(w.root).read_bytes()
        assert get(w, 'read_ledger_with_operations_and_no_history').get_json()['ledger_id'] is None
        assert operations.ledger_path(w.root).read_bytes() == before, 'a read changed the ledger'
    with gen.world('exec_history') as w:
        w.mp.setattr(actions_module, 'time', w.clock)
        rows, own = seed(w)
        mine = {rows[name] for name in ('ad_confirmed', 'ad_unconfirmed', 'orbit_confirmed', 'orbit_unconfirmed', 'sweep', 'manual_refused', 'checks', 'open')}
        newest = get(w, 'read_newest_first_of_the_selected_emulator_and_account')
        body = newest.get_json()
        assert newest.status_code == 200 and set(ids(newest)) == mine and len(mine) == 8 and body['unusable'] == 0 and body['truncated'] is False and body['next_before'] is None
        assert rows['other_account'] not in ids(newest) and rows['other_device'] not in ids(newest), 'another account or emulator is in the page'
        starts = [row['started_at'] for row in body['executions']]
        assert starts == sorted(starts, reverse=True) and body['ledger_id'] and body['context']['device_key'] and body['schema_version'] == 1
        states = {row['id']: row for row in body['executions']}
        assert states[rows['open']]['state'] == 'running' and states[rows['open']]['finished_at'] is None and states[rows['open']]['duration_ms'] is None
        assert states[rows['checks']]['aggregate']['count'] == 5 and states[rows['checks']]['duration_ms'] is None and states[rows['manual_refused']]['state'] == 'refused'
        assert states[rows['sweep']]['outcome']['confirmed'] == 2 and states[rows['ad_unconfirmed']]['outcome']['effect'] == 'unconfirmed'
        seen = follow(w, '?limit=3', 'read_first_page_of_three_is_truncated_with_a_cursor', 'read_second_page_follows_the_cursor', 'read_last_page_has_no_cursor')
        assert seen == ids(newest) and len(seen) == len(set(seen)), 'following the cursor lost or repeated a row'
        tied = [row['id'] for row in body['executions'] if row['started_at'] == T0 + 60]
        assert len(tied) == 3, tied
        one_by_one = follow(w, '?limit=1', 'read_limit_one_first_page', *[f'read_limit_one_page_{n}' for n in range(2, 9)])
        assert one_by_one == ids(newest), 'rows of one start time were lost or repeated at limit 1'
        floating = get(w, 'read_only_the_action_floating_gems', '?action=floating_gems')
        assert {row['action'] for row in floating.get_json()['executions']} == {'floating_gems'} and len(ids(floating)) == 3
        pinned = get(w, 'read_only_the_action_instance_of_ad_gems', '?action=ad_gems&action_instance=ad_gems')
        assert {row['instance'] for row in pinned.get_json()['executions']} == {'ad_gems'} and rows['other_account'] not in ids(pinned)
        assert get(w, 'read_a_battle_no_row_names_is_an_empty_page', '?battle_id=no-such-battle').get_json()['executions'] == []
        older = get(w, 'read_a_bare_start_time_returns_strictly_older_rows', f'?before={T0 + 90}')
        assert set(ids(older)) == {rows['ad_confirmed'], rows['ad_unconfirmed'], rows['orbit_confirmed'], rows['orbit_unconfirmed']}
        assert len(ids(get(w, 'read_limit_five_hundred_is_accepted', '?limit=500'))) == 8
        refused(get(w, 'read_limit_zero_is_refused', '?limit=0'), 'limit must be between 1 and 500')
        refused(get(w, 'read_limit_501_is_refused', '?limit=501'), 'limit must be between 1 and 500')
        refused(get(w, 'read_limit_text_is_refused', '?limit=many'), 'limit must be a whole number')
        refused(get(w, 'read_before_that_is_no_cursor_is_refused', '?before=yesterday'), 'before must be a start time or a cursor')
        refused(get(w, 'read_unknown_emulator_is_refused', '?instance=nothing'), 'Unknown emulator')
        other = get(w, 'read_the_other_emulator_has_its_own_empty_history', '?instance=other').get_json()
        assert other['executions'] == [] and other['context']['instance'] == 'other' and other['context']['device_key'] != body['context']['device_key']
        damaged = sqlite3.connect(operations.ledger_path(w.root))
        chosen = selected(w)
        for number, start in enumerate((300.0, 110.0), 1):          # the newest and one in the middle
            damaged.execute("INSERT INTO action_executions(id, device, action, instance, account, started_at, terminal, body) VALUES (?, ?, 'ad_gems', 'x', ?, ?, 1, '{')",
                            (f'damaged-{number}', chosen['device_key'], chosen['account'], T0 + start))
        damaged.commit()
        damaged.close()
        skipped = get(w, 'read_damaged_rows_are_skipped_and_counted')
        assert skipped.get_json()['unusable'] == 2 and ids(skipped) == ids(newest), skipped.get_json()['unusable']
        walked = follow(w, '?limit=3', 'read_damaged_rows_first_page_of_three', 'read_damaged_rows_second_page', 'read_damaged_rows_last_page')
        assert walked == ids(newest), 'a damaged row hid an intact one from the cursor'
    with gen.world('exec_newer') as w:
        w.mp.setattr(actions_module, 'time', w.clock)
        seed(w)
        db = sqlite3.connect(operations.ledger_path(w.root))
        db.execute('UPDATE action_meta SET schema_version=99')
        db.commit()
        db.close()
        newer = get(w, 'read_a_ledger_a_newer_build_wrote_is_not_interpreted')
        body = newer.get_json()
        assert newer.status_code == 200 and body['executions'] == [] and body['reason'] == 'newer_schema' and body['ledger_schema_version'] == 99 and body['unusable'] == 0
    with gen.world('exec_detail_before') as w:
        w.mp.setattr(actions_module, 'time', w.clock)
        before = Driver(w, 'before-history', origin='started').go_live()
        old = w.get(AX, 'battle_detail_recorded_before_the_action_store_existed', f"/api/battles/{before.battle['id']}").get_json()
        assert old['executions'] == dict(items=None, reason='recorded_before_action_history', truncated=False)
    for label, name, origin, coverage in (('started', 'a_started_battle_lists_its_executions', 'started', 'full'),
                                           ('adopted', 'an_adopted_battle_lists_its_executions_covered_since_the_adoption', 'adopted', 'since_adoption')):
        with gen.world(f'exec_detail_{label}') as w:
            w.mp.setattr(actions_module, 'time', w.clock)
            driver = Driver(w, 'recorded', origin=origin).go_live()
            clock = At(500)
            session = ActionSession.for_battle(driver.session, 'collector')
            session.clock = clock
            window = session.begin('ad_gems', occurrence_key=f'window:{label}')
            clock.set(504)
            session.finish(window, result='succeeded', reason='offer_disappeared', effect='unconfirmed', attempts=1, confirmed=1, evidence=['offer_disappeared'])
            clock.set(520)
            session.check('floating_gems', result='no_op', reason='gem_not_detected')
            detail = w.get(AX, f'battle_detail_of_{name}', f"/api/battles/{driver.battle['id']}").get_json()
            items = detail['executions']['items']
            assert detail['executions']['reason'] is None and detail['executions']['truncated'] is False and len(items) == 2, detail['executions']
            assert {row['coverage'] for row in items} == {coverage} and {row['host']['battle_id'] for row in items} == {driver.battle['id']}
            assert [row['started_at'] for row in items] == sorted((row['started_at'] for row in items), reverse=True)
            if label == 'started':
                mine = get(w, 'read_the_executions_of_one_battle_through_the_generic_route', f"?battle_id={driver.battle['id']}").get_json()
                assert {row['host']['battle_id'] for row in mine['executions']} == {driver.battle['id']} and len(mine['executions']) == 2
                db = sqlite3.connect(operations.ledger_path(w.root))
                db.execute('UPDATE action_meta SET schema_version=99')
                db.commit()
                db.close()
                newer = w.get(AX, 'battle_detail_on_a_ledger_a_newer_build_wrote_is_not_interpreted', f"/api/battles/{driver.battle['id']}").get_json()
                assert newer['executions'] == dict(items=None, reason='newer_schema', truncated=False)


