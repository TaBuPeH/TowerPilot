"""Contract cases that complete the executions history (roadmap item 6, A2-7 backend requests B4, B6, B7 and B8; r17b).

ONE new family of dashboard_contract_pages_v1.json, `action_executions_more`, generated by the real routes over a temporary ledger, beside `action_executions` (whose
cases are unchanged except that every row now carries its action's `label`, request B9):

  run now          the battle detail lists the execution a Run now command started: its row carries that command's id (`command_id`), trigger manual, and the page can follow
                   the item `last.command_id` of runtime.actions to it (battle_actions_projection.run_now_completed_links_its_execution is the same battle's other half);
  cut off          a battle with more executions than a page holds: `executions.truncated` is true and `next_before` is the cursor the generic route continues from
                   (GET /api/actions/executions?battle_id=<id>&before=<next_before>); a complete block has no `next_before` key;
  settled          a driver that died with an execution open: the refresher (the dashboard's tick, never a GET) settles the row `interrupted`, with `finished_at` and `duration_ms`
                   null and the reason it was settled, and the battle detail says the same;
  harvest launch   the dashboard's launch attempts of the standalone collector are rows too (action `harvest_launch`, driver `dashboard`): a refusal before any operation exists
                   (the emulator is offline: `refused`, no operation) and a launch (`succeeded`, with the operation it started).
"""
from types import SimpleNamespace

from control import harvest
from runtime.action_session import ActionSession
from towerpilot_workflows import actions as actions_module

from dashboard_contract_cases_action_executions import At, URL
from dashboard_contract_cases_action_projection import attach, run_now_ad_gems
from test_dashboard_contract import Driver, with_orbit

AXM = 'action_executions_more'
PAGE = 50
T0 = 1_800_000_000.0


def generic_read(w, case, query=''):
    """GET /api/actions/executions, recorded in THIS family (the helper of action_executions records into that one, whose cases stay as published)."""
    return w.get(AXM, case, URL + query)


def turn_harvest_on(w, key):
    ident = harvest.identity_for(w.cfg)
    body = dict(enabled=True, preset='bp_farm', expected_revision=0, idempotency_key=key, expected_context={name: ident[name] for name in ('instance', 'account', 'serial', 'profile')})
    reply = w.plain_post('/api/harvest', body)
    assert reply.status_code == 200, reply.get_json()


def action_executions_more_cases(gen):
    with gen.world('axm_run_now') as w:
        w.mp.setattr(actions_module, 'time', w.clock)
        w.edit_profile(with_orbit)
        d = Driver(w, 'run-now-twin', origin='started')
        attach(d)
        d.go_live()
        scene, command = run_now_ad_gems(w, d)
        detail = w.get(AXM, 'battle_detail_lists_the_run_now_execution', f"/api/battles/{d.battle['id']}").get_json()
        [row] = [entry for entry in detail['executions']['items'] if entry['command_id']]
        assert row['command_id'] == command['id'] and row['trigger'] == 'manual' and (row['action'], row['label'], row['state']) == ('ad_gems', 'Ad gems', 'succeeded'), row
        assert detail['executions']['truncated'] is False and 'next_before' not in detail['executions']
        listed = w.get(AXM, 'read_the_run_now_execution_through_the_generic_route', f"{URL}?battle_id={d.battle['id']}").get_json()
        assert [entry['id'] for entry in listed['executions']] == [row['id']] and listed['executions'][0]['command_id'] == command['id']
    with gen.world('axm_truncated') as w:
        w.mp.setattr(actions_module, 'time', w.clock)
        d = Driver(w, 'many', origin='started').go_live()
        clock = At(100)
        session = ActionSession.for_battle(d.session, 'collector')
        session.clock = clock
        for number in range(PAGE + 1):
            clock.set(100 + 10 * number)
            session.record('ad_gems', result='succeeded', reason='offer_disappeared', effect='unconfirmed', attempts=1, confirmed=1, evidence=['offer_disappeared'],
                           occurrence_key=f'window:many:{number}')
        reply = w.get(AXM, 'battle_detail_truncated_at_fifty', f"/api/battles/{d.battle['id']}")
        block = reply.get_json()['executions']
        assert reply.status_code == 200 and len(block['items']) == PAGE and block['truncated'] is True and block['reason'] is None and block['next_before'], block['truncated']
        starts = [row['started_at'] for row in block['items']]
        assert starts == sorted(starts, reverse=True) and starts[-1] == T0 + 100 + 10 * 1, starts[-1]
        rest = w.get(AXM, 'battle_detail_truncated_continued_through_the_generic_route', f"{URL}?battle_id={d.battle['id']}&before={block['next_before']}").get_json()
        assert len(rest['executions']) == 1 and rest['truncated'] is False and rest['next_before'] is None and rest['executions'][0]['started_at'] == T0 + 100
        assert not {row['id'] for row in block['items']} & {row['id'] for row in rest['executions']}
    with gen.world('axm_settled') as w:
        w.mp.setattr(actions_module, 'time', w.clock)
        d = Driver(w, 'settle', origin='started').go_live()
        clock = At(200)
        session = ActionSession.for_battle(d.session, 'collector')
        session.clock = clock
        opened = session.begin('floating_gems', occurrence_key='window:left-open')
        before = generic_read(w, 'read_an_open_row_before_the_refresher_settles_it').get_json()['executions']
        assert [(row['id'], row['state'], row['finished_at']) for row in before] == [(opened, 'running', None)], before
        w.table.exit(d.op['worker']['pid'])              # the driver died with the window open
        w.advance(30)
        w.dash._harvest_tick()                           # the refresher: the operation is retired, the battle finished, the open row settled
        after = generic_read(w, 'read_after_the_refresher_settled_an_open_row').get_json()['executions']
        [row] = after
        assert (row['id'], row['state'], row['finished_at'], row['duration_ms'], row['duration_basis']) == (opened, 'interrupted', None, None, 'none'), row
        assert row['outcome']['result'] == 'interrupted' and row['outcome']['effect'] == 'unknown' and row['settled_reason'] in ('operation_ended', 'battle_ended') and row['settled_at'], row
        detail = w.get(AXM, 'battle_detail_after_the_refresher_settled_an_open_row', f"/api/battles/{d.battle['id']}").get_json()['executions']
        assert [(entry['id'], entry['state'], entry['finished_at'], entry['duration_ms']) for entry in detail['items']] == [(opened, 'interrupted', None, None)]
    with gen.world('axm_harvest') as w:
        w.mp.setattr(actions_module, 'time', w.clock)
        real_session = harvest.action_session

        def on_the_world_clock(root, cfg):
            session = real_session(root, cfg)
            session.clock = SimpleNamespace(mono=w.clock.monotonic, wall=w.clock.time)      # the dashboard's recorder reads the machine's clock; the world has one
            return session
        w.mp.setattr(harvest, 'action_session', on_the_world_clock)
        w.adb.state = 'offline'
        turn_harvest_on(w, 'turn-on-launch')
        w.dash._harvest_tick()
        refused = generic_read(w, 'read_harvest_refusal_before_any_operation', '?action=harvest_launch').get_json()['executions']
        [row] = refused
        assert (row['action'], row['label'], row['state'], row['host']['driver'], row['host']['operation_id'], row['trigger']) == ('harvest_launch', 'Harvest collector launch', 'refused', 'dashboard', None, 'automatic'), row
        assert row['outcome']['reason'] == 'emulator_offline' and row['aggregate']['count'] == 1, row
        w.adb.state = 'device'
        w.advance(harvest.REFUSAL_RETRY_SEC + 1)
        w.dash._harvest_tick()
        launched = generic_read(w, 'read_harvest_launch_accepted', '?action=harvest_launch').get_json()['executions']
        assert [entry['state'] for entry in launched] == ['succeeded', 'refused'], launched
        newest = launched[0]
        assert newest['outcome']['reason'] == 'launched' and newest['outcome']['effect'] == 'unconfirmed' and newest['refs']['operation_id'] and newest['host']['driver'] == 'dashboard', newest


