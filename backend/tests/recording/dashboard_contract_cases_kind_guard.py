"""Contract cases of the guard on a run's `kind` (roadmap r12d; the r12c review, F6-11 RL12).

ONE new family of dashboard_contract_pages_v1.json, `run_kind_guard`, generated by the real route (POST /api/profile-patch) over the synthetic world of run_entry_patch.
A run's kind picks its runner and decides which fields it may carry, so it is fixed once the run is added. Before r12d the route refused most kind changes only by accident
(the validator disliked the result); a change that left a valid profile was SAVED (run_entry_patch_parity recorded a coin run becoming a tournament run). Now:

  * a patch that changes the kind of a run that exists before and after it - by its `kind` field, by replacing the whole run, or by replacing the whole `blueprints` mapping -
    is 400 {ok:false, code:"kind_change_refused", error, changes:[{blueprint, from_kind, to_kind}]} and writes nothing;
  * the check comes after the revision / context checks and AFTER the validator, so a change the validator refuses keeps its own, more specific answer (no code);
  * adding a run, removing one, and setting the kind a run already has are not changes; the sanctioned way to change a run's type is two requests: remove, then add.
"""
import copy

from dashboard_contract_cases_context import page_context
from dashboard_contract_cases_profile import PATCH_URL
from dashboard_contract_cases_run_leftovers import entry_world, source

KG = 'run_kind_guard'


def patch(w, case, path, *, value=None, delete=False, revision=None, **extra):
    """One patch of one run, the way an editor would send it: {name, path, value | op:'delete', expected_revision[, expected_context]}."""
    body = dict(name='mine', path=path, expected_revision=source(w)['revision'] if revision is None else revision, **extra)
    if delete:
        body['op'] = 'delete'
    else:
        body['value'] = value
    return w.post(KG, case, PATCH_URL, body)


def changes_of(reply, *changes):
    got = reply.get_json()
    assert reply.status_code == 400 and got['ok'] is False and got['code'] == 'kind_change_refused' and got['error'], (reply.status_code, got)
    assert got['changes'] == [dict(blueprint=b, from_kind=f, to_kind=t) for b, f, t in changes], got['changes']
    return got


def unchanged(w, revision):
    assert source(w)['revision'] == revision, 'a refused kind change changed the saved profile'


def run_kind_guard_cases(gen):
    with gen.world('kg_refused') as w:
        entry_world(w)
        revision = source(w, KG, 'read_before_the_kind_attempts')['revision']
        kinds = {name: run['kind'] for name, run in source(w)['profile']['blueprints'].items()}
        assert kinds == {'farm': 'coin', 'farm_deep': 'coin', 'shards': 'shard', 'tourney': 'tournament', 'dissonance': 'coin'}, kinds
        got = changes_of(patch(w, 'kind_changed_on_a_coin_run_is_refused', ['blueprints', 'farm_deep', 'kind'], value='tournament'), ('farm_deep', 'coin', 'tournament'))
        assert 'farm_deep' in got['error'] and 'coin' in got['error'] and 'tournament' in got['error']
        unchanged(w, revision)
        whole = dict(source(w)['profile']['blueprints']['farm_deep'], kind='tournament')
        changes_of(patch(w, 'whole_run_replaced_by_a_run_of_another_kind_is_refused', ['blueprints', 'farm_deep'], value=whole), ('farm_deep', 'coin', 'tournament'))
        unchanged(w, revision)
        blueprints = copy.deepcopy(source(w)['profile']['blueprints'])
        blueprints['farm_deep']['kind'] = 'tournament'
        blueprints['dissonance'].pop('dissonant_tab')
        blueprints['dissonance']['kind'] = 'shard'
        blueprints['dissonance'].pop('restart_via_home', None)
        blueprints['dissonance'].pop('shopping', None)
        assert w.dash._profile_check({**source(w)['profile'], 'blueprints': blueprints}) == [], 'the mapping must be one the validator accepts'
        got = changes_of(patch(w, 'whole_blueprints_mapping_with_two_kinds_changed_names_both', ['blueprints'], value=blueprints),
                         ('dissonance', 'coin', 'shard'), ('farm_deep', 'coin', 'tournament'))        # sorted by run name
        unchanged(w, revision)
        # what the validator refuses keeps the validator's own answer: no code, `problems`
        for case, kw in (('kind_deleted_keeps_the_validators_answer', dict(delete=True)), ('kind_unknown_keeps_the_validators_answer', dict(value='dissonance'))):
            reply = patch(w, case, ['blueprints', 'farm', 'kind'], **kw)
            got = reply.get_json()
            assert reply.status_code == 400 and 'code' not in got and got['problems'], (case, got)
        reply = patch(w, 'kind_changed_on_a_coin_run_with_coin_only_fields_keeps_the_validators_answer', ['blueprints', 'dissonance', 'kind'], value='shard')
        assert reply.status_code == 400 and 'code' not in reply.get_json() and reply.get_json()['problems']
        reply = patch(w, 'kind_changed_on_a_shard_run_keeps_the_validators_answer', ['blueprints', 'shards', 'kind'], value='tournament')     # its `count` is shard-only
        assert reply.status_code == 400 and 'code' not in reply.get_json() and 'count' in reply.get_json()['error']
        unchanged(w, revision)
        # the run is still editable after the refusals, and its kind is as it was
        saved = patch(w, 'other_field_of_the_run_still_saves_after_the_refusal', ['blueprints', 'farm_deep', 'tier'], value=15)
        assert saved.status_code == 200 and saved.get_json()['profile']['blueprints']['farm_deep']['kind'] == 'coin' and saved.get_json()['revision'] != revision
        read = source(w, KG, 'read_after_the_attempts_every_kind_is_as_it_was')
        assert {name: run['kind'] for name, run in read['profile']['blueprints'].items()} == kinds and read['profile']['blueprints']['farm_deep']['tier'] == 15
    with gen.world('kg_accepted') as w:
        entry_world(w)
        source(w, KG, 'read_before_the_changes_that_are_not_kind_changes')
        same = patch(w, 'kind_set_to_the_kind_the_run_already_has_is_accepted', ['blueprints', 'farm_deep', 'kind'], value='coin')
        assert same.status_code == 200 and same.get_json()['profile']['blueprints']['farm_deep']['kind'] == 'coin'
        whole = dict(source(w)['profile']['blueprints']['farm_deep'], tier=16)
        replaced = patch(w, 'whole_run_replaced_by_a_run_of_the_same_kind_is_accepted', ['blueprints', 'farm_deep'], value=whole)
        assert replaced.status_code == 200 and replaced.get_json()['profile']['blueprints']['farm_deep']['tier'] == 16
        added = dict(kind='shard', tier=3, loadout='plain', count=2, label='Added shard run', policies={'gather': 'gems_only'})
        created = patch(w, 'run_added_with_a_kind_of_its_own_is_accepted', ['blueprints', 'added_shard'], value=added)
        assert created.status_code == 200 and created.get_json()['profile']['blueprints']['added_shard']['kind'] == 'shard'
        removed = patch(w, 'run_removed_is_accepted', ['blueprints', 'dissonance'], delete=True)
        assert removed.status_code == 200 and 'dissonance' not in removed.get_json()['profile']['blueprints']
        again = dict(kind='shard', tier=3, loadout='plain', count=1, label='Dissonance shards', policies={'gather': 'gems_only'})
        readded = patch(w, 'run_added_again_with_another_kind_after_it_was_removed_is_accepted', ['blueprints', 'dissonance'], value=again)
        assert readded.status_code == 200 and readded.get_json()['profile']['blueprints']['dissonance']['kind'] == 'shard'
        read = source(w, KG, 'read_after_the_changes_that_are_not_kind_changes')
        assert read['problems'] == [] and read['profile']['blueprints']['dissonance']['kind'] == 'shard' and read['profile']['blueprints']['farm_deep']['kind'] == 'coin'
    with gen.world('kg_order') as w:
        entry_world(w)
        context = page_context(w)
        revision = source(w)['revision']
        stale = patch(w, 'stale_revision_is_judged_before_the_guard', ['blueprints', 'farm_deep', 'kind'], value='tournament', revision='0' * 64)
        assert stale.status_code == 409 and stale.get_json()['code'] == 'revision_conflict', stale.get_json()
        elsewhere = patch(w, 'another_context_is_judged_before_the_guard', ['blueprints', 'farm_deep', 'kind'], value='tournament', revision=revision,
                          expected_context=dict(context, profile='someone_else'))
        assert elsewhere.status_code == 409 and elsewhere.get_json()['code'] == 'context_changed', elsewhere.get_json()
        changes_of(patch(w, 'matching_context_and_revision_do_not_let_a_kind_change_through', ['blueprints', 'farm_deep', 'kind'], value='tournament', revision=revision,
                         expected_context=context), ('farm_deep', 'coin', 'tournament'))
        unchanged(w, revision)
        source(w, KG, 'read_after_the_ordered_refusals_nothing_changed')
