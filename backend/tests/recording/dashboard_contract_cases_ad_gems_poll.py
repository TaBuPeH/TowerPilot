"""Contract cases of an Ad gems attempt that fails, driven through the collector's own poll (roadmap r12d; the gap left by F6-11 brief 6.4).

ONE new family of dashboard_contract_pages_v1.json, `ad_gems_failed_attempt_poll`, generated by the real route (GET /api/battles/active) over a run driver whose Ad gems
collector is the real `interactions.ad_gems.AdGemCollector`, driven by its own `poll(frame)` on the world's clock. Only the device boundary is faked - the HUD frames, the
recognizer's rectangle, the window list, the capture and the tap - so the route publishes what the collector itself measured.

battle_details_runtime (F6-11 6.4) records an attempt that was finished by calling the collector's `_finish_attempt` directly; there the scheduling and response timing
(`scheduling_wait_sec`, `response_delay_sec`) are null and `response_wait_sec` / `response_overdue_sec` are absent, because only `poll` sets them. Here the offer is absent on the
first checks (so `appearance_after_at` is set), appears, waits for the collection window (scheduling wait), gets its response delay, and is then attempted:

  offer_seen / response scheduled   the read between the offer's first sighting and the attempt: `response_due_at` set, no failed attempt yet;
  unconfirmed                       the tap was sent and the offer was still on screen: not_confirmed / offer_still_visible, with every timing field;
  moved                             the fresh frame shows the offer 200 px lower: skipped / offer_moved, no tap;
  blocked                           another app is in front of the game: skipped / in_front:<package>, the window list recorded;
  missing                           the fresh frame no longer shows the offer: skipped / fresh_offer_missing, visibility absent.

Outcomes that carry a Python traceback (a refused tap, a capture error) are not recorded: the traceback holds this machine's file paths.
"""
import random
from types import SimpleNamespace

from interactions import ad_gems

from dashboard_contract_cases_run_leftovers import active
from test_dashboard_contract import Driver

AP = 'ad_gems_failed_attempt_poll'
RECT = (20, 1200, 248, 148)
MOVED = (20, 1400, 248, 148)
APPEARS = 4          # seconds after the first poll: before it the HUD shows no offer, so the collector sees it appear after an absence
WINDOW = 10          # the collection window opens ten seconds after the first poll
TIMING = ('scheduling_wait_sec', 'response_delay_sec', 'response_wait_sec', 'response_overdue_sec')


class Scene:
    """One run driver with its real Ad gems collector and the faked device boundary of one failure mode."""

    def __init__(self, w, mode, driver=None):
        """`driver`: a run driver the caller built (with its recorders attached); the default is a plain one. Mode `confirmed`: the offer is gone from the frame after the tap."""
        self.w, self.mode, self.taps = w, mode, []
        self.d = driver or Driver(w)
        self.d.observe()
        self.ad = self.d.rs.gems.ad_gems
        # the collector mints window / offer / attempt ids from a 12-hex trace id taken from uuid4; the contract's id aliasing only normalises whole UUIDs, so the
        # trace id would carry the generator's uuid counter (which background threads can advance by one between two runs) into the recorded answers
        self.ad._trace_id = f'adp-{mode}'
        self.ad.rng = random.Random(f'{w.name}-ad-gems')
        self.ad.delay = (15.0, 15.0)
        self.ad.options['poll_sec'] = [2, 2]
        self.start = w.clock.monotonic()
        self.ad.next_at = self.ad.next_window_at = self.start + WINDOW
        self.frame, self.fresh, self.after = object(), object(), object()
        frames = iter([self.fresh, self.after])
        w.mp.setattr(ad_gems.screen, 'identify', lambda frame: SimpleNamespace(name='battle'))
        w.mp.setattr(ad_gems.wave_reader, 'read_wave', lambda frame: 123)
        w.mp.setattr(ad_gems, 'find_claim_rect', self.find)
        w.mp.setattr(ad_gems.capture, 'grab', lambda: (w.advance(2), next(frames))[1])
        w.mp.setattr(ad_gems.overlays, 'windows', self.windows)
        w.mp.setattr(ad_gems.act, 'tap', lambda *args, **kwargs: self.taps.append(args) or {})

    def find(self, frame, **kwargs):
        if frame is self.fresh:
            return {'missing': None, 'moved': MOVED}.get(self.mode, RECT)
        if frame is self.after:
            return None if self.mode == 'confirmed' else RECT
        return RECT if self.w.clock.monotonic() >= self.start + APPEARS else None

    def windows(self, serial, **kwargs):
        self.w.advance(1)
        game = ad_gems.overlays.GAME_PKG + '/Activity'
        return ['com.android.vending/Activity', game] if self.mode == 'blocked' else [game]

    def run(self, *, read=None):
        """Poll once a second until the collector has made its attempt; `read` is called once, when the response is scheduled and the attempt has not been made."""
        for _ in range(60):
            self.ad.poll(self.frame)
            if read and self.ad.claim_at is not None and not self.ad.counters['attempts']:
                self.d.publish()
                read()
                read = None
            if self.ad.counters['attempts']:
                return self
            self.w.advance(1)
        raise AssertionError('the collector never attempted a claim')

    def read(self, case):
        self.d.publish()
        return active(self.w, AP, case).get_json()['battle']['runtime']['routines']['ad_gems']


def failed(got, outcome, reason, *, skips, blocker=None):
    """What every recorded failure shares: the attempt is counted once, never confirmed, correlated, and every timing field is set.
    `blocker` is the status's own reading of why nothing is being claimed now: the failure's reason, unless the offer is absent again (offer_absent)."""
    last = got['last_failed_attempt']
    assert (last['outcome'], last['reason'], last['confirmed']) == (outcome, reason, False), last
    assert got['last_outcome'] == last and got['claim_attempt_id'] is None and got['blocker'] == (blocker or reason), got
    assert (got['counters']['attempts'], got['counters']['confirmed'], got['counters']['skips']) == (1, 0, skips), got['counters']
    for field in TIMING:
        assert got['durations'][field] is not None and last[field] is not None, (field, got['durations'], last)
    assert got['durations']['scheduling_wait_sec'] == 6.0 and got['durations']['response_delay_sec'] == 15.0 and got['durations']['response_wait_sec'] == 15.0
    assert last['window_id'] == got['window_id'] and last['offer_id'] == got['offer_id'] and last['claim_attempt_id'].endswith(':attempt:1')
    assert last['window_id'].startswith('adp-') and last['window_id'].endswith(':window:1') and last['offer_id'].endswith(':offer:1'), last
    assert got['appearance_after_at'] is not None and got['first_seen_at'] is not None and got['window_started_at'] is not None
    return last


def ad_gems_failed_attempt_poll_cases(gen):
    with gen.world('adp_unconfirmed') as w:
        scene = Scene(w, 'unconfirmed')

        def scheduled():
            got = active(w, AP, 'offer_seen_after_an_absence_and_its_response_scheduled').get_json()['battle']['runtime']['routines']['ad_gems']
            assert got['visibility'] == 'visible' and got['appearance_after_at'] is not None and got['first_seen_at'] > got['appearance_after_at'], got
            assert got['response_due_at'] is not None and got['response_started_at'] is not None and got['last_failed_attempt'] is None, got
            assert got['durations']['scheduling_wait_sec'] == 6.0 and got['durations']['response_delay_sec'] == 15.0, got['durations']
            assert got['counters']['seen'] == 1 and got['counters']['attempts'] == 0 and got['blocker'] == 'response_delay', got
        scene.run(read=scheduled)
        got = scene.read('failed_attempt_unconfirmed_the_offer_was_still_visible_after_the_tap')
        last = failed(got, 'not_confirmed', 'offer_still_visible', skips=0)
        assert len(scene.taps) == 1 and got['visibility'] == 'visible' and last['verification_before_tap_sec'] == 3.0 and last['verification_sec'] == 5.35, (scene.taps, last)
    for mode, case, outcome, reason in (('moved', 'failed_attempt_skipped_the_offer_moved_before_the_tap', 'skipped', 'offer_moved'),
                                        ('blocked', 'failed_attempt_skipped_another_app_was_in_front_of_the_game', 'skipped', 'in_front:com.android.vending'),
                                        ('missing', 'failed_attempt_skipped_the_offer_was_gone_on_the_fresh_frame', 'skipped', 'fresh_offer_missing')):
        with gen.world('adp_' + mode) as w:
            scene = Scene(w, mode).run()
            got = scene.read(case)
            last = failed(got, outcome, reason, skips=1, blocker='offer_absent' if mode == 'missing' else None)
            assert scene.taps == [] and 'verification_before_tap_sec' not in last, (mode, scene.taps, last)
            if mode == 'moved':
                assert last['center_displacement_px'] == 200 and last['observed_rect'] == list(RECT) and last['fresh_rect'] == list(MOVED), last
            if mode == 'blocked':
                assert last['visible_windows'] == ['com.android.vending/Activity', ad_gems.overlays.GAME_PKG + '/Activity'], last
            if mode == 'missing':
                assert got['visibility'] == 'absent' and got['claim_rect'] is None, got
