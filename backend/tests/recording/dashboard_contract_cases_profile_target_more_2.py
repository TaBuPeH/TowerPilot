"""Contract cases of seven more run-entry edits of an INACTIVE profile (roadmap r12f, the follow-up of F6-14): the family profile_target_more_2.

ONE new family of dashboard_contract_pages_v1.json, generated by the real routes over the world of profile_target (alpha on main / fake:1, profile `mine` in force, `second` beside it,
`theirs` owned by beta) with four more things in the profile every copy starts from: the dissonance coin run `dissonance`, the grant quest `quest_sm` (rides 1), the cycle quest `quest_ilm`
(cycles 40), and a rescue policy on the coin run `farm` (the populated profile gives it none). `second` is the target of every request:

   POST /api/profile-patch {name: 'second', path, value | op: 'delete' (no value), expected_revision: R, expected_context: {instance, account, profile, serial}}

with R the revision of the GET /api/profile-src/second read recorded just before it, and one more GET /api/profile-src/second just after:

   1  delete   blueprints.farm.label                    the run is shown by its identifier again
   2  delete   blueprints.farm.policies.gather          the run keeps no gathering policy (its `policies` stays as a mapping)
   3  delete   blueprints.farm.policies.rescue          the run keeps no rescue policy
   4  delete   blueprints.dissonance.dissonant_tab      the coin run is no longer a dissonance run
   5  save 2   blueprints.quest_sm.rides                a grant quest rides twice
   6  save 2   blueprints.quest_ilm.cycles              a cycle quest runs twice
   7  delete   blueprints.quest_sm.rides                the quest uses its own default again

and one repeat of 3 after the seven (the policy is already gone: 200, the same revision, the file is not rewritten).

The requests run in this order in ONE world: each starts from the state the one before left. The generator checks, for every request, that the profile read afterwards is the profile read before with exactly that
one path changed (an independent walk of the path, not the route's), that the answer's profile and revision are the read's, that the validator has no problem before or after, and that the active profile `mine` and
config.yaml are byte-identical at the end.

What the route does (read from the source, then recorded): `_apply_patch` walks the path, creating a missing MAPPING step, and sets or pops the leaf (popping an absent key is not an error); the validator judges the whole
patched profile; `blueprint_kind_changes` refuses a change of a run's kind (none of the seven touches `kind`); a profile that did not change is written with the same bytes, so its revision does not move.
"""
import copy

from dashboard_contract_cases_context import page_context
from dashboard_contract_cases_profile_target import target_world
from dashboard_contract_cases_profile_target_more import read, send, snapshot_of, untouched
from dashboard_contract_cases_run_leftovers import add_dissonance_run

PM2 = 'profile_target_more_2'
PAGE_CONTEXT = {'instance': 'main', 'account': 'alpha', 'profile': 'mine', 'serial': 'fake:1'}
FARM_POLICIES = ['blueprints', 'farm', 'policies']
# the seven requests in the order root listed them: the name stem, the path, the value (a delete has none) and whether it deletes
STEPS = [('farm_label', ['blueprints', 'farm', 'label'], None, True),
         ('farm_gathering_policy', FARM_POLICIES + ['gather'], None, True),
         ('farm_rescue_policy', FARM_POLICIES + ['rescue'], None, True),
         ('dissonant_tab', ['blueprints', 'dissonance', 'dissonant_tab'], None, True),
         ('quest_rides', ['blueprints', 'quest_sm', 'rides'], 2, False),
         ('quest_cycles', ['blueprints', 'quest_ilm', 'cycles'], 2, False),
         ('quest_rides', ['blueprints', 'quest_sm', 'rides'], None, True)]


def case_names(stem, delete):
    """The three cases of one request: the read before, the patch, the read after."""
    verb = 'deleted' if delete else 'saved'
    return f'read_before_the_{stem}_is_{verb}', f'inactive_{stem}_{verb}', f'read_after_the_{stem}_was_{verb}'


def more_runs(profile):
    """What every profile of the world starts from: the dissonance run, the two quests, and a rescue policy on `farm`."""
    add_dissonance_run(profile)
    profile['blueprints']['quest_sm'] = {'kind': 'uw_grant_quest', 'loadout': 'plain', 'tier': 1, 'grant_targets': ['smart_missiles'], 'rides': 1, 'reroll_at_wave': 1000, 'ride_to_wave': 6500}
    profile['blueprints']['quest_ilm'] = {'kind': 'cycle_quest', 'loadout': 'plain', 'tier': 1, 'cycle_sec': 25, 'cycles': 40}
    profile['blueprints']['farm']['policies']['rescue'] = 'wall_drain'


def changed(profile, path, value, delete):
    """`profile` with the one path set or deleted: an independent walk (the route's _apply_patch is what is recorded here, so it cannot be what proves it)."""
    out = copy.deepcopy(profile)
    node = out
    for step in path[:-1]:
        node = node[step]
    if delete:
        node.pop(path[-1], None)
    else:
        node[path[-1]] = value
    return out


def profile_target_more_2_cases(gen):
    with gen.world('ptm2_runs') as w:
        target_world(w, mutate=more_runs)
        snapshot = snapshot_of(w)
        context = page_context(w)
        assert context == PAGE_CONTEXT, context
        for stem, path, value, delete in STEPS:
            name_before, name_patch, name_after = case_names(stem, delete)
            before = read(w, name_before, family=PM2)
            assert before['ok'] is True and before['problems'] == [], (stem, before['problems'])
            reply = send(w, name_patch, path, value=value, delete=delete, context=context, revision=before['revision'], expect=200, family=PM2)
            expected = changed(before['profile'], path, value, delete)
            assert expected != before['profile'], (stem, 'the edit changes nothing in this world')
            assert reply['ok'] is True and reply['profile'] == expected and reply['warnings'] == [] and reply['revision'] != before['revision'], (stem, reply)
            after = read(w, name_after, family=PM2)
            assert after['profile'] == expected and after['revision'] == reply['revision'] and after['problems'] == [], (stem, after['problems'])
        # the policy is already gone: the route pops an absent key, writes the same bytes, and the revision does not move
        before = read(w, 'read_before_the_farm_rescue_policy_is_deleted_again', family=PM2)
        farm = before['profile']['blueprints']
        assert 'rescue' not in farm['farm']['policies'] and 'gather' not in farm['farm']['policies'] and 'label' not in farm['farm'], farm['farm']
        assert 'dissonant_tab' not in farm['dissonance'] and 'rides' not in farm['quest_sm'] and farm['quest_ilm']['cycles'] == 2, farm
        again = send(w, 'inactive_farm_rescue_policy_deleted_again_when_the_run_has_none', FARM_POLICIES + ['rescue'], delete=True, context=context, revision=before['revision'], expect=200, family=PM2)
        assert again['ok'] is True and again['revision'] == before['revision'] and again['profile'] == before['profile'], again
        untouched(w, snapshot)
