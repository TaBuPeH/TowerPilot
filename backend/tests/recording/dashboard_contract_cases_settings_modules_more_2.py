"""Contract cases of three recordings the settings and equipment pages still needed (roadmap r12f, the follow-up of F6-15 / C-03).

ONE new family of dashboard_contract_pages_v1.json, `settings_modules_more_2`, generated by the real routes (POST /api/loadout-patch, GET /api/config, GET /api/profile-src/<name>,
GET and POST /api/settings) over the worlds of the loadout restore and settings families. Nothing published is touched.

  Restore values only   saved_modules_restore_only: the loadout 'plain' with a modules_restore and NO `modules`, saved from the state settings_modules_more.read_before_saved_modules_restore
                        records (the cards restore is already saved), with the exact request {name, expected_revision, expected_context {account: null, instance, profile, serial}, body};
                        and read_after_saved_modules_restore_only (GET /api/config).
  No blueprints        GET /api/profile-src/mine for a profile with no `blueprints` mapping (profile_src_without_blueprints; also `blueprints: null`, a list, and an empty mapping), and what
                        POST /api/loadout-patch answers for it: a restore edit is 409 restore_loadout_unused (no run of the profile names any loadout), any other loadout save is 400 with the
                        profile's own problems; nothing is written.
  Malformed lists       GET /api/settings where a tournament-cards list holds [false, 7, "keep"] (hand-edited YAML), the save that sends it back (refused), a save of the other list only
                        (accepted: only the fields a request names are validated, so the malformed list stays as stored), and the save that repairs it.

What the routes do (read from the source, then recorded):
  * loadout-patch judges the whole body it is given: no key is merged with the stored loadout. The restore keys are checked against the account only for a loadout a blueprint of the ACTIVE
    profile names (playerprofile.loadouts_in_use); a profile with no blueprints mapping names none, so a body that changes a restore key is refused (409 restore_loadout_unused) before the
    validator runs, and any other body is judged by the profile validator, which reports the missing section (400, `problems`, `error` = the first problem).
  * GET /api/profile-src/<name> answers 200 even when the validator has problems: {ok, name, profile, problems, warnings, revision, validator_error}; `profile` is the file as parsed (the
    `blueprints` key is absent, null, a list or {} exactly as the file has it).
  * the settings read shows a stored value as it is, raw (a boolean and a number inside a string list included); `validate` refuses a string list whose entry is not a non-blank string, with the
    position of the first bad entry, and only the fields a request names are validated.
"""
import copy

from dashboard_contract_cases_context import page_context
from dashboard_contract_cases_editors import config_of, equipped, loadout
from dashboard_contract_cases_settings import snapshot, submit
from dashboard_contract_cases_settings_modules import furnished, stored
from dashboard_contract_cases_settings_modules_more import config_bytes, fields, read_after, refused

SM2 = 'settings_modules_more_2'
CARDS = {'cards': 'main_farm', 'cards_restore': 'no_card'}
MODULES_ONLY = dict(CARDS, modules_restore=[['black_hole_digestor', 'assist']])
PAGE_CONTEXT = {'account': None, 'instance': 'main', 'profile': 'mine', 'serial': 'fake:1'}
MALFORMED = [False, 7, 'keep']


# ------------------------------------------------------------------------------------------------ 1. a modules restore with no `modules`
def restore_only_cases(gen):
    with gen.world('set_more2_restore_only') as w:
        equipped(w)
        context = page_context(w)
        assert context == PAGE_CONTEXT, context
        first = w.plain_post('/api/loadout-patch', dict(name='plain', body=CARDS, expected_revision=config_of(w)['config_revision'], expected_context=context))
        assert first.status_code == 200, first.get_json()           # the published saved_cards_restore; not recorded here
        before = config_of(w)                                          # = settings_modules_more.read_before_saved_modules_restore (the guard test compares the revisions)
        assert before['loadouts']['plain'] == CARDS and before['config_revision'] == first.get_json()['config_revision']
        reply = loadout(w, 'saved_modules_restore_only', 'plain', MODULES_ONLY, before['config_revision'], expect=200, expected_context=context, family=SM2).get_json()
        assert reply['ok'] and reply['loadouts']['plain'] == MODULES_ONLY and 'modules' not in reply['loadouts']['plain'], reply
        assert reply['config_revision'] != before['config_revision']
        read = w.get(SM2, 'read_after_saved_modules_restore_only', '/api/config').get_json()
        assert read['loadouts']['plain'] == MODULES_ONLY and read['config_revision'] == reply['config_revision']
        assert read['loadouts']['spare'] == before['loadouts']['spare'] and read['loadouts']['later'] == before['loadouts']['later']         # the other loadouts are untouched


# ------------------------------------------------------------------------------------------------ 2. a profile with no blueprints mapping
# the case of the source read, the case of the restore refusal, and the change that makes the profile of the world what the name says
WITHOUT = [('profile_src_without_blueprints', 'restore_refused_for_a_profile_without_blueprints', lambda profile: profile.pop('blueprints')),
           ('profile_src_with_blueprints_null', 'restore_refused_for_a_profile_with_blueprints_null', lambda profile: profile.__setitem__('blueprints', None)),
           ('profile_src_with_blueprints_a_list', 'restore_refused_for_a_profile_with_blueprints_a_list', lambda profile: profile.__setitem__('blueprints', [])),
           ('profile_src_with_an_empty_blueprints_mapping', 'restore_refused_for_a_profile_with_an_empty_blueprints_mapping', lambda profile: profile.__setitem__('blueprints', {}))]


def no_blueprints_cases(gen):
    for number, (case, refusal, mutate) in enumerate(WITHOUT):
        with gen.world(f'set_more2_no_blueprints_{number}') as w:
            equipped(w, mutate=mutate)
            context, revision = page_context(w), config_of(w)['config_revision']
            src = w.get(SM2, case, '/api/profile-src/mine')
            body = src.get_json()
            assert src.status_code == 200 and body['ok'] is True and body['name'] == 'mine', (case, src.status_code)
            assert body['problems'] and 'blueprints' in body['problems'][0], (case, body['problems'])
            assert ('blueprints' in body['profile']) == (number > 0) and body['profile'].get('blueprints') in (None, [], {}), (case, body['profile'].get('blueprints'))
            gone = loadout(w, refusal, 'plain', CARDS, revision, expect=409, expected_context=context, family=SM2).get_json()
            assert gone['ok'] is False and gone['code'] == 'restore_loadout_unused' and gone['restore_keys'] == ['cards_restore'] and gone['active_profile'] == 'mine', gone
            assert config_of(w)['config_revision'] == revision, (case, 'a refused restore edit changed config.yaml')
            if number == 0:
                other = loadout(w, 'loadout_save_refused_for_a_profile_without_blueprints', 'plain', {'cards': 'no_card'}, revision, expect=400, expected_context=context, family=SM2).get_json()
                assert other['ok'] is False and other['problems'] == body['problems'] and other['error'] == body['problems'][0] and 'code' not in other, other
                assert config_of(w)['config_revision'] == revision
                held = w.get(SM2, 'read_config_after_the_refusals_nothing_changed', '/api/config').get_json()
                assert held['config_revision'] == revision and held['loadouts']['plain'] == {}


# ------------------------------------------------------------------------------------------------ 3. a hand-edited tournament list
def malformed_cases(gen):
    with gen.world('set_more2_malformed_tourney') as w:
        furnished(w)
        w.edit_config(lambda cfg: cfg['accounts']['alpha']['tourney_card_tweaks'].update(drop=copy.deepcopy(MALFORMED)))
        assert stored(w)['accounts']['alpha']['tourney_card_tweaks'] == {'drop': MALFORMED, 'add': []}
        snap = snapshot(w, 'read_with_malformed_tournament_cards', SM2)
        assert fields(snap, 'tournament-cards') == {'drop': MALFORMED, 'add': []}, fields(snap, 'tournament-cards')       # the read shows the stored value raw
        refused(w, 'tournament_cards_sent_back_with_the_malformed_entries_is_refused', snap, 'tournament-cards', {'drop': MALFORMED, 'add': []},
                'Cards to drop: entry 1 must be a non-blank string', family=SM2)
        assert snapshot(w, 'read_after_the_refused_send_back_nothing_changed', SM2) == snap
        other = submit(w, 'saved_tournament_cards_add_list_only_the_malformed_drop_list_stays', snap, 'tournament-cards', {'add': ['golden_orb']}, expect=200, family=SM2).get_json()
        assert fields(other, 'tournament-cards') == {'drop': MALFORMED, 'add': ['golden_orb']}, fields(other, 'tournament-cards')
        assert stored(w)['accounts']['alpha']['tourney_card_tweaks'] == {'drop': MALFORMED, 'add': ['golden_orb']}
        read = read_after(w, 'read_after_the_add_list_was_saved_the_malformed_drop_list_remains', other, family=SM2)
        fixed = submit(w, 'saved_tournament_cards_repairing_the_malformed_drop_list', read, 'tournament-cards', {'drop': ['keep']}, expect=200, family=SM2).get_json()
        assert fields(fixed, 'tournament-cards') == {'drop': ['keep'], 'add': ['golden_orb']}, fields(fixed, 'tournament-cards')
        assert stored(w)['accounts']['alpha']['tourney_card_tweaks'] == {'drop': ['keep'], 'add': ['golden_orb']} and stored(w)['tourney_card_tweaks'] == {'drop': ['legacy_drop'], 'add': []}
        read_after(w, 'read_after_the_malformed_drop_list_was_repaired', fixed, family=SM2)
        bytes_after = config_bytes(w)
        again = submit(w, 'saved_the_repaired_lists_again_keeps_the_revision', fixed, 'tournament-cards', {'drop': ['keep'], 'add': ['golden_orb']}, expect=200, family=SM2).get_json()
        assert again['revision'] == fixed['revision'] and config_bytes(w) == bytes_after


def settings_modules_more_2_cases(gen):
    restore_only_cases(gen)
    no_blueprints_cases(gen)
    malformed_cases(gen)
