"""Contract cases of the shopping queue that the F6-12 recordings did not reach (roadmap r12c, requests (b) and (d) of the F6-11/F6-12 reviews).

Two NEW families of dashboard_contract_pages_v1.json, generated by the real routes over the synthetic world of the Shopping queue family:

  shopping_queue_bounds            SQ5: what the SERVER answers to a queue whose per-entry numbers are out of bounds - a negative, fractional, text or boolean tap cap, a
                                   weight of 0, 101, a fraction or text, a wave range that is reversed, empty, starts below 1 or is not whole - through the saved
                                   run save (POST /api/run-controls) and the live save (POST /api/operations/{id}/live-controls); and the boundary values that are accepted;
  run_controls_live_reset_all_mixed  one live-controls request that sends `null` for the shopping plan AND the routine overrides applied together, from the applied
                                   mixed state of shopping_queue.shopping_plan_routine_overrides_applied, with the battle read before and after it applies; only the plan;
                                   only the routines; a stale control revision.

The older families keep their bytes. Nothing here changes a runtime file.
"""
import copy

from dashboard_contract_cases_runs import RUN, live_body, live_url, read_run, save_body
from dashboard_contract_cases_shopping import P1, PW, live_world, shopping_world
from dashboard_contract_cases_run_leftovers import leaves

SB, RM = 'shopping_queue_bounds', 'run_controls_live_reset_all_mixed'


def plan_with(base, index=0, **fields):
    """`base` with the fields of its queue entry `index` replaced (a fresh copy: the module's plans are never edited)."""
    plan = copy.deepcopy(base)
    plan['queue'][index].update(fields)
    return plan


# (case, the entry's fields): each makes the SERVER refuse the whole plan; the plan is otherwise P1
OUT_OF_BOUNDS = [
    ('tap_cap_negative', dict(tap_limit=-1)),
    ('tap_cap_fraction', dict(tap_limit=2.5)),
    ('tap_cap_text', dict(tap_limit='3')),
    ('tap_cap_true', dict(tap_limit=True)),
    ('weight_zero', dict(weight=0)),
    ('weight_fraction', dict(weight=1.5)),
    ('weight_text', dict(weight='2')),
    ('weight_above_100', dict(weight=101)),
    ('wave_range_reversed', dict(from_wave=10, until_wave=5)),
    ('wave_range_empty', dict(from_wave=5, until_wave=5)),
    ('until_wave_below_two', dict(until_wave=1)),
    ('from_wave_zero', dict(from_wave=0)),
    ('from_wave_fraction', dict(from_wave=2.5)),
    ('until_wave_fraction', dict(from_wave=1, until_wave=7.5)),
]
LIVE_REFUSED = ('tap_cap_negative', 'tap_cap_fraction', 'weight_zero', 'wave_range_reversed')
# the smallest and largest values the validator accepts, on both entries of the queue
BOUNDARY = plan_with(plan_with(P1, 0, tap_limit=0, weight=100, from_wave=1, until_wave=2), 1, tap_limit=None, weight=1, from_wave=5, until_wave=6)


def shopping_queue_bounds_cases(gen):
    with gen.world('sqb_saved') as w:
        shopping_world(w)
        current = read_run(w, 'read_before_the_refusals', 'farm', SB)
        for case, fields in OUT_OF_BOUNDS:
            reply = w.post(SB, f'saved_{case}_refused', RUN, save_body(current, {'shopping_plan': plan_with(P1, 0, **fields)}))
            assert reply.status_code == 400 and reply.get_json()['ok'] is False and reply.get_json()['error'], (case, reply.status_code, reply.get_json())
        held = read_run(w, 'read_after_the_refusals_nothing_changed', 'farm', SB)
        assert held['profile_revision'] == current['profile_revision'] and held['settings']['shopping_plan'] == P1, 'a refused plan changed the saved run'
    with gen.world('sqb_saved_boundary') as w:
        shopping_world(w)
        current = read_run(w)
        accepted = w.post(SB, 'saved_boundary_values_accepted', RUN, save_body(current, {'shopping_plan': BOUNDARY}))
        assert accepted.status_code == 200 and accepted.get_json()['settings']['shopping_plan'] == BOUNDARY, accepted.get_json()
        read = read_run(w, 'read_after_the_boundary_values_were_saved', 'farm', SB)
        assert read['settings']['shopping_plan'] == BOUNDARY and read['profile_revision'] == accepted.get_json()['profile_revision']
    with gen.world('sqb_live') as w:
        d = live_world(w)
        for number, case in enumerate(LIVE_REFUSED, 1):
            fields = dict(OUT_OF_BOUNDS)[case]
            reply = w.post(SB, f'live_{case}_refused', live_url(d), live_body(d, {'shopping_plan': plan_with(P1, 0, **fields)}, f'sqb-{number}'))
            assert reply.status_code == 400 and reply.get_json()['ok'] is False, (case, reply.status_code, reply.get_json())
        battle = w.get(SB, 'read_after_the_live_refusals_nothing_was_recorded', '/api/battles/active').get_json()['battle']
        assert battle['commands'] == [] and battle['control_revision'] == battle['applied_revision'] == 0 and battle['effective']['shopping_plan'] == P1
        accepted = w.post(SB, 'live_boundary_values_accepted', live_url(d), live_body(d, {'shopping_plan': BOUNDARY}, 'sqb-ok'))
        assert accepted.status_code == 200 and accepted.get_json()['command']['state'] == 'requested', accepted.get_json()
        d.checkpoint()
        applied = w.get(SB, 'read_after_the_live_boundary_values_applied', '/api/battles/active').get_json()['battle']
        assert applied['effective']['shopping_plan'] == BOUNDARY and applied['applied_revision'] == applied['control_revision'] == 1


# ------------------------------------------------------------------------------------------------ one reset for the plan and the routine overrides
ROUTINES = {'routines.shopping.enabled': False, 'routines.shopping.interval_sec': 60}
NO_ROUTINES = {path: None for path in ROUTINES}


def mixed_world(w, *, record=True):
    """A live battle with the routine overrides (shopping off, every 60 s) applied at revision 1 and the plan PW applied at revision 2: the state of
    shopping_queue.shopping_plan_routine_overrides_applied."""
    d = live_world(w)
    post = (lambda case, body, key: w.post(RM, case, live_url(d), live_body(d, body, key))) if record else \
        (lambda case, body, key: w.plain_post(live_url(d), live_body(d, body, key)))
    assert post('routine_overrides_set_before_the_reset', ROUTINES, 'mx-1').status_code == 200
    d.checkpoint()
    assert post('shopping_plan_set_before_the_reset', {'shopping_plan': PW}, 'mx-2').status_code == 200
    d.checkpoint()
    return d


def active(w, case=None):
    reply = w.get(RM, case, '/api/battles/active') if case else w.client.get('/api/battles/active')
    return reply.get_json()['battle']


def run_controls_live_reset_all_mixed_cases(gen):
    with gen.world('rmx_all') as w:
        d = mixed_world(w)
        before = active(w, 'read_before_the_reset_the_mixed_overrides_are_in_force')
        assert before['effective']['shopping_plan'] == PW and before['effective']['routines']['shopping'] == dict(enabled=False, interval_sec=60), before['effective']
        assert before['applied_revision'] == before['control_revision'] == 2 and 'shopping_plan' in before['overrides']
        reset = w.post(RM, 'accepted_null_for_shopping_plan_and_routine_overrides', live_url(d),
                       live_body(d, dict({'shopping_plan': None}, **NO_ROUTINES), 'mx-3'))
        assert reset.status_code == 200 and reset.get_json()['command']['state'] == 'requested', reset.get_json()
        requested = active(w, 'read_after_the_reset_was_accepted_before_it_applies')
        assert requested['effective']['shopping_plan'] == PW and requested['control_revision'] == 3 and requested['applied_revision'] == 2
        d.checkpoint()
        after = active(w, 'read_after_the_mixed_reset_applied')
        assert after['applied_revision'] == after['control_revision'] == 3 and not leaves(after['overrides']) and 'shopping_plan' not in after['overrides'], after['overrides']
        assert after['effective']['shopping_plan'] == P1, after['effective']['shopping_plan']
        replay = w.post(RM, 'identical_resend_of_the_mixed_reset_answered_from_the_record', live_url(d),
                        live_body(d, dict({'shopping_plan': None}, **NO_ROUTINES), 'mx-3', expected_revision=2))
        assert replay.status_code == 200 and replay.get_json()['command']['id'] == reset.get_json()['command']['id']
    with gen.world('rmx_plan_only') as w:
        d = mixed_world(w, record=False)
        reply = w.post(RM, 'accepted_null_for_the_shopping_plan_only_keeps_the_routine_overrides', live_url(d), live_body(d, {'shopping_plan': None}, 'mx-p'))
        assert reply.status_code == 200, reply.get_json()
        d.checkpoint()
        kept = active(w, 'read_after_the_plan_only_reset_the_routine_overrides_remain')
        assert kept['effective']['shopping_plan'] == P1 and kept['effective']['routines']['shopping'] == dict(enabled=False, interval_sec=60), kept['effective']
        assert 'shopping_plan' not in kept['overrides'] and sorted(leaves(kept['overrides'])) == sorted(ROUTINES), kept['overrides']
    with gen.world('rmx_routines_only') as w:
        d = mixed_world(w, record=False)
        reply = w.post(RM, 'accepted_null_for_the_routine_overrides_only_keeps_the_plan_override', live_url(d), live_body(d, dict(NO_ROUTINES), 'mx-r'))
        assert reply.status_code == 200, reply.get_json()
        d.checkpoint()
        kept = active(w, 'read_after_the_routines_only_reset_the_plan_override_remains')
        assert kept['effective']['shopping_plan'] == PW and kept['overrides']['shopping_plan'] == PW and not leaves(kept['overrides']['routines']), kept['overrides']
    with gen.world('rmx_stale') as w:
        d = mixed_world(w, record=False)
        stale = w.post(RM, 'mixed_reset_with_a_stale_control_revision_refused', live_url(d),
                       live_body(d, dict({'shopping_plan': None}, **NO_ROUTINES), 'mx-s', expected_revision=1))
        assert stale.status_code == 409, stale.get_json()
        kept = active(w, 'read_after_the_refusal_both_kinds_of_override_remain')
        assert kept['control_revision'] == 2 and kept['effective']['shopping_plan'] == PW and kept['overrides']['shopping_plan'] == PW, kept['overrides']
        assert sorted(leaves({'routines': kept['overrides']['routines']})) == sorted(ROUTINES), kept['overrides']
