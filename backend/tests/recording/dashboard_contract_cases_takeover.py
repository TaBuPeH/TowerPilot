"""Recorded contract cases of the takeover routes (roadmap item 3, T3c): what the Dashboard reads from `GET /api/takeover/preview` and `POST /api/control
{action: "takeover"}` and from the battle it starts. Recorded THROUGH the real routes over the synthetic world of the harvesting tests; nothing is typed by hand
except the requests, the one worker failure that is stood in for (below) and the takeover battle records of `launch_collector` and `attached_battle`, which are
created on the store (the real worker's own record is the one in `real_worker`).

The family file is backend/tests/fixtures/dashboard_contract_takeover_v1.json (written by support/fixture_json.py). It is a separate file on purpose: the pages
fixture is regenerated by every UI-backend package, and takeover must not make them conflict.

Where the observed wave comes from: the server reads no screen. `current_battle.observed_wave` is the last wave the standalone COLLECTOR published on its battle
record (`wave_source: "collector_record"`); with no collector record there is no server-side wave (`wave_source: "none"`, everything null) and the person confirms
a battle the worker will prove from the screen. The dialog sends back the `current_battle` ids and wave it was shown as `attach.expected_battle`.

Volatile values are replaced by stable names: ids by `<id-N>` in order of appearance, digests by `<sha256>` (except `policy_revision`, which is a function of the
run), times by `<time>`, the temporary root by `<root>`. The worker failure after acceptance (`failed_after_accept`) is the ledger transition the worker's
failure writes (`{status: failed, error: {code, message}}`); the codes themselves (attach_*) belong to the worker (T3b) and are named here as the spec names them.
"""
