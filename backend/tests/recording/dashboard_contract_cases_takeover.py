def launch_free(app, rec):
    request = body(app, tier={'value': 15, 'provenance': 'declared'}, key='takeover-key-1')
    first = rec.add('accepted_nothing_owns_the_emulator', app.client.post('/api/control', json=request), request)
    rec.cases['accepted_nothing_owns_the_emulator']['envelope'] = rec.scrub(attach_of(app, first['operation_id']))
    rec.add('identical_retry_replays_the_receipt', app.client.post('/api/control', json=request), request)
    store = operations.ledger(app.dash.ROOT)
    op = store.get(first['operation_id'])
    op = store.transition(op['id'], op['revision'], 'running', worker={'pid': 1, 'creation_time': 1.0})
    store.transition(op['id'], op['revision'], 'failed', error={'code': 'attach_no_battle', 'message': 'No battle is on screen; nothing was sent to the game'})
    rec.add('failed_after_accept_read_back_by_the_same_request', app.client.post('/api/control', json=request), request)
    rec.add('failed_after_accept_read_by_id', app.client.get(f"/api/operations/{first['operation_id']}"))
    changed = json.loads(json.dumps(request))
    changed['attach']['tier'] = {'value': None, 'provenance': 'unknown'}
    rec.add('same_key_changed_request_is_uncoded_409', app.client.post('/api/control', json=changed), changed)


def launch_collector(app, rec):
    running, store, battle = collector(app)
    request = body(app, key='takeover-key-2')
    got = rec.add('accepted_collector_transferred', app.client.post('/api/control', json=request), request)
    rec.cases['accepted_collector_transferred']['envelope'] = rec.scrub(attach_of(app, got['operation_id']))
    store.finish(battle['id'], 'g1', reason='driver_operation_ended', status='interrupted')       # what the worker does after its entry gate
    op = operations.ledger(app.dash.ROOT).get(got['operation_id'])
    created = store.create(op['id'], op['context'], op['request']['battle_envelope'], generation='g2', origin='partial_adoption', previous_battle_id=battle['id'])
    rec.add('battle_after_taking_over_the_collectors_battle', app.client.get('/api/battles/active'),
            pick=lambda got_: {'battle': {name: got_['battle'].get(name) for name in BATTLE_KEYS if name in got_['battle']}})
    assert created['id'] == app.client.get('/api/battles/active').get_json()['battle']['id']
    store.update_status(created['id'], 'g2', {'observed_wave': 4390})                                  # the battle moves on; the entry observation is a separate fact
    rec.add('battle_with_the_later_wave_but_no_entry_observation', app.client.get('/api/battles/active'),
            pick=lambda got_: {'battle': {name: got_['battle'].get(name) for name in BATTLE_KEYS if name in got_['battle']}})


def refusals(app, rec):
    shown = preview(app)
    for case, change in (('reserved_field', dict(harvest=True)), ('unknown_field', dict(surprise=1))):
        request = body(app, shown=shown, **change)
        rec.add(f'invalid_{case}', app.client.post('/api/control', json=request), request)
    request = body(app, shown=shown, attach_changes={'attestation': 'yes'})
    rec.add('invalid_attestation', app.client.post('/api/control', json=request), request)
    request = body(app, shown=shown)
    del request['attach']
    rec.add('invalid_missing_attach', app.client.post('/api/control', json=request), request)
    request = body(app, shown=shown, attach_changes={'policy_revision': '0' * 64})
    rec.add('policy_changed', app.client.post('/api/control', json=request), request)
    request = body(app, shown=shown)
    request['expected_context']['account'] = 'someone-else'
    rec.add('context_changed', app.client.post('/api/control', json=request), request)
    request = body(app, shown=shown, preset='bp_missing')
    rec.add('invalid_unknown_run', app.client.post('/api/control', json=request), request)
    app.readiness.missing = [missing_row(readiness.IN_TOURNAMENT)]
    request = body(app, shown=shown)
    rec.add('tournament_recognition_missing', app.client.post('/api/control', json=request), request)
    app.readiness.missing = [missing_row('home/example_dialog.png')]
    rec.add('calibration_needed', app.client.post('/api/control', json=request), request)
    app.readiness.missing = []
    real = app.dash._compiled_runs
    app.monkeypatch.setattr(app.dash, '_compiled_runs', lambda cfg: {**real(cfg), 'bp_farm': dict(real(cfg)['bp_farm'], max_wave=500)})
    rec.add('takeover_not_compatible', app.client.post('/api/control', json=request), request)
    app.monkeypatch.setattr(app.dash, '_compiled_runs', real)
    assert app.dash._ACTION_LOCK.acquire(blocking=False)
    try:
        rec.add('action_lock', app.client.post('/api/control', json=request), request)
    finally:
        app.dash._ACTION_LOCK.release()
    app.rows.append({'pid': 4242, 'runner': 'orchestrator', 'cmdline': 'python orchestrator.py'})
    rec.add('device_owned_by_another_runner', app.client.post('/api/control', json=request), request)
    assert ops(app) == []


def refusals_collector(app, rec):
    running, store, battle = collector(app)
    shown = preview(app)
    request = body(app, shown=shown, attach_changes={'expected_battle': {'battle_id': None, 'generation': None, 'observed_wave': None}})
    rec.add('attach_battle_changed', app.client.post('/api/control', json=request), request)
    app.psutil.lingering = True
    request = body(app, shown=shown)
    rec.add('collector_stopping', app.client.post('/api/control', json=request), request)
    assert all(op['kind'] == 'gems' for op in ops(app))


def attached_battle(app, rec):
    """A taken-over battle that is live: a live control, the unknown-outcome 5xx and its replay, then a person's Stop and what is read after it."""
    running, store, battle = collector(app)
    request = body(app, key='takeover-key-3')
    got = app.client.post('/api/control', json=request).get_json()
    ops_store = operations.ledger(app.dash.ROOT)
    op = ops_store.get(got['operation_id'])
    op = ops_store.transition(op['id'], op['revision'], 'running', worker={'pid': 1, 'creation_time': 1.0})
    store.finish(battle['id'], 'g1', reason='driver_operation_ended', status='interrupted')
    created = store.create(op['id'], op['context'], op['request']['battle_envelope'], generation='g2', origin='partial_adoption', previous_battle_id=battle['id'])
    store.activate(created['id'], 'g2', {'controls': ['routines.ad_gems.enabled'], 'actions': []})
    url = f"/api/operations/{op['id']}/live-controls"
    control = {'battle_id': created['id'], 'generation': 'g2', 'expected_revision': 0, 'idempotency_key': 'attached-control-1', 'changes': {'routines.ad_gems.enabled': False}}
    lost = control
    real = battle_api.public
    app.monkeypatch.setattr(battle_api, 'public', lambda *a, **k: (_ for _ in ()).throw(KeyError('battle row vanished')))
    rec.add('live_control_recorded_but_unreadable_is_a_500_outcome_unknown', app.client.post(url, json=lost), lost)
    app.monkeypatch.setattr(battle_api, 'public', real)
    rec.add('the_same_request_reads_the_recorded_command_back_accepted', app.client.post(url, json=lost), lost, pick=lambda got_: {'ok': got_['ok'], 'command': {name: got_['command'].get(name) for name in ('id', 'kind', 'state') if name in got_['command']}})
    stop = {'expected_revision': op['revision']}
    pending = dict(control, expected_revision=1, idempotency_key='attached-control-2', changes={'routines.ad_gems.enabled': True})
    rec.add('second_control_while_the_first_is_pending_is_an_uncoded_409', app.client.post(url, json=pending), pending)
    rec.add('stop_automation', app.client.post(f"/api/operations/{op['id']}/cancel", json=stop), stop)
    rec.add('operation_after_stop', app.client.get(f"/api/operations/{op['id']}"))
    battle_api.reconcile_existing(app.dash.ROOT)                          # the refresher's reconcile: the record of a driver that is gone finishes `interrupted`
    rec.add('battle_after_stop_is_interrupted_and_the_game_battle_is_untouched', app.client.get(f"/api/battles/{created['id']}"),
            pick=lambda got_: {'battle': {name: got_['battle'].get(name) for name in BATTLE_KEYS + ('reason', 'end_reason') if name in got_['battle']}})
    rec.add('retrying_the_takeover_after_stop_replays_the_receipt', app.client.post('/api/control', json=request), request,
            pick=lambda got_: {'ok': got_['ok'], 'operation_id': got_['operation_id'], 'status': got_['operation']['status']})


def real_worker(app, rec, monkeypatch, tmp_path):
    """The REAL T3b worker (orchestrator.main) on operations the REAL route accepted: what it writes is what is recorded, nothing is stood in."""
    running, store, battle = collector(app, wave=4200)
    request = body(app, key='real-worker-1')
    got = app.client.post('/api/control', json=request).get_json()
    ledger = operations.ledger(app.dash.ROOT)
    op = ledger.get(got['operation_id'])
    ledger.transition(op['id'], op['revision'], 'running', worker={'pid': 1, 'creation_time': 1.0})
    ledger.transition(running['id'], ledger.get(running['id'])['revision'], 'cancelled') if ledger.get(running['id'])['status'] in ('accepted', 'running') else None
    outcome, taps = run_worker(app, op['id'], [frame(wave=4388), frame(wave=4390)], monkeypatch, tmp_path)
    assert outcome == 'looping' and taps == []
    rec.add('battle_read_after_the_real_worker_entered', app.client.get('/api/battles/active'),
            pick=lambda got_: {'battle': {name: got_['battle'].get(name) for name in BATTLE_KEYS if name in got_['battle']}, 'runtime_attach_entry': got_['battle']['runtime'].get('attach_entry')})
    rec.add('collector_record_after_the_real_worker_entered', app.client.get(f"/api/battles/{battle['id']}"),
            pick=lambda got_: {'battle': {name: got_['battle'].get(name) for name in ('status', 'end_reason', 'reason') if name in got_['battle']}})


def real_worker_refused(app, rec, monkeypatch, tmp_path):
    """The real worker refusing at its entry gate: the failed operation is what the UI reads, and no battle record exists."""
    request = body(app, key='real-worker-2')
    got = app.client.post('/api/control', json=request).get_json()
    ledger = operations.ledger(app.dash.ROOT)
    op = ledger.get(got['operation_id'])
    ledger.transition(op['id'], op['revision'], 'running', worker={'pid': 1, 'creation_time': 1.0})
    outcome, taps = run_worker(app, op['id'], [frame(screen='home', wave=None)], monkeypatch, tmp_path)
    assert outcome == 'returned' and taps == []
    rec.add('operation_after_the_real_worker_refused', app.client.get(f"/api/operations/{op['id']}"),
            pick=lambda got_: {'operation': {name: got_['operation'].get(name) for name in ('status', 'error')}})
    rec.add('no_battle_after_the_real_worker_refused', app.client.get('/api/battles/active'), pick=lambda got_: {'battle': got_['battle']})
    rec.add('same_request_reads_the_failed_operation_back', app.client.post('/api/control', json=request), request,
            pick=lambda got_: {'ok': got_['ok'], 'operation_id': got_['operation_id'], 'status': got_['operation']['status'], 'error': got_['operation']['error']})


