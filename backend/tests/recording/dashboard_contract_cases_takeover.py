VERSION = 1
UUID = re.compile(r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')
HEX64 = re.compile(r'^[0-9a-f]{64}$')
TIME_KEYS = ('server_time', 'timestamp', 'creation_time')
# Volatile numbers keep their TYPE (the UI schema reads numbers): a socket the OS picked, the test process's pid, a real wait, and every timestamp become fixed numbers.
PLACEHOLDER_KEYS = {'adb_port': 50000, 'pid': 4242, 'waited_sec': 0.0}
FIXED_TIME = 1800000000.0
BATTLE_KEYS = ('id', 'origin', 'status', 'previous_battle_id', 'start_certainty', 'label', 'blueprint', 'wave', 'wave_provenance', 'attach', 'lineage')


class Scrubber:
    def __init__(self, root):
        self.root, self.ids = str(root), {}

    def __call__(self, value, key=None):
        if isinstance(value, dict):
            return {name: self(item, name) for name, item in value.items()}
        if isinstance(value, list):
            return [self(item, key) for item in value]
        if isinstance(value, str):
            if UUID.match(value):
                return self.ids.setdefault(value, f'<id-{len(self.ids) + 1}>')
            if HEX64.match(value) and key != 'policy_revision' and key != 'current_policy_revision':
                return '<sha256>'
            return value.replace(self.root, '<root>').replace('\\', '/')
        if isinstance(value, float) and (key in TIME_KEYS or (key or '').endswith('_at')):
            return FIXED_TIME
        if key in PLACEHOLDER_KEYS and isinstance(value, (int, float)) and not isinstance(value, bool):
            return PLACEHOLDER_KEYS[key]
        return value


class Recorder:
    def __init__(self, app):
        self.app, self.scrub, self.cases = app, Scrubber(app.dash.ROOT), {}
        for module in (harvest_http, takeover_http):                      # request keys count from 1 in every recording, and the counters are put back after
            app.monkeypatch.setattr(module, 'KEY', itertools.count(1))

    def add(self, name, reply, request=None, pick=None):
        got = reply.get_json()
        if pick:
            got = pick(got)
        self.cases[name] = {'request': self.scrub(request), 'status': reply.status_code, 'response': self.scrub(got)}
        return reply.get_json()


def collector(app, wave=4200):
    enable(app)
    running = running_collector(app)
    store, battle = _battle_for(app, running)
    store.update_status(battle['id'], battle['generation'], {'observed_wave': wave})
    app.rows.append(collector_row(running))
    return running, store, store.get(battle['id'])


def attach_of(app, operation_id):
    envelope = operations.ledger(app.dash.ROOT).get(operation_id)['request']['battle_envelope']
    return {'attach': envelope['attach'], 'preset_key': envelope['preset_key'], 'config_preset_is_key': envelope['config']['preset'] == envelope['preset_key'],
            'preset_equals_frozen_run': envelope['preset'] == envelope['config']['presets'][envelope['preset_key']],
            'repeat_enabled': envelope['controls']['routines']['repeat']['enabled'], 'rewards_enabled': envelope['controls']['routines']['rewards']['enabled']}


