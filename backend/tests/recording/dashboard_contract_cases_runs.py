"""Contract cases of the Runs page: saving a run's routine controls, and the live-controls save of a battle.

Two families (generated by test_dashboard_contract_pages.py into dashboard_contract_pages_v1.json):

  run_controls_save   POST /api/run-controls - the SAVED run (the profile file), compare-and-set on
                      `profile_revision`, with the account/emulator/profile `context` its read named;
  run_controls_live   POST /api/operations/{id}/live-controls - the TRACKED BATTLE's overrides, compare-and-set
                      on `control_revision`, idempotent by `idempotency_key`.

Every case is a request the real route answered over synthetic state. A "read" case is the GET a client
makes afterwards to settle an answer it did not get or did not understand; the case name says which write
it follows. A write whose reply the client never saw is generated by really performing the write and then
recording only the read (nothing in the fixture is a hand-made answer).
"""
import copy
import json
from pathlib import Path

import yaml

from control import operations
from dashboard_contract_pages_world import raw_post
from test_dashboard_contract import Driver, PLAN_V2, action_url, raising, recorded_commands

SAVE, LIVE = 'run_controls_save', 'run_controls_live'
RUN = '/api/run-controls'


# ------------------------------------------------------------------ saved run
def read_run(w, case=None, run='farm', family=SAVE):
    """GET /api/run-controls for `run`; recorded when `case` is given."""
    path = f'{RUN}?blueprint={run}'
    response = w.get(family, case, path) if case else w.client.get(path)
    return response.get_json()


def save_body(read, changes, **override):
    """The body the Runs page sends: the run, the context and revision of the read it was edited from, only the changed paths."""
    body = dict(blueprint='farm', context=read['context'], expected_revision=read['profile_revision'], changes=changes)
    body.update(override)
    return body


def save(w, case, read, changes, **override):
    return w.post(SAVE, case, RUN, save_body(read, changes, **override)).get_json()


def with_a_second_run(w, kind='shard', *, valid=True):
    """A second run of the profile. `shard` supports fewer controls than the coin run (and says so in `notice`).
    valid=False leaves it with a loadout its kind may not use, so the profile has a problem the saves did not cause."""
    def add(profile):
        other = copy.deepcopy(profile['blueprints']['farm'])
        other['kind'] = kind
        if valid and kind != 'coin':
            other['loadout'] = 'plain'
        profile['blueprints']['other'] = other
    if valid and kind != 'coin':
        w.edit_config(lambda cfg: cfg['loadouts'].update(plain={}))
    w.edit_profile(add)


def copy_profile(w, source, target, tweak=None):
    profiles = Path(w.root) / 'profiles'
    data = yaml.safe_load((profiles / f'{source}.yaml').read_text(encoding='utf-8'))
    if tweak:
        tweak(data)
    (profiles / f'{target}.yaml').write_text(yaml.safe_dump(data), encoding='utf-8')


def saved_run_succeeds(gen):
    with gen.world('rcs_ok') as w:
        first = read_run(w, 'read_before_the_first_save')
        one = save(w, 'saved_switch_off', first, {'routines.ad_gems.enabled': False})
        assert one['ok'] and one['profile_revision'] != first['profile_revision']
        assert one['settings']['routines']['ad_gems']['enabled'] is False
        again = read_run(w, 'read_after_the_save_holds_the_new_values')
        assert again['profile_revision'] == one['profile_revision'] and again['settings'] == one['settings']
        two = save(w, 'saved_numbers_with_the_revision_of_the_last_save', one,
                   {'routines.ad_gems.interval_sec': 900, 'routines.ad_gems.window_sec': 30,
                    'routines.floating_gems.interval_sec': 1200, 'routines.floating_gems.tap_interval_sec': 2.5})
        assert two['settings']['routines']['ad_gems']['interval_sec'] == 900
        assert two['settings']['routines']['floating_gems']['tap_interval_sec'] == 2.5
        three = save(w, 'saved_switches_and_numbers_in_one_request', two,
                     {'routines.floating_gems.enabled': True, 'routines.shopping.enabled': True,
                      'routines.shopping.interval_sec': 120, 'routines.rewards.enabled': False,
                      'routines.abilities.enabled': False})
        # the switch alone cannot turn shopping on for a run with no shopping queue: the effective value is still off
        assert three['settings']['routines']['shopping'] == {'enabled': False, 'interval_sec': 120}
        four = save(w, 'saved_null_returns_a_number_to_its_default', three, {'routines.ad_gems.interval_sec': None})
        assert four['settings']['routines']['ad_gems']['interval_sec'] == first['settings']['routines']['ad_gems']['interval_sec']
        five = save(w, 'saved_run_given_as_the_preset_id', four, {'routines.repeat.enabled': False}, blueprint='bp_farm')
        assert five['blueprint'] == 'farm' and five['settings']['routines']['repeat']['enabled'] is False
        w.post(SAVE, 'saved_with_the_nested_form_the_run_key_and_the_patch_key', RUN,
               dict(run='farm', context=five['context'], expected_revision=five['profile_revision'],
                    patch={'routines': {'rescue': {'enabled': False}}}))
        final = read_run(w, 'read_after_several_saves')
        assert final['settings']['routines']['rescue']['enabled'] is False and final['settings']['routines']['repeat']['enabled'] is False
    with gen.world('rcs_shopping_plan') as w:
        first = read_run(w, 'read_before_the_plan_save')
        planned = save(w, 'saved_shopping_plan_v2', first, {'shopping_plan': PLAN_V2})
        assert planned['settings']['shopping_plan']['version'] == 2 and planned['settings']['routines']['shopping']['enabled'] is True
        off = save(w, 'saved_shopping_switch_off_keeps_the_plan', planned, {'routines.shopping.enabled': False})
        assert off['settings']['routines']['shopping']['enabled'] is False and off['settings']['shopping_plan']['version'] == 2
        planned = save(w, 'saved_shopping_switch_on_again_with_a_plan', off, {'routines.shopping.enabled': True})
        assert planned['settings']['routines']['shopping']['enabled'] is True
        w.post(SAVE, 'saved_shopping_plan_null_refused', RUN, save_body(planned, {'shopping_plan': None}))
        w.post(SAVE, 'saved_shopping_plan_invalid_refused', RUN,
               save_body(planned, {'shopping_plan': dict(PLAN_V2, queue=[{'id': 'no_such_upgrade', 'enabled': True}])}))
    with gen.world('rcs_shared_policy') as w:
        # two runs share the profile's gather policy; a save on one clones it, the other keeps its values
        with_a_second_run(w, 'coin')
        w.edit_profile(lambda profile: profile['blueprints']['other'].update(policies={'gather': 'shared'}))
        before = read_run(w, 'read_of_the_first_run_before_it_is_saved')
        sibling = read_run(w, 'read_of_the_second_run_sharing_its_policy', 'other')
        save(w, 'saved_the_first_run_only', before, {'routines.ad_gems.enabled': False, 'routines.ad_gems.interval_sec': 600})
        after = read_run(w, 'read_of_the_second_run_after_the_first_was_saved', 'other')
        assert after['settings'] == sibling['settings'], 'saving one run changed a run that shares its policy'
    with gen.world('rcs_limited_run') as w:
        with_a_second_run(w, 'shard')
        limited = read_run(w, 'read_of_a_run_with_fewer_controls', 'other')
        assert limited.get('notice') and 'routines.shopping.enabled' not in limited['capabilities']['controls']
        supported = save(w, 'saved_a_control_the_run_supports', limited, {'routines.ad_gems.enabled': False}, blueprint='other')
        assert supported['ok'] and supported['settings']['routines']['ad_gems']['enabled'] is False
        w.post(SAVE, 'refused_a_control_the_run_does_not_support', RUN,
               save_body(limited, {'routines.shopping.enabled': True}, blueprint='other'))
        w.post(SAVE, 'refused_the_shopping_plan_the_run_does_not_support', RUN,
               save_body(limited, {'shopping_plan': PLAN_V2}, blueprint='other'))

def saved_run_refuses_bad_values(gen):
    with gen.world('rcs_invalid') as w:
        r = read_run(w, 'read_before_the_refusals')
        invalid = (('invalid_below_the_minimum', {'routines.ad_gems.interval_sec': 0}),
                   ('invalid_above_the_maximum', {'routines.ad_gems.window_sec': 61}),
                   ('invalid_decimal_below_the_minimum', {'routines.floating_gems.tap_interval_sec': 0.4}),
                   ('invalid_text_for_a_number', {'routines.ad_gems.interval_sec': 'abc'}),
                   ('invalid_empty_text_for_a_number', {'routines.ad_gems.interval_sec': ''}),
                   ('invalid_true_for_a_number', {'routines.ad_gems.interval_sec': True}),
                   ('invalid_number_for_a_switch', {'routines.ad_gems.enabled': 1}),
                   ('invalid_text_for_a_switch', {'routines.ad_gems.enabled': 'on'}),
                   ('one_invalid_path_refuses_the_whole_request', {'routines.ad_gems.enabled': False, 'routines.ad_gems.window_sec': 4}))
        for case, changes in invalid:
            reply = w.post(SAVE, case, RUN, save_body(r, changes))
            assert reply.status_code == 400 and reply.get_json()['ok'] is False, case
        unchanged = read_run(w, 'read_after_the_refusals_nothing_changed')
        assert unchanged == r, 'a refused save changed the saved run'
    with gen.world('rcs_unknown') as w:
        r = read_run(w)
        for case, changes in (('unknown_control', {'routines.ad_gems.speed': 3}),
                              ('unknown_routine', {'routines.coffee.enabled': True}),
                              ('path_without_a_field', {'routines.ad_gems': True}),
                              ('path_with_too_many_parts', {'routines.ad_gems.enabled.now': True}),
                              ('path_outside_routines', {'settings.ad_gems.enabled': True}),
                              ('nested_form_with_an_unknown_field', {'extras': {'a': 1}}),
                              ('nested_form_with_an_unknown_routine', {'routines': {'coffee': {'enabled': True}}}),
                              ('changes_empty', {}),
                              ('changes_a_list', []),
                              ('changes_text', 'routines.ad_gems.enabled')):
            assert w.post(SAVE, case, RUN, save_body(r, changes)).status_code == 400, case
        missing = save_body(r, None)
        del missing['changes']
        assert w.post(SAVE, 'changes_missing', RUN, missing).status_code == 400
        for case, run in (('unknown_run', 'nope'), ('combo_is_no_run', 'combo'), ('run_missing', None), ('run_not_text', 5)):
            body = save_body(r, {'routines.ad_gems.enabled': False}, blueprint=run)
            assert w.post(SAVE, case, RUN, body).status_code == 400, case
        assert w.post(SAVE, 'body_a_list', RUN, []).status_code == 400
        assert raw_post(w, SAVE, 'body_not_json', RUN, 'routines.ad_gems.enabled=false', content_type='text/plain').status_code == 400
        assert w.post(SAVE, 'body_missing', RUN).status_code == 400
        assert read_run(w) == r
    with gen.world('rcs_nonfinite') as w:
        # NaN and Infinity cannot be written in the (strict JSON) fixture; the route is asserted instead
        r = read_run(w)
        for text in ('NaN', 'Infinity', '-Infinity', '1e999'):
            body = ('{"blueprint": "farm", "expected_revision": "%s", "context": %s, "changes": {"routines.ad_gems.interval_sec": %s}}'
                    % (r['profile_revision'], json.dumps(r['context']), text))
            reply = w.client.post(RUN, data=body, content_type='application/json')
            assert reply.status_code == 400 and 'Invalid value' in reply.get_json()['error'], (text, reply.get_json())
        assert read_run(w) == r


def saved_run_refuses_a_changed_target(gen):
    with gen.world('rcs_conflicts') as w:
        r = read_run(w, 'read_before_the_conflicts')
        change = {'routines.ad_gems.enabled': False}
        context = r['context']
        missing = save_body(r, change)
        del missing['context']
        assert w.post(SAVE, 'context_missing', RUN, missing).status_code == 409
        for case, field, value in (('context_other_emulator', 'instance', 'other'), ('context_other_profile', 'profile', 'theirs'),
                                   ('context_other_account', 'account', 'beta')):
            reply = w.post(SAVE, case, RUN, save_body(r, change, context=dict(context, **{field: value})))
            assert reply.status_code == 409 and 'changed' in reply.get_json()['error'], case
        no_profile = {k: v for k, v in context.items() if k != 'profile'}
        assert w.post(SAVE, 'context_with_a_member_missing', RUN, save_body(r, change, context=no_profile)).status_code == 409
        # another client saves first: this client's revision is stale
        assert w.plain_post(RUN, save_body(r, {'routines.floating_gems.enabled': True})).status_code == 200
        stale = w.post(SAVE, 'stale_revision_another_client_saved_first', RUN, save_body(r, change))
        assert stale.status_code == 409 and 'Saved run changed' in stale.get_json()['error']
        seen = read_run(w, 'read_after_the_stale_refusal_holds_the_other_clients_save')
        assert seen['settings']['routines']['floating_gems']['enabled'] is True and seen['settings']['routines']['ad_gems']['enabled'] is True
        w.post(SAVE, 'stale_revision_is_judged_before_the_values', RUN, save_body(r, {'routines.ad_gems.window_sec': 4}))
        w.post(SAVE, 'context_is_judged_before_the_revision', RUN, save_body(r, change, context=dict(context, instance='other')))
        for case, revision in (('expected_revision_null', None), ('expected_revision_a_number', 3), ('expected_revision_empty_text', '')):
            assert w.post(SAVE, case, RUN, save_body(r, change, expected_revision=revision)).status_code == 409, case
        no_revision = save_body(r, change)
        del no_revision['expected_revision']
        assert w.post(SAVE, 'expected_revision_missing', RUN, no_revision).status_code == 409
        assert w.post(SAVE, 'saved_again_with_the_revision_just_read', RUN, save_body(seen, change)).status_code == 200
    with gen.world('rcs_context_changed') as w:
        r = read_run(w, 'read_before_the_profile_changes')
        copy_profile(w, 'mine', 'second', lambda profile: profile['policies']['gather']['shared'].update(gem_delay_sec=[5, 12]))
        w.edit_config(lambda cfg: cfg.update(active_profile='second'))
        assert w.post(SAVE, 'context_changed_after_the_read', RUN, save_body(r, {'routines.ad_gems.enabled': False})).status_code == 409
        now = read_run(w, 'read_after_the_context_changed_names_the_new_profile')
        assert now['context']['profile'] == 'second' and now['profile_revision'] != r['profile_revision']
    with gen.world('rcs_action_lock') as w:
        r = read_run(w, 'read_before_the_action_lock')
        assert w.dash._ACTION_LOCK.acquire(blocking=False)
        try:
            locked = w.post(SAVE, 'action_lock_another_action_in_progress', RUN, save_body(r, {'routines.ad_gems.enabled': False}))
        finally:
            w.dash._ACTION_LOCK.release()
        assert locked.status_code == 409 and locked.get_json()['code'] == 'action_lock'
        assert read_run(w, 'read_after_the_action_lock_nothing_saved') == r


def saved_run_of_a_profile_that_cannot_be_edited(gen):
    save_anyway = dict(blueprint='farm', context={}, expected_revision=None, changes={'routines.ad_gems.enabled': False})
    with gen.world('rcs_no_profile') as w:
        w.edit_config(lambda cfg: cfg.update(active_profile=None))
        w.get(SAVE, 'read_without_an_active_profile', f'{RUN}?blueprint=farm')
        w.post(SAVE, 'save_without_an_active_profile', RUN, save_anyway)
    with gen.world('rcs_profile_file_missing') as w:
        w.edit_config(lambda cfg: cfg.update(active_profile='ghost'))
        w.get(SAVE, 'read_of_a_profile_whose_file_is_missing', f'{RUN}?blueprint=farm')
        w.post(SAVE, 'save_of_a_profile_whose_file_is_missing', RUN, save_anyway)
    with gen.world('rcs_starter') as w:
        copy_profile(w, 'mine', 'default')
        w.edit_config(lambda cfg: cfg.update(active_profile='default'))
        r = read_run(w, 'read_of_the_shipped_starter_is_allowed')
        reply = w.post(SAVE, 'starter_profile_is_read_only', RUN, save_body(r, {'routines.ad_gems.enabled': False}))
        assert reply.status_code == 409 and 'editable profile' in reply.get_json()['error']
    with gen.world('rcs_draft') as w:
        copy_profile(w, 'mine', 'mine.draft')
        w.edit_config(lambda cfg: cfg.update(active_profile='mine.draft'))
        r = read_run(w, 'read_of_a_scan_draft_is_allowed')
        assert w.post(SAVE, 'scan_draft_is_read_only', RUN, save_body(r, {'routines.ad_gems.enabled': False})).status_code == 409
    with gen.world('rcs_foreign') as w:
        copy_profile(w, 'mine', 'theirs')

        def two_accounts(cfg):
            cfg['accounts'] = {'alpha': {'label': 'Alpha', 'active_profile': 'theirs', 'loadouts': {}},
                               'beta': {'label': 'Beta', 'active_profile': 'theirs', 'loadouts': {}}}
            cfg['instances']['main']['account'] = 'alpha'
        w.edit_config(two_accounts)
        r = read_run(w, 'read_of_another_accounts_profile_is_allowed')
        assert r['context']['account'] == 'alpha' and r['context']['profile'] == 'theirs'
        assert w.post(SAVE, 'another_accounts_profile_is_read_only', RUN, save_body(r, {'routines.ad_gems.enabled': False})).status_code == 409
    with gen.world('rcs_other_run_problem') as w:
        # another run of the profile has a problem: the validator refuses a save of this run too
        with_a_second_run(w, 'shard', valid=False)
        r = read_run(w, 'read_of_a_run_whose_profile_has_a_problem_in_another_run')
        refused = w.post(SAVE, 'save_refused_for_a_problem_in_another_run_of_the_profile', RUN, save_body(r, {'routines.ad_gems.enabled': False}))
        assert refused.status_code == 400 and 'blueprints.other.loadout' in refused.get_json()['error']
    with gen.world('rcs_profile_problem') as w:
        # the profile has a problem the save did not cause
        w.edit_profile(lambda profile: profile['blueprints']['farm'].update(loadout='nope'))
        r = w.get(SAVE, 'read_of_a_profile_with_a_problem', f'{RUN}?blueprint=farm').get_json()
        body = save_body(r, {'routines.ad_gems.enabled': False}) if r.get('ok') else save_anyway
        w.post(SAVE, 'save_of_a_profile_with_a_problem', RUN, body)


def saved_run_answer_is_lost_or_never_written(gen):
    with gen.world('rcs_write_failed') as w:
        r = read_run(w, 'read_before_the_failed_write')
        w.mp.setattr(w.dash, '_save_yaml_backup', raising(OSError('profiles/mine.yaml could not be written')))
        failed = w.post(SAVE, 'write_failed_nothing_saved_500', RUN, save_body(r, {'routines.ad_gems.enabled': False}))
        assert failed.status_code == 500
        assert read_run(w, 'read_after_the_failed_write_the_revision_is_unchanged') == r
    with gen.world('rcs_answer_failed') as w:
        r = read_run(w, 'read_before_the_unanswered_save')
        real, calls = operations.file_revision, []

        def revision_then_fail(path):
            calls.append(path)
            if len(calls) == 2:
                raise OSError('the saved profile could not be read back')
            return real(path)
        body = save_body(r, {'routines.ad_gems.enabled': False, 'routines.ad_gems.interval_sec': 600})
        w.mp.setattr(operations, 'file_revision', revision_then_fail)
        failed = w.post(SAVE, 'saved_then_the_answer_failed_500', RUN, body)
        assert failed.status_code == 500 and len(calls) == 2
        w.mp.setattr(operations, 'file_revision', real)
        held = read_run(w, 'read_after_the_unanswered_save_holds_every_sent_value')
        assert held['profile_revision'] != r['profile_revision']
        assert held['settings']['routines']['ad_gems']['enabled'] is False and held['settings']['routines']['ad_gems']['interval_sec'] == 600
        resend = w.post(SAVE, 'identical_resend_after_a_committed_save_is_refused_as_stale', RUN, body)
        assert resend.status_code == 409 and 'Saved run changed' in resend.get_json()['error']
        assert read_run(w) == held, 'the refused resend changed the saved run'
    with gen.world('rcs_lost_answer_saved') as w:
        r = read_run(w, 'read_before_the_lost_answer')
        assert w.plain_post(RUN, save_body(r, {'routines.ad_gems.enabled': False})).status_code == 200   # the client never saw this answer
        read = read_run(w, 'read_after_a_lost_answer_the_save_is_there')
        assert read['profile_revision'] != r['profile_revision'] and read['settings']['routines']['ad_gems']['enabled'] is False
    with gen.world('rcs_lost_request') as w:
        r = read_run(w, 'read_before_the_lost_request')
        # the request never arrived: there is nothing to perform; the read is what the first one was
        assert read_run(w, 'read_after_a_lost_request_nothing_was_saved') == r
    with gen.world('rcs_lost_answer_other_client') as w:
        r = read_run(w, 'read_before_the_other_clients_save')
        assert w.plain_post(RUN, save_body(r, {'routines.floating_gems.enabled': True})).status_code == 200   # another client's save
        read = read_run(w, 'read_after_a_lost_answer_a_new_revision_without_the_sent_values')
        assert read['profile_revision'] != r['profile_revision'] and read['settings']['routines']['ad_gems']['enabled'] is True

def run_controls_save_cases(gen):
    saved_run_succeeds(gen)
    saved_run_refuses_bad_values(gen)
    saved_run_refuses_a_changed_target(gen)
    saved_run_of_a_profile_that_cannot_be_edited(gen)
    saved_run_answer_is_lost_or_never_written(gen)


# ------------------------------------------------------------- live controls
def live_url(d):
    return action_url(d.op, 'live-controls')


def live_body(d, changes, key, **override):
    battle = d.battle
    body = dict(battle_id=battle['id'], generation=d.generation, expected_revision=battle['control_revision'],
                idempotency_key=key, changes=changes)
    body.update(override)
    return body


def live(w, case, d, changes, key, **override):
    return w.post(LIVE, case, live_url(d), live_body(d, changes, key, **override))


def active_battle(w, case):
    return w.get(LIVE, case, '/api/battles/active')


def live_change_succeeds(gen):
    with gen.world('rcl_accepted') as w:
        d = Driver(w).go_live()
        active_battle(w, 'read_before_the_first_change')
        first = live(w, 'accepted_switch_off', d, {'routines.ad_gems.enabled': False}, 'live-1')
        assert first.status_code == 200 and first.get_json()['command']['state'] == 'requested'
        assert first.get_json()['control_revision'] == 1
        listed = active_battle(w, 'read_after_the_change_lists_the_command_and_its_key').get_json()
        assert [c['request_keys'] for c in listed['battle']['commands']] == [['live-1']]
        replay = live(w, 'identical_retry_answered_from_the_record', d, {'routines.ad_gems.enabled': False}, 'live-1', expected_revision=0)
        assert replay.status_code == 200 and replay.get_json()['command']['id'] == first.get_json()['command']['id']
        assert len(recorded_commands(d)) == 1
        other = live_body(d, {'routines.ad_gems.enabled': True}, 'live-1', expected_revision=0)
        assert w.post(LIVE, 'same_key_with_other_changes_refused', live_url(d), other).status_code == 409
        stale = live_body(d, {'routines.ad_gems.interval_sec': 600}, 'live-2', expected_revision=0)
        assert w.post(LIVE, 'stale_control_revision_refused', live_url(d), stale).status_code == 409
        pending = live_body(d, {'routines.ad_gems.interval_sec': 600}, 'live-3')
        assert w.post(LIVE, 'second_change_while_the_first_is_not_applied_refused', live_url(d), pending).status_code == 409
        d.checkpoint()      # the driver applies the first change at its next safe point
        applied = active_battle(w, 'read_after_the_driver_applied_the_change').get_json()['battle']
        assert applied['applied_revision'] == applied['control_revision'] == 1 and applied['commands'][0]['state'] == 'applied'
        live(w, 'accepted_numbers_after_the_previous_change_applied', d,
             {'routines.ad_gems.interval_sec': 600, 'routines.ad_gems.window_sec': 20}, 'live-4')
        d.checkpoint()
        live(w, 'accepted_null_resets_a_path_to_the_battles_starting_value', d, {'routines.ad_gems.interval_sec': None}, 'live-5')
        d.checkpoint()
        live(w, 'accepted_several_paths_in_one_command', d,
             {'routines.floating_gems.enabled': True, 'routines.floating_gems.interval_sec': 900,
              'routines.floating_gems.tap_interval_sec': 2.5, 'routines.shopping.enabled': True,
              'routines.shopping.interval_sec': 60}, 'live-6')
        d.checkpoint()
        live(w, 'accepted_with_the_nested_form', d, {'routines': {'rewards': {'enabled': False}}}, 'live-7')
        d.checkpoint()
        final = active_battle(w, 'read_after_several_changes_overrides_and_applied_values').get_json()['battle']
        assert final['applied_revision'] == final['control_revision'] == 5 and final['overrides']
        assert [c['state'] for c in final['commands']] == ['applied'] * 5


def live_change_is_invalid(gen):
    with gen.world('rcl_invalid') as w:
        d = Driver(w).go_live()
        before = active_battle(w, 'read_before_the_refusals').get_json()['battle']
        for n, (case, changes) in enumerate((
                ('invalid_below_the_minimum', {'routines.ad_gems.interval_sec': 0}),
                ('invalid_above_the_maximum', {'routines.ad_gems.window_sec': 61}),
                ('invalid_decimal_below_the_minimum', {'routines.floating_gems.tap_interval_sec': 0.4}),
                ('invalid_text_for_a_number', {'routines.ad_gems.interval_sec': 'abc'}),
                ('invalid_true_for_a_number', {'routines.ad_gems.interval_sec': True}),
                ('invalid_number_for_a_switch', {'routines.ad_gems.enabled': 1}),
                ('unknown_control', {'routines.ad_gems.speed': 3}),
                ('unknown_routine', {'routines.coffee.enabled': True}),
                ('path_without_a_field', {'routines.ad_gems': True}),
                ('one_invalid_path_refuses_the_whole_command', {'routines.ad_gems.enabled': False, 'routines.ad_gems.window_sec': 4}),
                ('changes_empty', {}), ('changes_a_list', []), ('changes_text', 'x'))):
            assert live(w, case, d, changes, f'bad-{n}').status_code == 400, case
        # the shopping plan is a saved-run control: the live driver does not list it
        unsupported = live(w, 'control_the_driver_does_not_support', d, {'shopping_plan': PLAN_V2}, 'bad-plan')
        assert unsupported.status_code == 400 and 'Unsupported controls' in unsupported.get_json()['error']
        gone = live_body(d, {'routines.ad_gems.enabled': False}, 'bad-x')
        del gone['changes']
        assert w.post(LIVE, 'changes_missing', live_url(d), gone).status_code == 400
        for field in ('battle_id', 'generation', 'idempotency_key', 'expected_revision'):
            body = live_body(d, {'routines.ad_gems.enabled': False}, 'bad-y')
            del body[field]
            assert w.post(LIVE, f'{field}_missing', live_url(d), body).status_code == 400, field
        for case, field, value in (('idempotency_key_empty', 'idempotency_key', ''), ('idempotency_key_a_number', 'idempotency_key', 7),
                                   ('expected_revision_text', 'expected_revision', '0'), ('expected_revision_true', 'expected_revision', True),
                                   ('generation_a_number', 'generation', 3)):
            body = live_body(d, {'routines.ad_gems.enabled': False}, 'bad-z', **{field: value})
            assert w.post(LIVE, case, live_url(d), body).status_code == 400, case
        assert w.post(LIVE, 'body_a_list', live_url(d), []).status_code == 400
        assert raw_post(w, LIVE, 'body_not_json', live_url(d), 'routines.ad_gems.enabled=false', content_type='text/plain').status_code == 400
        assert w.post(LIVE, 'body_missing', live_url(d)).status_code == 400
        after = active_battle(w, 'read_after_the_refusals_nothing_was_recorded').get_json()['battle']
        assert after['commands'] == [] and after['control_revision'] == before['control_revision'] == 0


def live_change_meets_the_state_of_the_battle(gen):
    with gen.world('rcl_prepared') as w:
        d = Driver(w)        # launched, no report yet: the driver has not published what it can change
        assert d.battle['status'] == 'prepared'
        refused = live(w, 'prepared_battle_lists_no_controls_refused', d, {'routines.ad_gems.enabled': False}, 'prep-1')
        assert refused.status_code == 400 and 'Unsupported controls' in refused.get_json()['error']
    with gen.world('rcl_wrong_target') as w:
        d = Driver(w).go_live()
        assert live(w, 'stale_generation_refused', d, {'routines.ad_gems.enabled': False}, 'tgt-1', generation='an-older-driver').status_code == 409
        assert live(w, 'unknown_battle_refused', d, {'routines.ad_gems.enabled': False}, 'tgt-2', battle_id='no-such-battle').status_code == 404
        unknown = w.post(LIVE, 'unknown_operation_refused', '/api/operations/no-such-operation/live-controls',
                         live_body(d, {'routines.ad_gems.enabled': False}, 'tgt-3'))
        assert unknown.status_code == 404 and recorded_commands(d) == []
    with gen.world('rcl_driver_gone') as w:
        d = Driver(w).go_live()
        live(w, 'recorded_before_the_driver_ended', d, {'routines.ad_gems.enabled': False}, 'gone-1')
        w.table.exit(d.op['worker']['pid'])
        again = live_body(d, {'routines.floating_gems.enabled': True}, 'gone-2')
        assert w.post(LIVE, 'new_key_refused_the_driver_is_no_longer_active', live_url(d), again).status_code == 409
        replay = w.post(LIVE, 'identical_retry_answered_from_the_record_after_the_driver_ended', live_url(d),
                        live_body(d, {'routines.ad_gems.enabled': False}, 'gone-1', expected_revision=0))
        assert replay.status_code == 200 and len(recorded_commands(d)) == 1
    with gen.world('rcl_battle_ended') as w:
        d = Driver(w).go_live()
        live(w, 'recorded_before_the_battle_ended', d, {'routines.ad_gems.enabled': False}, 'end-1')
        d.end()
        refused = w.post(LIVE, 'new_key_refused_the_battle_has_ended', live_url(d),
                         live_body(d, {'routines.floating_gems.enabled': True}, 'end-2'))
        assert refused.status_code == 409
        replay = w.post(LIVE, 'identical_retry_after_the_battle_ended_answered_from_the_record', live_url(d),
                        live_body(d, {'routines.ad_gems.enabled': False}, 'end-1', expected_revision=0))
        assert replay.status_code == 200
    with gen.world('rcl_replaced') as w:
        first = Driver(w, 'driver-one').go_live()
        w.table.exit(first.op['worker']['pid'])
        second = Driver(w, 'driver-two', adopt=True).go_live()
        stale = live_body(first, {'routines.ad_gems.enabled': False}, 'old-1', expected_revision=0)
        assert w.post(LIVE, 'replaced_battle_refused', live_url(second), stale).status_code == 409
        assert recorded_commands(second) == []
    with gen.world('rcl_action_lock') as w:
        d = Driver(w).go_live()
        body = live_body(d, {'routines.ad_gems.enabled': False}, 'lock-1')
        assert w.dash._ACTION_LOCK.acquire(blocking=False)
        try:
            locked = w.post(LIVE, 'action_lock_another_action_in_progress', live_url(d), body)
        finally:
            w.dash._ACTION_LOCK.release()
        assert locked.status_code == 409 and locked.get_json()['code'] == 'action_lock' and recorded_commands(d) == []
        assert w.post(LIVE, 'retry_after_the_lock_was_released_is_recorded', live_url(d), body).status_code == 200


def live_change_is_recorded_then_the_answer_fails(gen):
    from control import battles as battle_api
    with gen.world('rcl_readback_failed') as w:
        d = Driver(w).go_live()
        body = live_body(d, {'routines.ad_gems.enabled': False}, 'unk-1')
        real = battle_api.public
        w.mp.setattr(battle_api, 'public', raising(KeyError('battle row vanished')))
        unknown = w.post(LIVE, 'admitted_then_the_readback_failed_unknown', live_url(d), body)
        assert unknown.status_code == 500 and unknown.get_json()['code'] == 'command_outcome_unknown'
        again = w.post(LIVE, 'retry_while_the_readback_still_fails_unknown', live_url(d), body)
        assert again.get_json()['command_id'] == unknown.get_json()['command_id']
        w.mp.setattr(battle_api, 'public', real)
        listed = active_battle(w, 'read_after_the_unknown_lists_the_key').get_json()['battle']['commands']
        assert [c['request_keys'] for c in listed] == [['unk-1']]
        replay = w.post(LIVE, 'identical_retry_answered_from_the_record_once_the_readback_works', live_url(d), body)
        assert replay.status_code == 200 and len(recorded_commands(d)) == 1
    with gen.world('rcl_not_recorded_read') as w:
        # a refused change leaves no command: the battle read after a 409 lists none (settles "nothing was recorded")
        d = Driver(w).go_live()
        assert live(w, 'stale_control_revision_refused_for_the_read', d, {'routines.ad_gems.enabled': False}, 'nr-1', expected_revision=5).status_code == 409
        nothing = active_battle(w, 'read_after_a_refusal_lists_no_command').get_json()['battle']
        assert nothing['commands'] == []


