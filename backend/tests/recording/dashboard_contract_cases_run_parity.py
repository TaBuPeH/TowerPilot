"""Contract cases of the run settings the legacy Runs page had and the recordings did not reach (roadmap r12c, request (c); F6-11 RL9, RL12, RL13).

ONE new family of dashboard_contract_pages_v1.json, `run_entry_patch_parity`, generated by the real route (POST /api/profile-patch on ['blueprints', <run>, <field>])
over the synthetic world of run_entry_patch. The published run_entry_patch keeps its bytes. Three groups, each the way the legacy page wrote the field (`setBp`: a value, or
`op: "delete"` when the field is cleared):

  label     a run's label (R-25 / RL9): set, DELETED so the run identifier shows again, deleted when there is none, refused empty or not text, refused where it would
            repeat another run's name, and the delete that is refused because the identifier title-cased would;
  kind      a coin run switched to a dissonance run and back (R-26 / RL12): the dissonance IS the coin run's `dissonant_tab` (set, retargeted, deleted, null); the
            `kind` field itself is refused (r12d: before it, a coin run that kept no coin-only field could be saved as a tournament run; the legacy page never wrote it);
  limits    `rides` of an Ultimate Weapon grant quest and `cycles` of a cycle quest (R-30 / RL13): saved, deleted, refused, and the fields the other kinds must not carry.
"""
import copy

from dashboard_contract_cases_profile import PATCH_URL
from dashboard_contract_cases_run_leftovers import entry_world, source

PARITY = 'run_entry_patch_parity'


def patch(w, case, run, fields, revision, *, value=None, delete=False, name='mine'):
    """One field of one run, the way the Runs page sends it: {name, path:['blueprints', run, *fields], value | op:'delete', expected_revision}."""
    body = dict(name=name, path=['blueprints', run, *fields], expected_revision=revision)
    if delete:
        body['op'] = 'delete'
    else:
        body['value'] = value
    return w.post(PARITY, case, PATCH_URL, body)


class Saves:
    """The revision a chain of saves is at: an accepted save moves it on, a refusal leaves it where it was (and must not have moved the profile)."""

    def __init__(self, w):
        self.w, self.revision = w, source(w)['revision']

    def ok(self, case, run, fields, **kw):
        reply = patch(self.w, case, run, fields, self.revision, **kw)
        assert reply.status_code == 200 and reply.get_json()['ok'], (case, reply.status_code, reply.get_json())
        self.revision = reply.get_json()['revision']
        return reply.get_json()

    def refused(self, case, run, fields, status=400, **kw):
        reply = patch(self.w, case, run, fields, self.revision, **kw)
        assert reply.status_code == status and reply.get_json()['ok'] is False and reply.get_json()['error'], (case, reply.status_code, reply.get_json())
        assert source(self.w)['revision'] == self.revision, (case, 'a refused patch changed the saved profile')
        return reply.get_json()

    def answer(self, case, run, fields, **kw):
        """A request whose answer is the point (whatever the route says): the revision follows when it was accepted."""
        reply = patch(self.w, case, run, fields, self.revision, **kw)
        body = reply.get_json()
        if reply.status_code == 200:
            self.revision = body['revision']
        else:
            assert source(self.w)['revision'] == self.revision, (case, 'a refused patch changed the saved profile')
        return reply.status_code, body


def label_runs(profile):
    """Two runs for the label cases: `farm_two` is labelled 'Second farm', so the identifier `second_farm` (title-cased: 'Second Farm') is a name that is taken as long
    as `second_farm` has a label of its own to hide behind."""
    template = copy.deepcopy(profile['blueprints']['farm_deep'])
    profile['blueprints']['farm_two'] = dict(copy.deepcopy(template), label='Second farm')
    profile['blueprints']['second_farm'] = dict(copy.deepcopy(template), label='Zed')


def quest_runs(profile):
    """A grant quest and a cycle quest, valid for the world's account (it does not own Smart Missiles)."""
    profile['blueprints']['quest_sm'] = {'kind': 'uw_grant_quest', 'loadout': 'plain', 'tier': 1, 'grant_targets': ['smart_missiles'], 'rides': 2,
                                         'reroll_at_wave': 1000, 'ride_to_wave': 6500}
    profile['blueprints']['quest_ilm'] = {'kind': 'cycle_quest', 'loadout': 'plain', 'tier': 1, 'cycle_sec': 25, 'cycles': 40}


def run_entry_patch_parity_cases(gen):
    with gen.world('rpp_label') as w:
        entry_world(w, profile_change=label_runs)
        saves = Saves(w)
        before = source(w, PARITY, 'read_before_the_label_edits')['profile']['blueprints']
        assert 'label' not in before['farm'] and before['farm_two']['label'] == 'Second farm'
        status, body = saves.answer('label_delete_when_the_run_has_no_label', 'farm', ['label'], delete=True)
        assert status == 200 and 'label' not in body['profile']['blueprints']['farm'], (status, body)          # nothing to remove: accepted, the profile is as it was
        saves.ok('saved_label', 'farm', ['label'], value='Daily coin farm')
        saves.ok('label_deleted_the_run_id_shows', 'farm', ['label'], delete=True)
        after = source(w, PARITY, 'read_after_the_label_was_deleted')
        assert 'label' not in after['profile']['blueprints']['farm'] and after['revision'] == saves.revision, after['profile']['blueprints']['farm']
        saves.refused('label_empty_text_refused', 'farm', ['label'], value='')
        saves.refused('label_only_spaces_refused', 'farm', ['label'], value='   ')
        saves.refused('label_not_text_refused', 'farm', ['label'], value=5)
        saves.refused('label_the_same_as_another_runs_identifier_title_cased_refused', 'farm', ['label'], value='Farm Deep')
        saves.refused('label_the_same_as_another_runs_label_refused', 'farm', ['label'], value=' second  FARM ')
        saves.refused('label_delete_refused_the_identifier_title_cased_is_another_runs_label', 'second_farm', ['label'], delete=True)
        source(w, PARITY, 'read_after_the_label_refusals_nothing_changed')
    with gen.world('rpp_kind') as w:
        entry_world(w)
        saves = Saves(w)
        source(w, PARITY, 'read_before_the_kind_switches')
        saves.ok('coin_run_switched_to_dissonance', 'farm', ['dissonant_tab'], value='attack')
        switched = source(w, PARITY, 'read_after_the_switch_to_dissonance')
        assert switched['profile']['blueprints']['farm']['dissonant_tab'] == 'attack' and switched['profile']['blueprints']['farm']['kind'] == 'coin'
        saves.ok('dissonance_run_retargeted_to_another_tab', 'farm', ['dissonant_tab'], value='defense')
        saves.ok('dissonance_run_switched_back_to_coin_by_deleting_the_tab', 'farm', ['dissonant_tab'], delete=True)
        back = source(w, PARITY, 'read_after_the_switch_back_to_coin')
        assert 'dissonant_tab' not in back['profile']['blueprints']['farm'] and back['revision'] == saves.revision
        saves.ok('coin_run_switched_to_dissonance_again', 'farm', ['dissonant_tab'], value='utility')
        # a value of null WITHOUT op:"delete" is stored as null (the key stays): the page deletes, it does not send this
        saves.ok('dissonant_tab_set_to_null_is_stored_as_null_not_deleted', 'farm', ['dissonant_tab'], value=None)
        held = source(w, PARITY, 'read_after_the_tab_was_set_to_null')['profile']['blueprints']['farm']
        assert 'dissonant_tab' in held and held['dissonant_tab'] is None, held
        for case, value in (('dissonant_tab_text_not_a_tab', 'sideways'), ('dissonant_tab_empty_text', ''), ('dissonant_tab_a_list', ['defense']), ('dissonant_tab_a_number', 3)):
            saves.refused(case + '_refused', 'farm', ['dissonant_tab'], value=value)
        saves.ok('dissonant_tab_ultimate_weapons_accepted', 'farm', ['dissonant_tab'], value='ultimate_weapons')
        saves.ok('dissonance_run_switched_back_to_coin_the_last_time', 'farm', ['dissonant_tab'], delete=True)
        # the `kind` field itself (the legacy page never writes it): refused here by the equipment the coin run keeps, and for an unknown kind
        asis = saves.refused('kind_changed_from_coin_to_tournament_refused_by_the_equipment', 'farm', ['kind'], value='tournament')
        assert 'as_is' in asis['error'] or any('as_is' in p for p in asis['problems']), asis['problems']
        saves.refused('kind_changed_to_dissonance_which_is_not_a_kind_refused', 'farm', ['kind'], value='dissonance')
        # ... and, for a coin run that carries no coin-only field (which the validator alone would have accepted), by the route's own guard (r12d):
        # 400 kind_change_refused, nothing written; the run stays editable (the saved tier below), and the run_kind_guard family records the rest
        guarded = saves.refused('kind_changed_on_a_coin_run_that_keeps_no_coin_only_field_is_refused', 'farm_deep', ['kind'], value='tournament')
        assert guarded['code'] == 'kind_change_refused' and guarded['changes'] == [dict(blueprint='farm_deep', from_kind='coin', to_kind='tournament')], guarded
        saves.ok('saved_tier_of_the_run_whose_kind_change_was_refused', 'farm_deep', ['tier'], value=15)
        read = source(w, PARITY, 'read_after_the_kind_attempts')
        assert read['profile']['blueprints']['farm_deep']['kind'] == 'coin' and read['profile']['blueprints']['farm_deep']['tier'] == 15
        assert read['profile']['blueprints']['farm']['kind'] == 'coin'
    with gen.world('rpp_limits') as w:
        entry_world(w, profile_change=quest_runs)
        saves = Saves(w)
        base = source(w, PARITY, 'read_before_the_limit_edits')
        assert base['problems'] == [] and base['profile']['blueprints']['quest_sm']['rides'] == 2 and base['profile']['blueprints']['quest_ilm']['cycles'] == 40, base['problems']
        for case, run, field, value in (('saved_rides', 'quest_sm', 'rides', 3), ('saved_rides_one', 'quest_sm', 'rides', 1), ('saved_cycles', 'quest_ilm', 'cycles', 5),
                                        ('saved_cycles_one', 'quest_ilm', 'cycles', 1)):
            saves.ok(case, run, [field], value=value)
        saves.ok('rides_deleted_the_quest_uses_its_own_default', 'quest_sm', ['rides'], delete=True)           # rides is optional ...
        required = saves.refused('cycles_deleted_refused_a_cycle_quest_needs_its_cycles', 'quest_ilm', ['cycles'], delete=True)       # ... cycles is required
        assert 'required' in required['error']
        held = source(w, PARITY, 'read_after_the_limit_saves')['profile']['blueprints']
        assert 'rides' not in held['quest_sm'] and held['quest_ilm']['cycles'] == 1, held
        for case, run, field, value in (('rides_zero', 'quest_sm', 'rides', 0), ('rides_negative', 'quest_sm', 'rides', -1), ('rides_fraction', 'quest_sm', 'rides', 2.5),
                                        ('rides_text', 'quest_sm', 'rides', '3'), ('cycles_zero', 'quest_ilm', 'cycles', 0), ('cycles_fraction', 'quest_ilm', 'cycles', 1.5),
                                        ('cycles_text', 'quest_ilm', 'cycles', '5'), ('rides_on_a_coin_run', 'farm', 'rides', 3), ('cycles_on_a_coin_run', 'farm', 'cycles', 3),
                                        ('cycles_on_a_grant_quest_run', 'quest_sm', 'cycles', 3), ('rides_on_a_cycle_quest_run', 'quest_ilm', 'rides', 3),
                                        ('count_on_a_grant_quest_run_names_rides', 'quest_sm', 'count', 3), ('count_on_a_cycle_quest_run_names_cycles', 'quest_ilm', 'count', 3)):
            saves.refused(f'{case}_refused', run, [field], value=value)
        source(w, PARITY, 'read_after_the_limit_refusals_nothing_changed')
