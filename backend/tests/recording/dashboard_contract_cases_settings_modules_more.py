"""Contract cases of the typed settings modules that settings_modules did not record (roadmap r12e / F6-15, compliance C-03: the Emulators, Runtime and Equipment recordings).

ONE new family of dashboard_contract_pages_v1.json, `settings_modules_more`, generated by the real routes (GET and POST /api/settings, GET /api/config, POST /api/loadout-patch) over
the worlds of settings_modules: alpha on `main` / fake:1 with the account `alpha`, beta on `other`, the presets normal_run, coin_farm and the placeholder `later`. The published
families are not touched: a read the page needs "just before" a published save is recorded here under the brief's name, in a world that reaches the same bytes (the guard
test in test_dashboard_contract_pages.py compares the revisions with the published request).

  Emulators   (instance-defaults)  read_before_saved_instance_defaults; the machine fallback (the empty preset) with autostart off, saved from the state the published save leaves, and
                                   read back; a hand-edited preset the options do not offer: the read, the form that sends it back (refused), a save without the field (kept), a listed choice.
  Runtime     (machine defaults)   run-defaults, loop-defaults, missions-defaults and fleet-defaults saved while the selected emulator carries an override that differs from the machine
                                   default: read before, save, read after (the override is byte-identical); run-defaults with a stored preset that is not offered, and with no runnable preset;
                                   a placeholder preset (`defined: false`), the empty value on run-defaults, and no `presets` at all.
  Equipment   (tournament-cards)   both lists empty, saved from the state the published save leaves (account-bound), read back, saved again; one list emptied; no account bound;
                                   plus the two GET /api/config reads the loadout restore cases need: before saved_modules_restore, and before the clearing refusal.

What the routes do (read from the source, then recorded):
  * the machine defaults edit cfg[ident]; the emulator's module shows cfg[ident] with instances.<selected>[ident] laid over it key by key (control/settings_catalog.py, `overridable`).
    run-defaults is cfg.preset; the emulator's own default preset (instance-defaults, instances.<selected>.preset) comes first and is not touched by it.
  * an enum field offers exactly the options of the catalogue: run-defaults the runnable presets (every preset except a `defined: false` placeholder), instance-defaults the same plus
    the empty value "Use machine fallback". `validate` refuses any other value, whatever its type, with `<label>: expected enum`; the whole request is validated before anything is
    written, and only the fields the request names are validated (a stored value that is no longer offered stays until a request names it).
  * with no runnable preset run-defaults offers an empty list: even the value it shows is refused. instance-defaults still offers the empty value.
  * tournament-cards stores the two string lists as sent, [] included; with an account bound to the selected emulator they are the ACCOUNT's, otherwise the root block. A save that
    changes nothing is 200 with the same revision, and config.yaml is byte-identical afterwards.
"""
import copy

from dashboard_contract_cases_context import page_context
from dashboard_contract_cases_editors import LOADOUT_URL, LOADOUTS, config_of, equipped
from dashboard_contract_cases_settings import URL, module_of, save, snapshot, submit
from dashboard_contract_cases_settings_modules import furnished, slug, stored, without_backup
from dashboard_contract_pages_world import populate

SMM = 'settings_modules_more'

# the machine's own blocks, and the selected emulator's override of each (partial on purpose: a key the override does not carry follows the default)
DEFAULTS = {'loop': {'fps': 2.5, 'dry_run': False}, 'missions': {'visit_delay_sec': [60, 600]}, 'fleet': {'hold_window': 100, 'post_window': 150}}
OVERRIDES = {'loop': {'fps': 5}, 'missions': {'visit_delay_sec': [30, 45]}, 'fleet': {'hold_window': 80}}
OVERRIDE_PRESET, NEW_PRESET = 'coin_farm', 'shard_run'        # the emulator's own default preset, and the machine fallback the page saves over it (a third runnable preset, so the two differ)
# module, what the page saves, and what the SELECTED EMULATOR's module shows afterwards (its override, and the new default for a key the override does not carry)
SAVES = [('run-defaults', {'preset': NEW_PRESET}, None),
         ('loop-defaults', {'fps': 3.5, 'dry_run': True}, {'fps': 5, 'dry_run': True}),
         ('missions-defaults', {'visit_delay_sec': [90, 450]}, {'visit_delay_sec': [30, 45]}),
         ('fleet-defaults', {'hold_window': 120, 'post_window': 175}, {'hold_window': 80, 'post_window': 175})]
RUN_REFUSAL, INSTANCE_REFUSAL = 'Fallback preset: expected enum', 'Default preset: expected enum'
EMPTY = {'drop': [], 'add': []}
# what the published settings_modules family saves, in its order (copied: the guard test compares the revisions, so a drift fails there)
PUBLISHED_INSTANCE = {'label': 'Tower one', 'autostart': True}                        # + preset: the first runnable preset
PUBLISHED_TOURNEY = {'drop': ['cash', 'extra_orb'], 'add': ['golden_orb']}


def fields(snap, module):
    return {f['key']: f['value'] for f in module_of(snap, module)['fields']}


def offered(snap, module):
    return [o['value'] for o in next(f for f in module_of(snap, module)['fields'] if f['key'] == 'preset')['options']]


def config_bytes(w):
    return (w.root / 'config.yaml').read_bytes()


def quietly(w, module, values):
    """A save the page made before the case starts (not recorded: settings_modules recorded it, or the case is what follows it): 200, and the snapshot it answered."""
    snap = snapshot(w)
    reply = w.plain_post(URL, dict(context=snap['context'], revision=snap['revision'], module=module, values=values))
    assert reply.status_code == 200, (module, values, reply.get_json())
    return reply.get_json()


def published_saves(w, through):
    """The first `through` saves of settings_modules' set_mod_defaults world (instance-defaults, run-defaults, tournament-cards), unrecorded: the state the page is in
    when it reads the settings again, byte for byte."""
    snap = snapshot(w)
    runnable = offered(snap, 'run-defaults')
    current = fields(snap, 'run-defaults')['preset']
    steps = [('instance-defaults', dict(PUBLISHED_INSTANCE, preset=runnable[0])), ('run-defaults', {'preset': next(name for name in runnable if name != current)}),
             ('tournament-cards', copy.deepcopy(PUBLISHED_TOURNEY))]
    reply = None
    for module, values in steps[:through]:
        reply = quietly(w, module, values)
    return reply


def refused(w, case, snap, module, values, message, family=SMM):
    """One save the route refuses: 400 {ok:false, error}, config.yaml byte-identical."""
    before = config_bytes(w)
    reply = submit(w, case, snap, module, values, expect=400, family=family).get_json()
    assert reply == {'ok': False, 'error': message}, (case, reply)
    assert config_bytes(w) == before, (case, 'a refused save wrote config.yaml')
    return reply


def read_after(w, case, reply, family=SMM):
    read = snapshot(w, case, family)
    assert read == without_backup(reply), case
    return read


# ------------------------------------------------------------------------------------------------ Emulators: instance-defaults
def emulator_cases(gen):
    with gen.world('set_more_emulators') as w:
        furnished(w)
        before = snapshot(w, 'read_before_saved_instance_defaults', SMM)
        assert fields(before, 'instance-defaults') == {'label': 'Alpha tower', 'preset': '', 'autostart': False}, fields(before, 'instance-defaults')
        first = published_saves(w, 1)                                  # the published saved_instance_defaults: label Tower one, the first runnable preset, autostart on
        assert fields(first, 'instance-defaults') == {'label': 'Tower one', 'preset': offered(before, 'run-defaults')[0], 'autostart': True}
        values = {'preset': '', 'autostart': False}                    # what the page sends for "use the machine fallback" with autostart switched off
        reply = save(w, 'saved_instance_defaults_with_fallback_and_autostart_off', first, 'instance-defaults', values, SMM)
        assert fields(reply, 'instance-defaults') == {'label': 'Tower one', 'preset': '', 'autostart': False}, fields(reply, 'instance-defaults')
        main = stored(w)['instances']['main']
        assert (main['label'], main['preset'], main['autostart']) == ('Tower one', '', False)          # the fallback is stored as the empty string, autostart as an explicit false
        assert 'preset' not in stored(w)['instances']['other'] and stored(w)['preset'] == 'normal_run'
        read_after(w, 'read_after_saved_instance_defaults_with_fallback_and_autostart_off', reply)
    with gen.world('set_more_unlisted_instance') as w:                 # the emulator's preset was hand-edited to a name the catalogue does not offer
        furnished(w)
        w.edit_config(lambda cfg: cfg['instances']['main'].update(preset='ghost'))
        snap = snapshot(w, 'read_with_an_unlisted_saved_instance_defaults_preset', SMM)
        assert fields(snap, 'instance-defaults')['preset'] == 'ghost' and 'ghost' not in offered(snap, 'instance-defaults') and offered(snap, 'instance-defaults')[0] == ''
        refused(w, 'instance_defaults_form_sent_with_the_unlisted_preset_is_refused', snap, 'instance-defaults', {'label': 'Tower', 'preset': 'ghost', 'autostart': True}, INSTANCE_REFUSAL)
        assert snapshot(w, 'read_after_the_refused_unlisted_instance_preset_nothing_changed', SMM) == snap
        partial = save(w, 'instance_defaults_saved_without_the_preset_field_keeps_the_unlisted_preset', snap, 'instance-defaults', {'label': 'Tower', 'autostart': True}, SMM)
        assert fields(partial, 'instance-defaults') == {'label': 'Tower', 'preset': 'ghost', 'autostart': True} and stored(w)['instances']['main']['preset'] == 'ghost'
        read_after(w, 'read_after_the_partial_instance_save_the_unlisted_preset_remains', partial)
        chosen = save(w, 'instance_defaults_choosing_the_machine_fallback_replaces_the_unlisted_preset', partial, 'instance-defaults', {'preset': ''}, SMM)
        assert fields(chosen, 'instance-defaults')['preset'] == '' and stored(w)['instances']['main']['preset'] == ''
        read_after(w, 'read_after_the_unlisted_instance_preset_was_replaced', chosen)


# ------------------------------------------------------------------------------------------------ Runtime: the machine defaults
def overridden(cfg):
    cfg.update(copy.deepcopy(DEFAULTS))
    cfg['presets'][NEW_PRESET] = {'label': 'Shard Run'}
    cfg['instances']['main'].update(copy.deepcopy(OVERRIDES), preset=OVERRIDE_PRESET)


def override_cases(gen):
    with gen.world('set_more_overrides') as w:
        furnished(w)
        w.edit_config(overridden)
        start = stored(w)
        assert start['instances']['main']['loop'] == OVERRIDES['loop'] and start['loop'] == DEFAULTS['loop'] and start['preset'] == 'normal_run' and 'loop' not in start['instances']['other']
        snap = snapshot(w)
        assert fields(snap, 'instance-defaults')['preset'] == OVERRIDE_PRESET != fields(snap, 'run-defaults')['preset']
        for ident in DEFAULTS:                                          # the emulator's module shows its override, the defaults module the machine's own value
            assert fields(snap, ident) != fields(snap, ident + '-defaults'), ident
        for module, values, effective in SAVES:
            ident = module[:-len('-defaults')]
            kept = copy.deepcopy(stored(w)['instances'])
            snap = snapshot(w, f'read_before_saved_{slug(module)}_with_overrides', SMM)
            reply = save(w, f'saved_{slug(module)}_with_overrides', snap, module, values, SMM)
            assert fields(reply, module) == values, module                                  # the machine default is what was sent
            if effective is None:
                assert fields(reply, 'instance-defaults')['preset'] == OVERRIDE_PRESET and stored(w)['preset'] == NEW_PRESET      # the emulator's own preset still comes first
            else:
                assert fields(reply, ident) == effective, (ident, fields(reply, ident))     # the emulator's module: its override, and the new default for a key it does not carry
                assert stored(w)[ident] == values, module
            assert stored(w)['instances'] == kept, (module, 'the emulator\'s override changed')     # the override, and the other emulator, are byte-identical
            read_after(w, f'read_after_saved_{slug(module)}_with_overrides', reply)
        final = stored(w)
        assert {ident: final[ident] for ident in DEFAULTS} == {'loop': SAVES[1][1], 'missions': SAVES[2][1], 'fleet': SAVES[3][1]} and final['preset'] == NEW_PRESET
        assert final['instances']['main']['loop'] == OVERRIDES['loop'] and final['instances']['main']['fleet'] == OVERRIDES['fleet'] and final['instances']['main']['preset'] == OVERRIDE_PRESET


# ------------------------------------------------------------------------------------------------ Runtime: a preset the options list does not offer
def preset_cases(gen):
    with gen.world('set_more_placeholder') as w:                      # normal_run, coin_farm are offered; `later` is a placeholder (defined: false)
        furnished(w)
        snap = snapshot(w, 'read_with_a_placeholder_preset_in_the_configuration', SMM)
        assert offered(snap, 'run-defaults') == ['coin_farm', 'normal_run'] and offered(snap, 'instance-defaults') == ['', 'coin_farm', 'normal_run']
        refused(w, 'run_defaults_with_a_placeholder_preset_is_refused', snap, 'run-defaults', {'preset': 'later'}, RUN_REFUSAL)
        refused(w, 'run_defaults_with_the_empty_value_is_refused', snap, 'run-defaults', {'preset': ''}, RUN_REFUSAL)
        refused(w, 'instance_defaults_with_a_placeholder_preset_is_refused', snap, 'instance-defaults', {'preset': 'later'}, INSTANCE_REFUSAL)
        refused(w, 'instance_defaults_with_a_placeholder_and_a_valid_label_writes_neither', snap, 'instance-defaults', {'label': 'Tower', 'preset': 'later'}, INSTANCE_REFUSAL)
        assert snapshot(w, 'read_after_the_refused_preset_saves_nothing_changed', SMM) == snap
    with gen.world('set_more_unlisted_run') as w:                      # config.preset was hand-edited to a name the catalogue does not offer
        furnished(w)
        w.edit_config(lambda cfg: cfg.update(preset='ghost'))
        snap = snapshot(w, 'read_with_an_unlisted_saved_run_defaults_preset', SMM)
        assert fields(snap, 'run-defaults') == {'preset': 'ghost'} and 'ghost' not in offered(snap, 'run-defaults')
        refused(w, 'run_defaults_saving_back_the_unlisted_preset_is_refused', snap, 'run-defaults', {'preset': 'ghost'}, RUN_REFUSAL)
        assert snapshot(w, 'read_after_the_refused_unlisted_run_preset_nothing_changed', SMM) == snap
        listed = save(w, 'run_defaults_choosing_a_listed_preset_replaces_the_unlisted_one', snap, 'run-defaults', {'preset': 'coin_farm'}, SMM)
        assert fields(listed, 'run-defaults') == {'preset': 'coin_farm'} and stored(w)['preset'] == 'coin_farm'
        read_after(w, 'read_after_the_unlisted_run_preset_was_replaced', listed)
    with gen.world('set_more_no_runnable_preset') as w:                # every preset is a placeholder: the options list is empty
        furnished(w)
        w.edit_config(lambda cfg: cfg.__setitem__('presets', {'later': {'defined': False}}))
        snap = snapshot(w, 'read_with_no_runnable_run_defaults_preset_options', SMM)
        assert offered(snap, 'run-defaults') == [] and offered(snap, 'instance-defaults') == [''] and fields(snap, 'run-defaults') == {'preset': 'normal_run'}
        refused(w, 'run_defaults_with_no_runnable_preset_refuses_the_value_it_shows', snap, 'run-defaults', {'preset': 'normal_run'}, RUN_REFUSAL)
        refused(w, 'run_defaults_with_no_runnable_preset_refuses_the_empty_value', snap, 'run-defaults', {'preset': ''}, RUN_REFUSAL)
        refused(w, 'instance_defaults_with_no_runnable_preset_refuses_a_named_preset', snap, 'instance-defaults', {'preset': 'normal_run'}, INSTANCE_REFUSAL)
        assert snapshot(w, 'read_after_the_empty_options_refusals_nothing_changed', SMM) == snap
        kept = save(w, 'instance_defaults_with_no_runnable_preset_still_saves_the_empty_value', snap, 'instance-defaults', {'preset': ''}, SMM)
        assert fields(kept, 'instance-defaults')['preset'] == '' and offered(kept, 'instance-defaults') == [''] and stored(w)['instances']['main']['preset'] == ''
        read_after(w, 'read_after_the_empty_value_was_saved_with_no_runnable_preset', kept)
    with gen.world('set_more_no_presets') as w:                        # the configuration names no preset at all
        furnished(w)
        w.edit_config(lambda cfg: cfg.pop('presets', None))
        assert 'presets' not in stored(w)
        snap = snapshot(w, 'read_with_no_presets_in_the_configuration_the_options_are_empty', SMM)
        assert offered(snap, 'run-defaults') == [] and offered(snap, 'instance-defaults') == ['']
        refused(w, 'run_defaults_with_no_presets_in_the_configuration_is_refused', snap, 'run-defaults', {'preset': 'normal_run'}, RUN_REFUSAL)


# ------------------------------------------------------------------------------------------------ Equipment: empty tournament lists, and two config reads
def tournament_cases(gen):
    with gen.world('set_more_tourney_bound') as w:                     # alpha is bound to main: the lists are the account's; the root block is the legacy default
        furnished(w)
        published = published_saves(w, 3)                              # the published saved_tournament_cards has been made: drop cash, extra_orb; add golden_orb
        before = stored(w)
        snap = snapshot(w, 'read_before_saved_tournament_cards_empty_lists', SMM)
        assert snap == without_backup(published) and fields(snap, 'tournament-cards') == PUBLISHED_TOURNEY
        reply = save(w, 'saved_tournament_cards_empty_lists', snap, 'tournament-cards', EMPTY, SMM)
        assert fields(reply, 'tournament-cards') == EMPTY
        after = stored(w)
        assert after['accounts']['alpha']['tourney_card_tweaks'] == EMPTY and after['accounts']['beta'] == before['accounts']['beta'], after['accounts']
        assert after['tourney_card_tweaks'] == before['tourney_card_tweaks'] == {'drop': ['legacy_drop'], 'add': []}      # the legacy default is not the account's
        bytes_after = config_bytes(w)
        read = read_after(w, 'read_after_saved_tournament_cards_empty_lists', reply)
        config = w.get(SMM, 'config_read_after_saved_tournament_cards_empty_lists', '/api/config').get_json()
        assert config['tourney_card_tweaks'] == EMPTY, config['tourney_card_tweaks']
        again = submit(w, 'saved_the_same_empty_lists_again_keeps_the_revision', read, 'tournament-cards', EMPTY, expect=200, family=SMM).get_json()
        assert again['ok'] and again['revision'] == read['revision'] and fields(again, 'tournament-cards') == EMPTY
        assert config_bytes(w) == bytes_after and stored(w) == after
    with gen.world('set_more_tourney_partial') as w:
        furnished(w)
        published_saves(w, 3)
        snap = snapshot(w, 'read_before_only_the_drop_list_is_emptied', SMM)
        reply = save(w, 'saved_tournament_cards_with_only_the_drop_list_empty_the_add_list_is_kept', snap, 'tournament-cards', {'drop': []}, SMM)
        assert fields(reply, 'tournament-cards') == {'drop': [], 'add': ['golden_orb']}
        assert stored(w)['accounts']['alpha']['tourney_card_tweaks'] == {'drop': [], 'add': ['golden_orb']}
        read_after(w, 'read_after_only_the_drop_list_was_emptied', reply)
        quietly(w, 'tournament-cards', copy.deepcopy(PUBLISHED_TOURNEY))               # the page put the lists back
        snap = snapshot(w, 'read_before_only_the_add_list_is_emptied', SMM)
        last = save(w, 'saved_tournament_cards_with_only_the_add_list_empty_the_drop_list_is_kept', snap, 'tournament-cards', {'add': []}, SMM)
        assert fields(last, 'tournament-cards') == {'drop': ['cash', 'extra_orb'], 'add': []}
        read_after(w, 'read_after_only_the_add_list_was_emptied', last)
    with gen.world('set_more_tourney_unbound') as w:                   # no account is bound to the selected emulator: the root block is the lists
        populate(w, config=lambda cfg: cfg.__setitem__('tourney_card_tweaks', {'drop': ['legacy_drop'], 'add': ['legacy_add']}))
        assert stored(w).get('accounts') is None
        snap = snapshot(w, 'read_before_the_unbound_tournament_lists_are_emptied', SMM)
        assert snap['context']['account'] is None and fields(snap, 'tournament-cards') == {'drop': ['legacy_drop'], 'add': ['legacy_add']}
        reply = save(w, 'saved_tournament_cards_empty_lists_and_no_account', snap, 'tournament-cards', EMPTY, SMM)
        assert fields(reply, 'tournament-cards') == EMPTY and stored(w)['tourney_card_tweaks'] == EMPTY and stored(w).get('accounts') is None
        read_after(w, 'read_after_the_unbound_tournament_lists_were_emptied', reply)


def restore(w, name, body, revision, context):
    return w.plain_post(LOADOUT_URL, dict(name=name, body=body, expected_revision=revision, expected_context=context))


def restore_read_cases(gen):
    """GET /api/config in the state the loadout restore cases of the published families start from; the request that follows is replayed unrecorded, to prove the read admits it."""
    with gen.world('set_more_restore_modules') as w:                   # loadout_restore: the cards restore has been saved, the modules restore is next
        equipped(w)
        context = page_context(w)
        cards = {'cards': 'main_farm', 'cards_restore': 'no_card'}
        first = restore(w, 'plain', cards, config_of(w)['config_revision'], context)
        assert first.status_code == 200, first.get_json()
        read = w.get(SMM, 'read_before_saved_modules_restore', '/api/config').get_json()
        assert read['loadouts']['plain'] == cards and read['config_revision'] == first.get_json()['config_revision']
        modules = dict(cards, modules=[['amplifying_strike', 'primary']], modules_restore=[['black_hole_digestor', 'assist']])
        saved = restore(w, 'plain', modules, read['config_revision'], context)
        assert saved.status_code == 200 and saved.get_json()['loadouts']['plain'] == modules, saved.get_json()
    with gen.world('set_more_restore_clearing') as w:                  # loadout_restore_eligibility: a loadout no run uses holds a restore value stored before the guard
        equipped(w, loadouts=dict(LOADOUTS, spare={'cards': 'no_card', 'cards_restore': 'ghost_deck'}))
        context = page_context(w)
        kept = restore(w, 'spare', {'cards': 'main_farm', 'cards_restore': 'ghost_deck'}, config_of(w)['config_revision'], context)
        assert kept.status_code == 200, kept.get_json()
        read = w.get(SMM, 'read_before_the_clearing_refusal', '/api/config').get_json()
        assert read['loadouts']['spare'] == {'cards': 'main_farm', 'cards_restore': 'ghost_deck'} and read['config_revision'] == kept.get_json()['config_revision']
        refusal = restore(w, 'spare', {'cards': 'main_farm'}, read['config_revision'], context)
        assert refusal.status_code == 409 and refusal.get_json()['code'] == 'restore_loadout_unused', refusal.get_json()
        assert config_of(w)['config_revision'] == read['config_revision']


def settings_modules_more_cases(gen):
    emulator_cases(gen)
    override_cases(gen)
    preset_cases(gen)
    tournament_cases(gen)
    restore_read_cases(gen)
