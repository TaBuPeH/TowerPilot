def refused(w, case, template, run_id, options, code, guard, *, name='mine', status=400, problems=None, body=None):
    reply = add(w, case, template, run_id, options, name=name, body=body, family=CODED, **guard)
    got = reply.get_json()
    assert reply.status_code == status and got['ok'] is False and got['code'] == code and got['error'], (case, reply.status_code, got)
    if problems is not None:
        assert bool(got.get('problems')) is problems, (case, got)
    return got


def own_revision(w, name):
    """The revision of that profile file as /api/profile-src would publish it: the SHA-256 of its bytes."""
    return hashlib.sha256((w.root / 'profiles' / f'{name}.yaml').read_bytes()).hexdigest()


def run_templates_add_coded_cases(gen):
    with gen.world('rtc_refusals') as w:
        fenced_world(w)
        revision, context = source(w, CODED, 'read_before_any_add')['revision'], alpha(w)
        both = dict(expected_revision=revision, expected_context=context)
        for case, template, run_id, options, code in REFUSALS:
            refused(w, case, template, run_id, options, code, both, problems=code == 'validation_failed')
        assert source(w)['revision'] == revision, 'a refused add changed the saved profile'
        source(w, CODED, 'read_after_the_refusals_nothing_changed')
        only_revision, only_context = dict(expected_revision=revision), dict(expected_context=context)
        refused(w, 'id_taken_with_only_the_revision', 'farm', 'farm', {}, 'id_taken', only_revision)
        refused(w, 'id_taken_with_only_the_context', 'farm', 'farm', {}, 'id_taken', only_context)
        refused(w, 'recipe_refused_with_only_the_revision', 'ghost', 'new_run', {}, 'recipe_refused', only_revision)
        refused(w, 'recipe_refused_with_only_the_context', 'ghost', 'new_run', {}, 'recipe_refused', only_context)
        refused(w, 'validation_failed_with_only_the_revision', 'farm', 'new_run', {'tier': 0}, 'validation_failed', only_revision, problems=True)
        refused(w, 'validation_failed_with_only_the_context', 'farm', 'new_run', {'tier': 0}, 'validation_failed', only_context, problems=True)
        # the guards keep their own codes and their place: the revision and the context are judged before the recipe
        stale = add(w, 'stale_revision_with_a_bad_recipe_is_revision_conflict_not_recipe_refused', 'ghost', 'Not A Valid Id', {'speed': 1}, family=CODED,
                    expected_revision='0' * 64, expected_context=context)
        assert stale.status_code == 409 and stale.get_json()['code'] == 'revision_conflict', stale.get_json()
        assert source(w)['revision'] == revision
    with gen.world('rtc_policy_taken') as w:
        def policy_exists(profile):
            profile['policies']['gather']['pre__all_on'] = copy.deepcopy(profile['policies']['gather']['all_on'])
        fenced_world(w)
        w.edit_profile(policy_exists)
        revision, context = source(w)['revision'], alpha(w)
        got = refused(w, 'id_taken_a_copied_policy_exists', 'farm', 'pre', {'label': 'Pre run'}, 'id_taken', dict(expected_revision=revision, expected_context=context))
        assert 'already exists' in got['error'] and source(w)['revision'] == revision
        source(w, CODED, 'read_after_the_policy_clash_nothing_changed')
    with gen.world('rtc_profile') as w:
        fenced_world(w)
        profile = source(w)['profile']
        revision, context = source(w)['revision'], alpha(w)
        write_profile(w, 'default', profile)
        write_profile(w, 'mine.draft', {'player': {}})
        write_profile(w, 'broken', 'blueprints: [unclosed\n')
        write_profile(w, 'list', '- a\n')
        write_profile(w, 'empty', '')
        (w.root / 'profiles' / 'latin.yaml').write_bytes(b'label: caf\xe9\n')
        both = dict(expected_revision=revision, expected_context=context)
        refused(w, 'profile_unavailable_the_starter', 'farm', 'new_run', {}, 'profile_unavailable', dict(both, expected_revision='any'), name='default', status=409)
        refused(w, 'profile_unavailable_a_scan_draft', 'farm', 'new_run', {}, 'profile_unavailable', dict(both, expected_revision='any'), name='mine.draft', status=409)
        refused(w, 'profile_unavailable_no_such_profile', 'farm', 'new_run', {}, 'profile_unavailable', both, name='ghost')
        refused(w, 'profile_unavailable_no_such_profile_with_only_the_context', 'farm', 'new_run', {}, 'profile_unavailable', dict(expected_context=context), name='ghost')
        for case, name in (('file_that_is_not_yaml', 'broken'), ('file_that_is_a_list', 'list'), ('empty_file', 'empty'), ('file_that_is_not_utf8', 'latin')):
            # the revision guard is the file's own (a different one would be a revision_conflict, judged first): the file is read, then it cannot be used
            refused(w, f'profile_unavailable_{case}', 'farm', 'new_run', {}, 'profile_unavailable', dict(both, expected_revision=own_revision(w, name)), name=name)
        refused(w, 'profile_unavailable_name_with_a_path', None, None, None, 'profile_unavailable', both,
                body=dict(profile='../outside', template='farm', run_id='new_run', **both))
        refused(w, 'profile_unavailable_name_not_text', None, None, None, 'profile_unavailable', both, body=dict(profile=5, template='farm', run_id='new_run', **both))
        refused(w, 'profile_unavailable_name_missing', None, None, None, 'profile_unavailable', both, body=dict(template='farm', run_id='new_run', **both))
        assert source(w)['revision'] == revision
        source(w, CODED, 'read_after_the_profile_refusals_nothing_changed')
    with gen.world('rtc_write') as w:
        fenced_world(w)
        revision, context = source(w)['revision'], alpha(w)
        both = dict(expected_revision=revision, expected_context=context)
        real = w.dash._save_yaml_backup
        w.mp.setattr(w.dash, '_save_yaml_backup', raising(OSError('profiles/mine.yaml could not be written')))
        got = refused(w, 'write_failed_nothing_saved', 'farm', 'fresh_one', {'label': 'Fresh one'}, 'write_failed_nothing_saved', both)
        assert got['error'] == 'profiles/mine.yaml could not be written' and source(w)['revision'] == revision
        refused(w, 'write_failed_nothing_saved_with_only_the_context', 'farm', 'fresh_one', {'label': 'Fresh one'}, 'write_failed_nothing_saved', dict(expected_context=context))
        source(w, CODED, 'read_after_the_failed_write_the_revision_is_unchanged')

        def written_then_failed(path, data):
            real(path, data)
            raise OSError('the answer could not be built after the file was written')
        w.mp.setattr(w.dash, '_save_yaml_backup', written_then_failed)
        unknown = add(w, 'written_then_the_answer_failed_has_no_code', 'farm', 'half_run', {'label': 'Half run'}, family=CODED, expect=400, **both).get_json()
        assert unknown['ok'] is False and 'code' not in unknown, unknown
        w.mp.setattr(w.dash, '_save_yaml_backup', real)
        held = source(w, CODED, 'read_after_an_error_that_followed_the_write_holds_the_run')
        assert held['revision'] != revision and 'half_run' in held['profile']['blueprints']
        resend = add(w, 'identical_resend_after_the_error_is_revision_conflict', 'farm', 'half_run', {'label': 'Half run'}, family=CODED, expect=409, **both).get_json()
        assert resend['code'] == 'revision_conflict'
        context_only = refused(w, 'identical_resend_with_only_the_context_is_id_taken', 'farm', 'half_run', {'label': 'Half run'}, 'id_taken', dict(expected_context=context))
        assert 'already exists' in context_only['error']
        accepted = add(w, 'added_with_both_guards_has_no_code', 'farm', 'good_run', {'label': 'Good run'}, family=CODED, expect=200,
                       expected_revision=held['revision'], expected_context=context).get_json()
        assert accepted['ok'] is True and 'code' not in accepted and accepted['revision'] != held['revision']
    with gen.world('rtc_unguarded') as w:
        fenced_world(w)
        assert 'code' not in add(w, 'unguarded_id_taken_has_no_code', 'farm', 'farm', {}, family=CODED, expect=400).get_json()
        assert 'code' not in add(w, 'unguarded_recipe_refused_has_no_code', 'ghost', 'new_run', {}, family=CODED, expect=400).get_json()
        assert 'code' not in add(w, 'unguarded_validation_failed_has_no_code', 'farm', 'new_run', {'tier': 0}, family=CODED, expect=400).get_json()
        assert 'code' not in add(w, 'unguarded_unknown_profile_has_no_code', 'farm', 'new_run', {}, name='ghost', family=CODED, expect=400).get_json()
        assert 'code' not in add(w, 'unguarded_body_not_an_object_has_no_code', None, None, body=[1], family=CODED, expect=400).get_json()
        w.mp.setattr(w.dash, '_save_yaml_backup', raising(OSError('profiles/mine.yaml could not be written')))
        assert 'code' not in add(w, 'unguarded_write_failed_has_no_code', 'farm', 'fresh_one', {'label': 'Fresh one'}, family=CODED, expect=400).get_json()
