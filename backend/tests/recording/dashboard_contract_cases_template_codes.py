    ('recipe_refused_identifier_with_a_capital', 'farm', 'Farm_Two', {}, 'recipe_refused'),
    ('recipe_refused_identifier_with_a_space', 'farm', 'farm two', {}, 'recipe_refused'),
    ('recipe_refused_identifier_starting_with_a_digit', 'farm', '2farm', {}, 'recipe_refused'),
    ('recipe_refused_identifier_empty', 'farm', '', {}, 'recipe_refused'),
