"""Contract cases of the stable refusal codes of POST /api/run-templates/add (roadmap r12c, request (a) of the F6-11 part 2 review).

ONE new family of dashboard_contract_pages_v1.json, `run_templates_add_coded`, generated by the real route over the synthetic world of the other Runs
families. A request that names a guard (`expected_revision` and/or `expected_context`) now gets a stable `code` on every refusal the route can prove
happened before anything was written, so the page can show it as Refused instead of Unknown:

  id_taken                    400  the run identifier, or a policy that identifier would create, exists already
  recipe_refused              400  the recipe or the choices were refused (not an identifier, unknown template, unsupported or malformed choice)
  validation_failed           400  the profile validator refused the result (the answer keeps `problems`)
  profile_unavailable         400/409  no such profile, unreadable, not a mapping, the starter or a scan draft
  write_failed_nothing_saved  400  the write raised AND the profile file is byte-identical to what it was before the attempt

A failure after which the file differs (or cannot be read back) has NO code - `written_then_the_answer_failed` shows it - and a request without a guard
is answered exactly as before, without a code (the `unguarded_*` cases; the published families run_templates_add and the older cases of
run_templates_add_fenced are the same requests). revision_conflict, context_changed and invalid_request are the guards' own codes, unchanged.
"""
